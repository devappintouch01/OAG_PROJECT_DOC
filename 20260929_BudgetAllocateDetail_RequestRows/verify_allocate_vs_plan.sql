-- ตรวจรายการหน้า พ.ร.บ. (BudgetAllocateDetail) เทียบหน้าแผนการใช้จ่าย (BudgetPlanExpenseDetail) — ฟอร์ม 1
-- 1 แถว = 1 รายการ (ปี + Category + ผลผลิต + กิจกรรม) ทั้งสองหน้า
--
-- ALLOC = แถวรายการหน้า พ.ร.บ. — OAGWBG_V_BUDGETALLOCATEITEM เงื่อนไขเดียวกับ GetBudgetAllocateItemsGroupByPlanId
--         นับเฉพาะรายการที่ยืนยันแล้ว (C) และงบ พ.ร.บ. (จัดสรร + แปรญัตติ) <> 0 ให้ตรงกับที่หน้าแผนแสดง
-- PLAN  = แถวหน้าแผนการใช้จ่าย — OAGWBG_V_BUDGETDISBURSEMENTPLANITEMPIVOT เงื่อนไขเดียวกับ GetBudgetDisbursementPlanGroupByPlanId
--         (view กรอง BUDGETSTATUS = 'C' อยู่แล้ว, หน้าจอกรอง TOTALALLOCATESUMMARYAMOUNT <> 0)
--
-- เปลี่ยนปีที่ :budget_year (ทั้ง 2 จุด) ก่อนรัน
-- ผลที่ถูกต้อง: ONLY_IN_ALLOC = 0, ONLY_IN_PLAN = 0, AMOUNT_DIFF = 0
-- =====================================================================

-- (1) สรุปจำนวน
WITH ALLOC AS (
    SELECT x.BUDGETYEAR,
           TO_CHAR(x.PRODUCTID) AS PRODUCTID,
           TO_CHAR(x.ACTIVITYCODEID) AS ACTIVITYID,
           x.CATEGORY_ID AS CATEGORYID,
           MAX(x.CATEGORY_NAME) AS CATEGORYNAME,
           -- view แปะยอด type 6/5 ของรายการซ้ำทุกแถวคำขอ จึงใช้ MAX ไม่ใช่ SUM
           MAX(NVL(x.TOTALALLOCATEAMOUNT, 0)) + MAX(NVL(x.TOTALADJUSTEDAMOUNT, 0)) AS APPROVED,
           MIN(x.BUDGETSTATUS) AS MIN_STATUS,
           MAX(x.BUDGETSTATUS) AS MAX_STATUS
      FROM OAGWBG_V_BUDGETALLOCATEITEM x
     WHERE x.BUDGETYEAR = 2569 /* :budget_year */
       AND x.BUDGETFORMTYPEID = 1
       AND (x.TOTALREQUESTSIMMARYAMOUNT <> 0 OR x.BUDGETREQUESTID = 0)
       AND (x.PARENTID IS NOT NULL OR NOT EXISTS (
               SELECT 1 FROM OAGWBG_V_BUDGETALLOCATEITEM c
                WHERE c.BUDGETYEAR = x.BUDGETYEAR AND c.PARENTID IS NOT NULL AND c.PARENTID = x.BUDGETREQUESTID))
     GROUP BY x.BUDGETYEAR, TO_CHAR(x.PRODUCTID), TO_CHAR(x.ACTIVITYCODEID), x.CATEGORY_ID
),
ALLOC_C AS (
    SELECT * FROM ALLOC WHERE MAX_STATUS = 'C' AND APPROVED <> 0
),
PLAN AS (
    SELECT p.BUDGETYEAR, p.PRODUCT_ID AS PRODUCTID, p.ACTIVITY_ID AS ACTIVITYID, p.CATEGORYID,
           MAX(p.NAME) AS CATEGORYNAME,
           MAX(p.TOTALALLOCATESUMMARYAMOUNT) AS APPROVED,
           SUM(NVL(p.TOTALPLANAMOUNT, 0)) AS PLANNED,
           COUNT(*) AS N_ROWS
      FROM OAGWBG_V_BUDGETDISBURSEMENTPLANITEMPIVOT p
     WHERE p.BUDGETYEAR = 2569 /* :budget_year */
       AND p.BUDGETFORMTYPEID = 1
       AND p.TOTALALLOCATESUMMARYAMOUNT <> 0
     GROUP BY p.BUDGETYEAR, p.PRODUCT_ID, p.ACTIVITY_ID, p.CATEGORYID
),
CMP AS (
    SELECT COALESCE(a.PRODUCTID, p.PRODUCTID) AS PRODUCTID,
           COALESCE(a.ACTIVITYID, p.ACTIVITYID) AS ACTIVITYID,
           COALESCE(a.CATEGORYID, p.CATEGORYID) AS CATEGORYID,
           COALESCE(a.CATEGORYNAME, p.CATEGORYNAME) AS CATEGORYNAME,
           a.APPROVED AS ALLOC_APPROVED,
           p.APPROVED AS PLAN_APPROVED,
           p.PLANNED  AS PLAN_PLANNED,
           p.N_ROWS   AS PLAN_ROWS,
           CASE WHEN a.CATEGORYID IS NULL THEN 'ONLY_IN_PLAN'
                WHEN p.CATEGORYID IS NULL THEN 'ONLY_IN_ALLOC'
                WHEN a.APPROVED <> p.APPROVED THEN 'AMOUNT_DIFF'
                WHEN p.N_ROWS > 1 THEN 'DUP_IN_PLAN'
                ELSE 'OK' END AS RESULT
      FROM ALLOC_C a
      FULL OUTER JOIN PLAN p
        ON p.PRODUCTID = a.PRODUCTID AND p.ACTIVITYID = a.ACTIVITYID AND p.CATEGORYID = a.CATEGORYID
)
SELECT (SELECT COUNT(*) FROM ALLOC)   AS ALLOC_ITEMS_ALL,
       (SELECT COUNT(*) FROM ALLOC_C) AS ALLOC_ITEMS_CONFIRMED,
       (SELECT COUNT(*) FROM PLAN)    AS PLAN_ITEMS,
       s.*
  FROM (SELECT SUM(CASE WHEN RESULT = 'OK' THEN 1 ELSE 0 END)            AS OK,
               SUM(CASE WHEN RESULT = 'ONLY_IN_ALLOC' THEN 1 ELSE 0 END) AS ONLY_IN_ALLOC,
               SUM(CASE WHEN RESULT = 'ONLY_IN_PLAN' THEN 1 ELSE 0 END)  AS ONLY_IN_PLAN,
               SUM(CASE WHEN RESULT = 'AMOUNT_DIFF' THEN 1 ELSE 0 END)   AS AMOUNT_DIFF,
               SUM(CASE WHEN RESULT = 'DUP_IN_PLAN' THEN 1 ELSE 0 END)   AS DUP_IN_PLAN
          FROM CMP) s
/

-- (2) รายการที่ไม่ตรง (ใช้ CTE ชุดเดียวกับ (1) — ถ้าข้อ (1) ตรงหมด ข้อนี้จะไม่มีแถว)
WITH ALLOC AS (
    SELECT x.BUDGETYEAR, TO_CHAR(x.PRODUCTID) AS PRODUCTID, TO_CHAR(x.ACTIVITYCODEID) AS ACTIVITYID, x.CATEGORY_ID AS CATEGORYID,
           MAX(x.CATEGORY_NAME) AS CATEGORYNAME,
           MAX(NVL(x.TOTALALLOCATEAMOUNT, 0)) + MAX(NVL(x.TOTALADJUSTEDAMOUNT, 0)) AS APPROVED,
           MAX(x.BUDGETSTATUS) AS MAX_STATUS
      FROM OAGWBG_V_BUDGETALLOCATEITEM x
     WHERE x.BUDGETYEAR = 2569 /* :budget_year */
       AND x.BUDGETFORMTYPEID = 1
       AND (x.TOTALREQUESTSIMMARYAMOUNT <> 0 OR x.BUDGETREQUESTID = 0)
       AND (x.PARENTID IS NOT NULL OR NOT EXISTS (
               SELECT 1 FROM OAGWBG_V_BUDGETALLOCATEITEM c
                WHERE c.BUDGETYEAR = x.BUDGETYEAR AND c.PARENTID IS NOT NULL AND c.PARENTID = x.BUDGETREQUESTID))
     GROUP BY x.BUDGETYEAR, TO_CHAR(x.PRODUCTID), TO_CHAR(x.ACTIVITYCODEID), x.CATEGORY_ID
),
ALLOC_C AS (SELECT * FROM ALLOC WHERE MAX_STATUS = 'C' AND APPROVED <> 0),
PLAN AS (
    SELECT p.PRODUCT_ID AS PRODUCTID, p.ACTIVITY_ID AS ACTIVITYID, p.CATEGORYID, MAX(p.NAME) AS CATEGORYNAME,
           MAX(p.TOTALALLOCATESUMMARYAMOUNT) AS APPROVED, COUNT(*) AS N_ROWS
      FROM OAGWBG_V_BUDGETDISBURSEMENTPLANITEMPIVOT p
     WHERE p.BUDGETYEAR = 2569 /* :budget_year */ AND p.BUDGETFORMTYPEID = 1 AND p.TOTALALLOCATESUMMARYAMOUNT <> 0
     GROUP BY p.PRODUCT_ID, p.ACTIVITY_ID, p.CATEGORYID
)
SELECT COALESCE(a.PRODUCTID, p.PRODUCTID) AS PRODUCTID,
       COALESCE(a.ACTIVITYID, p.ACTIVITYID) AS ACTIVITYID,
       COALESCE(a.CATEGORYID, p.CATEGORYID) AS CATEGORYID,
       COALESCE(a.CATEGORYNAME, p.CATEGORYNAME) AS CATEGORYNAME,
       a.APPROVED AS ALLOC_APPROVED, p.APPROVED AS PLAN_APPROVED, p.N_ROWS AS PLAN_ROWS,
       CASE WHEN a.CATEGORYID IS NULL THEN 'ONLY_IN_PLAN'
            WHEN p.CATEGORYID IS NULL THEN 'ONLY_IN_ALLOC'
            WHEN a.APPROVED <> p.APPROVED THEN 'AMOUNT_DIFF'
            ELSE 'DUP_IN_PLAN' END AS RESULT
  FROM ALLOC_C a
  FULL OUTER JOIN PLAN p
    ON p.PRODUCTID = a.PRODUCTID AND p.ACTIVITYID = a.ACTIVITYID AND p.CATEGORYID = a.CATEGORYID
 WHERE a.CATEGORYID IS NULL OR p.CATEGORYID IS NULL OR a.APPROVED <> p.APPROVED OR p.N_ROWS > 1
 ORDER BY 1, 2, 3
