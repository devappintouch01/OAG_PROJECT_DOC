-- =====================================================================
-- ตัวอย่างปี 2569: 1 รายการ (Category 2228 / ผลผลิต 21000 / กิจกรรม 21100) ที่มี 3 คำขอ
-- ไล่ทีละขั้น คำขอ → จัดสรร พ.ร.บ. → Interface GL → แผนรายเดือน → รับเงินรายงวด
-- SELECT อย่างเดียว — เปลี่ยนรายการได้ที่ค่า 2228 / 21000 / 21100 (ทุกขั้น)
-- =====================================================================

-- ขั้น A: คำขอ (record ระดับคำขอ) ที่ถูกรวมอยู่ในรายการนี้
SELECT g.ID AS BUDGETGOVERNMENTID, g.BUDGETREQUESTID, g.COSTCENTERID, cc.NAME AS COSTCENTERNAME,
       g.BUDGETDETAIL, v.TOTALREQUESTSIMMARYAMOUNT AS REQUEST_AMOUNT, g.BUDGETSTATUS
  FROM OAGWBG_BUDGETGOVERNMENT g
  LEFT JOIN OAGWBG_V_EXT_OAGGL_COST_CENTER_V cc ON cc.ID = g.COSTCENTERID
  LEFT JOIN OAGWBG_V_BUDGETALLOCATEITEM v ON v.BUDGET_GOVERNMENT_ID = g.ID
 WHERE g.BUDGETYEAR = 2569 AND g.BUDGETFORMTYPEID = 1
   AND g.CATEGORYID = 2228 AND g.PRODUCTID = 21000 AND g.ACTIVITYCODEID = 21100
   AND g.BUDGETGOVERNMENTTYPE IS NULL AND NVL(g.BUDGETREQUESTID,0) <> 0
   AND g.BUDGETSTATUS = 'C'
   -- ตัดคำขอแม่ที่มีคำขอลูก (ปรับปรุงคำขอ) ออก — เงื่อนไขเดียวกับหน้า พ.ร.บ./แผน
   AND NOT EXISTS (SELECT 1 FROM OAGWBG_BUDGETREQUEST br WHERE br.PARENTID IS NOT NULL AND br.PARENTID = g.BUDGETREQUESTID)
 ORDER BY g.COSTCENTERID;

-- ขั้น B: ยอดจัดสรร พ.ร.บ. (type 6/5/8) และรหัสงบประมาณ — ก้อนเดียวต่อรายการ
SELECT g.ID, g.BUDGETGOVERNMENTTYPE AS TYPE, g.BUDGETREQUESTID,
       g.TOTALALLOCATEAMOUNT, g.TOTALADJUSTEDAMOUNT, g.TOTALREQUESTADJUSTAMOUNT, g.BUDGETSTATUS,
       (SELECT b.BUDGETCODEID FROM OAGWBG_BUDGETCODE_YEAR b
         WHERE b.BUDGETYEAR = 2569 AND b.CATEGORYID = 2228 AND b.PRODUCTID = 21000 AND b.ACTIVITYCODEID = 21100
           AND ROWNUM = 1) AS BUDGETCODEID
  FROM OAGWBG_BUDGETGOVERNMENT g
 WHERE g.BUDGETYEAR = 2569 AND g.BUDGETFORMTYPEID = 1
   AND g.CATEGORYID = 2228 AND g.PRODUCTID = 21000 AND g.ACTIVITYCODEID = 21100
   AND g.BUDGETGOVERNMENTTYPE IN ('5', '6', '8')
 ORDER BY g.BUDGETGOVERNMENTTYPE;

-- ขั้น C: Interface GL ของ พ.ร.บ. (batch ที่สำเร็จ) — line ของรายการนี้
--   จับด้วยยอด = type 6 + type 5 ของรายการ และ Segment9 = รหัสงบประมาณของรายการ
SELECT l.WEB_BATCH_NO, l.LINE_NUMBER, l.SEGMENT5, l.SEGMENT8, l.SEGMENT9, l.SEGMENT10, l.SEGMENT11,
       l.ENTERED_DR, l.STATUS
  FROM OAGWBG_LOG_INTERFACE l
 WHERE l.WEB_BATCH_NO LIKE 'BUDGET_ACT_2569%' AND l.STATUS = 'S'
   AND l.SEGMENT9 = (SELECT b.BUDGETCODEID FROM OAGWBG_BUDGETCODE_YEAR b
                      WHERE b.BUDGETYEAR = 2569 AND b.CATEGORYID = 2228 AND b.PRODUCTID = 21000 AND b.ACTIVITYCODEID = 21100
                        AND ROWNUM = 1)
   -- รหัสงบประมาณใช้ร่วมหลายรายการ จึงกรองด้วยยอด = type 6 + type 5 ของรายการด้วย
   AND l.ENTERED_DR = (SELECT SUM(NVL(TOTALALLOCATEAMOUNT,0)) + SUM(NVL(TOTALADJUSTEDAMOUNT,0))
                         FROM OAGWBG_BUDGETGOVERNMENT
                        WHERE BUDGETYEAR = 2569 AND BUDGETFORMTYPEID = 1 AND BUDGETGOVERNMENTTYPE IN ('5', '6')
                          AND CATEGORYID = 2228 AND PRODUCTID = 21000 AND ACTIVITYCODEID = 21100)
 ORDER BY l.WEB_BATCH_NO, l.LINE_NUMBER;

-- ขั้น D: แผนรายเดือนระดับรายการ (ตารางนี้ไม่มีคอลัมน์ระบุคำขอ)
SELECT p.MONTH, p.ADDEDAMOUNT, p.BUDGETDISBURSEMENTPLANID
  FROM OAGWBG_BUDGETDISBURSEMENTPLANRECEIVE p
 WHERE p.BUDGETYEAR = 2569 AND p.CATEGORYID = 2228 AND p.PRODUCTID = 21000 AND p.ACTIVITYID = 21100
 ORDER BY CASE WHEN p.MONTH >= 10 THEN p.MONTH - 12 ELSE p.MONTH END;

-- ขั้น D.1: แผนรายเดือนรายคำขอ (1 record ต่อคำขอต่อเดือน) — ดูว่ายอดแผนไปอยู่ที่คำขอไหน
SELECT i.MONTH, g.ID AS BUDGETGOVERNMENTID, g.COSTCENTERID, i.COSTCENTERID AS PLAN_COSTCENTERID,
       NVL(i.ALLOCATEAMOUNT, 0) AS ALLOCATEAMOUNT
  FROM OAGWBG_BUDGETDISBURSEMENTPLANITEM i
  JOIN OAGWBG_BUDGETGOVERNMENT g ON g.ID = i.BUDGETGOVERNMENTID
 WHERE i.BUDGETYEAR = 2569 AND i.BUDGETFORMTYPEID = 1
   AND g.CATEGORYID = 2228 AND g.PRODUCTID = 21000 AND g.ACTIVITYCODEID = 21100
   AND g.BUDGETGOVERNMENTTYPE IS NULL AND NVL(g.BUDGETREQUESTID,0) <> 0
   AND g.BUDGETSTATUS = 'C'
   -- ตัดคำขอแม่ที่มีคำขอลูก (ปรับปรุงคำขอ) ออก — เงื่อนไขเดียวกับหน้า พ.ร.บ./แผน
   AND NOT EXISTS (SELECT 1 FROM OAGWBG_BUDGETREQUEST br WHERE br.PARENTID IS NOT NULL AND br.PARENTID = g.BUDGETREQUESTID)
 ORDER BY CASE WHEN i.MONTH >= 10 THEN i.MONTH - 12 ELSE i.MONTH END, g.COSTCENTERID;

-- ขั้น E: รับเงินรายงวด — แถวของรายการนี้แต่ละงวด
SELECT r.PERIOD, r.ROUNDNO, c.ID, c.BUDGETGOVERNMENTID, c.COSTCENTERID,
       c.TOTALALLOCATEAMOUNT, c.TOTALRECEIVEAMOUNT, c.STATUSID
  FROM OAGWBG_BUDGETRECEIVEPERIODCATEGORY c
  JOIN OAGWBG_BUDGETRECEIVEPERIOD r ON r.ID = c.BUDGETRECEIVEPERIODID
 WHERE c.BUDGETYEAR = 2569 AND c.CATEGORYID = 2228 AND c.PRODUCTID = 21000 AND c.ACTIVITYID = 21100
 ORDER BY r.PERIOD;
