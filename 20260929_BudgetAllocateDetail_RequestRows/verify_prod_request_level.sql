-- ตรวจบน PROD ว่าแต่ละขั้นของโฟลว พ.ร.บ. → GL → แผนการใช้จ่าย → รับเงินรายงวด
-- เก็บ/ส่งเป็น "รายการ" (Category+ผลผลิต+กิจกรรม) หรือ "รายคำขอ"
-- SELECT อย่างเดียว ไม่แก้ข้อมูล — รันทีละขั้น เปลี่ยนปีที่ 2569 ได้ตามต้องการ
-- ผล PREPROD ปี 2569 (2026-09-29) ใส่ไว้ท้ายแต่ละขั้นเพื่อเทียบ
-- =====================================================================

-- ขั้น 0: มีข้อมูลปีไหนบ้าง (จำนวน record คำขอ / record จัดสรร type 6)
SELECT BUDGETYEAR,
       SUM(CASE WHEN BUDGETGOVERNMENTTYPE IS NULL AND NVL(BUDGETREQUESTID,0) <> 0 THEN 1 ELSE 0 END) AS N_REQUEST_RECORDS,
       SUM(CASE WHEN BUDGETGOVERNMENTTYPE = '6' THEN 1 ELSE 0 END) AS N_TYPE6,
       MIN(CREATEON) AS FIRST_CREATE, MAX(UPDATEON) AS LAST_UPDATE
  FROM OAGWBG_BUDGETGOVERNMENT
 WHERE BUDGETFORMTYPEID = 1
 GROUP BY BUDGETYEAR
 ORDER BY BUDGETYEAR;


-- ขั้น 1: ยอดจัดสรร พ.ร.บ. (type 6) เก็บกี่ record ต่อรายการ
--   N_TYPE6 = N_KEYS  → 1 record ต่อรายการ (ไม่แยกรายคำขอ)
--   N_TYPE6 > N_KEYS  → มีรายการที่เก็บหลาย record (อาจแยกรายคำขอ) ดูขั้น 1.1
--   PREPROD 2569: 549 / 549 / 321
SELECT BUDGETYEAR,
       COUNT(*) AS N_TYPE6,
       COUNT(DISTINCT CATEGORYID || '|' || PRODUCTID || '|' || ACTIVITYCODEID) AS N_KEYS,
       SUM(CASE WHEN NVL(TOTALALLOCATEAMOUNT,0) <> 0 THEN 1 ELSE 0 END) AS N_NONZERO,
       SUM(CASE WHEN NVL(BUDGETREQUESTID,0) <> 0 THEN 1 ELSE 0 END) AS N_WITH_REQUESTID
  FROM OAGWBG_BUDGETGOVERNMENT
 WHERE BUDGETFORMTYPEID = 1 AND BUDGETGOVERNMENTTYPE = '6' AND BUDGETYEAR = 2569
 GROUP BY BUDGETYEAR;

-- ขั้น 1.1 (รันเมื่อขั้น 1 ได้ N_TYPE6 > N_KEYS): รายการที่มี type 6 มากกว่า 1 record
SELECT CATEGORYID, PRODUCTID, ACTIVITYCODEID, COUNT(*) AS N_RECORDS,
       SUM(NVL(TOTALALLOCATEAMOUNT,0)) AS SUM_ALLOC, MIN(CREATEON) AS FIRST_CREATE
  FROM OAGWBG_BUDGETGOVERNMENT
 WHERE BUDGETFORMTYPEID = 1 AND BUDGETGOVERNMENTTYPE = '6' AND BUDGETYEAR = 2569
 GROUP BY CATEGORYID, PRODUCTID, ACTIVITYCODEID
HAVING COUNT(*) > 1
 ORDER BY N_RECORDS DESC;


-- ขั้น 2: Interface GL ของ พ.ร.บ. — 1 line ต่อรายการ หรือรายคำขอ
--   batch ที่ STATUS = 'S' ถ้า LINES = จำนวนรายการที่มียอด (ขั้น 1 N_NONZERO) → ส่งรายการ
--   PREPROD 2569: batch S = 321 lines / 321 accounts
SELECT WEB_BATCH_NO,
       MIN(TO_CHAR(CREATEON, 'YYYY-MM-DD HH24:MI')) AS SENT_ON,
       COUNT(*) AS LINES,
       COUNT(DISTINCT SEGMENT5||'|'||SEGMENT6||'|'||SEGMENT7||'|'||SEGMENT8||'|'||SEGMENT9||'|'||SEGMENT10||'|'||SEGMENT11) AS DISTINCT_ACCOUNTS,
       SUM(ENTERED_DR) AS TOTAL_DR,
       MAX(STATUS) AS STATUS
  FROM OAGWBG_LOG_INTERFACE
 WHERE WEB_BATCH_NO LIKE 'BUDGET_ACT_2569%'
 GROUP BY WEB_BATCH_NO
 ORDER BY SENT_ON;


-- ขั้น 3: แผนการใช้จ่ายรายเดือน — กระจายยอดแผนให้หลายคำขอในรายการเดียวกันหรือไม่
--   N_GROUPS_PLANNED_MULTI > 0 → เคยวางแผนแยกรายคำขอ (ดูขั้น 3.1)
--   N_GROUPS_PLANNED_MULTI = 0 → ยอดแผนอยู่ที่คำขอเดียวต่อรายการ/เดือน (วางแผนระดับรายการ/หน่วยงาน)
--   PREPROD 2569: 3634 / 0 / 1752
SELECT COUNT(*) AS N_GROUPS_MULTI_REQUEST,
       SUM(CASE WHEN NZ > 1 THEN 1 ELSE 0 END) AS N_GROUPS_PLANNED_MULTI,
       SUM(CASE WHEN NZ = 1 THEN 1 ELSE 0 END) AS N_GROUPS_PLANNED_ONE
  FROM (SELECT i.BUDGETDISBURSEMENTPLANID, i.MONTH, g.CATEGORYID, g.PRODUCTID, g.ACTIVITYCODEID,
               COUNT(*) AS N,
               SUM(CASE WHEN NVL(i.ALLOCATEAMOUNT,0) <> 0 THEN 1 ELSE 0 END) AS NZ
          FROM OAGWBG_BUDGETDISBURSEMENTPLANITEM i
          JOIN OAGWBG_BUDGETGOVERNMENT g ON g.ID = i.BUDGETGOVERNMENTID
         WHERE i.BUDGETYEAR = 2569 AND i.BUDGETFORMTYPEID = 1 AND g.BUDGETSTATUS = 'C'
         GROUP BY i.BUDGETDISBURSEMENTPLANID, i.MONTH, g.CATEGORYID, g.PRODUCTID, g.ACTIVITYCODEID
        HAVING COUNT(*) > 1);

-- ขั้น 3.1 (รันเมื่อขั้น 3 ได้ N_GROUPS_PLANNED_MULTI > 0): ตัวอย่างรายการที่วางแผนแยกรายคำขอ
SELECT * FROM (
    SELECT g.CATEGORYID, g.PRODUCTID, g.ACTIVITYCODEID, i.MONTH,
           g.ID AS BUDGETGOVERNMENTID, g.BUDGETREQUESTID, g.COSTCENTERID, g.BUDGETDETAIL,
           i.ALLOCATEAMOUNT, i.UPDATEON,
           SUM(CASE WHEN NVL(i.ALLOCATEAMOUNT,0) <> 0 THEN 1 ELSE 0 END)
               OVER (PARTITION BY i.BUDGETDISBURSEMENTPLANID, i.MONTH, g.CATEGORYID, g.PRODUCTID, g.ACTIVITYCODEID) AS NZ_IN_GROUP
      FROM OAGWBG_BUDGETDISBURSEMENTPLANITEM i
      JOIN OAGWBG_BUDGETGOVERNMENT g ON g.ID = i.BUDGETGOVERNMENTID
     WHERE i.BUDGETYEAR = 2569 AND i.BUDGETFORMTYPEID = 1 AND g.BUDGETSTATUS = 'C'
) WHERE NZ_IN_GROUP > 1
 ORDER BY CATEGORYID, PRODUCTID, ACTIVITYCODEID, MONTH, BUDGETGOVERNMENTID
 FETCH FIRST 50 ROWS ONLY;


-- ขั้น 4: ยอดแผนรายเดือนระดับรายการ (ตารางที่หน้าแผน + รับเงินรายงวดใช้) — ตารางนี้ไม่มีคอลัมน์ระบุคำขอ
--   N_ROWS = N_KEYS → 1 แถวต่อรายการต่อเดือน
SELECT MONTH, COUNT(*) AS N_ROWS,
       COUNT(DISTINCT CATEGORYID || '|' || PRODUCTID || '|' || ACTIVITYID) AS N_KEYS,
       SUM(NVL(ADDEDAMOUNT,0)) AS TOTAL_ADDED
  FROM OAGWBG_BUDGETDISBURSEMENTPLANRECEIVE
 WHERE BUDGETYEAR = 2569 AND BUDGETFORMTYPEID = 1
 GROUP BY MONTH
 ORDER BY MONTH;


-- ขั้น 5: รับเงินรายงวด — 1 แถวต่อรายการ หรือรายคำขอ
--   N_ROWS ≈ N_ITEMS และ BG_IS_REQUEST = 0 → รับเงินระดับรายการ
--   PREPROD 2569 งวด 1: 347 / 321 / 321 / 2 / 0 / 0
SELECT r.PERIOD,
       COUNT(*) AS N_ROWS,
       COUNT(DISTINCT c.CATEGORYID || '|' || c.PRODUCTID || '|' || c.ACTIVITYID) AS N_ITEMS,
       COUNT(DISTINCT c.CATEGORYID || '|' || c.PRODUCTID || '|' || c.ACTIVITYID || '|' || c.COSTCENTERID) AS N_ITEM_COSTCENTER,
       COUNT(DISTINCT c.BUDGETGOVERNMENTID) AS N_BGID,
       SUM(CASE WHEN g.BUDGETGOVERNMENTTYPE = '6' THEN 1 ELSE 0 END) AS BG_IS_TYPE6,
       SUM(CASE WHEN NVL(g.BUDGETREQUESTID,0) <> 0 THEN 1 ELSE 0 END) AS BG_IS_REQUEST
  FROM OAGWBG_BUDGETRECEIVEPERIODCATEGORY c
  JOIN OAGWBG_BUDGETRECEIVEPERIOD r ON r.ID = c.BUDGETRECEIVEPERIODID
  LEFT JOIN OAGWBG_BUDGETGOVERNMENT g ON g.ID = c.BUDGETGOVERNMENTID
 WHERE c.BUDGETYEAR = 2569
 GROUP BY r.PERIOD
 ORDER BY r.PERIOD;


-- ขั้น 6 (ถ้าผู้ใช้ชี้รายการที่เคยแยกได้): ดูรายการเดียวครบทุกขั้น — แทน :CATEGORYID/:PRODUCTID/:ACTIVITYID
SELECT 'GOV' AS SRC, g.ID, g.BUDGETGOVERNMENTTYPE AS TYPE, g.BUDGETREQUESTID, g.COSTCENTERID, g.BUDGETDETAIL,
       g.TOTALALLOCATEAMOUNT AS AMOUNT, g.BUDGETSTATUS AS STATUS
  FROM OAGWBG_BUDGETGOVERNMENT g
 WHERE g.BUDGETYEAR = 2569 AND g.BUDGETFORMTYPEID = 1
   AND g.CATEGORYID = :CATEGORYID AND g.PRODUCTID = :PRODUCTID AND g.ACTIVITYCODEID = :ACTIVITYID
UNION ALL
SELECT 'RECEIVE', c.ID, TO_CHAR(r.PERIOD), NULL, c.COSTCENTERID, NULL, c.TOTALALLOCATEAMOUNT, TO_CHAR(c.STATUSID)
  FROM OAGWBG_BUDGETRECEIVEPERIODCATEGORY c JOIN OAGWBG_BUDGETRECEIVEPERIOD r ON r.ID = c.BUDGETRECEIVEPERIODID
 WHERE c.BUDGETYEAR = 2569 AND c.CATEGORYID = :CATEGORYID AND c.PRODUCTID = :PRODUCTID AND c.ACTIVITYID = :ACTIVITYID
 ORDER BY 1, 2;
