-- ปี 2569: ทุกรายการที่มีคำขอ >= 2 และมียอดจัดสรร — ไล่ทุกขั้นในแถวเดียว
-- N_REQ/N_CC      = จำนวนคำขอ/หน่วยงานที่ขอ (แยกจริงตอนขอ)
-- N_TYPE6/ALLOC   = record จัดสรร พ.ร.บ. และยอด (ถ้าแยกรายคำขอ N_TYPE6 จะ = N_REQ)
-- GL_LINES/GL_DR  = line ใน interface batch ที่สำเร็จ (batch ล่าสุดสถานะ S) ของรายการนี้
-- PLAN_SUM        = ยอดแผน 12 เดือน (PLANRECEIVE) / PLAN_BG = จำนวน record คำขอที่มียอดแผน
-- RCV_ROWS/RCV_SUM= แถวรับเงินรายงวด / ยอดรับรวม
-- SELECT อย่างเดียว
-- =====================================================================
WITH REQ AS (
  SELECT g.CATEGORYID, g.PRODUCTID, g.ACTIVITYCODEID, COUNT(*) N_REQ, COUNT(DISTINCT g.COSTCENTERID) N_CC
    FROM OAGWBG_BUDGETGOVERNMENT g
   WHERE g.BUDGETYEAR = 2569 AND g.BUDGETFORMTYPEID = 1 AND g.BUDGETGOVERNMENTTYPE IS NULL
     AND NVL(g.BUDGETREQUESTID,0) <> 0 AND g.BUDGETSTATUS = 'C'
     AND NOT EXISTS (SELECT 1 FROM OAGWBG_BUDGETREQUEST br WHERE br.PARENTID IS NOT NULL AND br.PARENTID = g.BUDGETREQUESTID)
   GROUP BY g.CATEGORYID, g.PRODUCTID, g.ACTIVITYCODEID),
T6 AS (
  SELECT CATEGORYID, PRODUCTID, ACTIVITYCODEID, COUNT(*) N_TYPE6, SUM(NVL(TOTALALLOCATEAMOUNT,0)) ALLOC
    FROM OAGWBG_BUDGETGOVERNMENT
   WHERE BUDGETYEAR = 2569 AND BUDGETFORMTYPEID = 1 AND BUDGETGOVERNMENTTYPE = '6'
   GROUP BY CATEGORYID, PRODUCTID, ACTIVITYCODEID),
T5 AS (
  SELECT CATEGORYID, PRODUCTID, ACTIVITYCODEID, SUM(NVL(TOTALADJUSTEDAMOUNT,0)) ADJ
    FROM OAGWBG_BUDGETGOVERNMENT
   WHERE BUDGETYEAR = 2569 AND BUDGETFORMTYPEID = 1 AND BUDGETGOVERNMENTTYPE = '5'
   GROUP BY CATEGORYID, PRODUCTID, ACTIVITYCODEID),
CODE AS (
  SELECT CATEGORYID, PRODUCTID, ACTIVITYCODEID, MAX(BUDGETCODEID) BUDGETCODEID
    FROM OAGWBG_BUDGETCODE_YEAR WHERE BUDGETYEAR = 2569 GROUP BY CATEGORYID, PRODUCTID, ACTIVITYCODEID),
GL AS (   -- batch สำเร็จล่าสุด
  SELECT * FROM OAGWBG_LOG_INTERFACE
   WHERE WEB_BATCH_NO = (SELECT MAX(WEB_BATCH_NO) FROM OAGWBG_LOG_INTERFACE
                          WHERE WEB_BATCH_NO LIKE 'BUDGET_ACT_2569%' AND STATUS = 'S'
                            AND WEB_BATCH_NO < 'BUDGET_ACT_2569_202602')),
PLN AS (
  SELECT CATEGORYID, PRODUCTID, ACTIVITYID, SUM(NVL(ADDEDAMOUNT,0)) PLAN_SUM, COUNT(*) PLAN_MONTHS
    FROM OAGWBG_BUDGETDISBURSEMENTPLANRECEIVE WHERE BUDGETYEAR = 2569 AND BUDGETFORMTYPEID = 1
   GROUP BY CATEGORYID, PRODUCTID, ACTIVITYID),
PLN_BG AS (
  SELECT g.CATEGORYID, g.PRODUCTID, g.ACTIVITYCODEID, COUNT(DISTINCT g.ID) PLAN_BG
    FROM OAGWBG_BUDGETDISBURSEMENTPLANITEM i JOIN OAGWBG_BUDGETGOVERNMENT g ON g.ID = i.BUDGETGOVERNMENTID
   WHERE i.BUDGETYEAR = 2569 AND i.BUDGETFORMTYPEID = 1 AND NVL(i.ALLOCATEAMOUNT,0) <> 0
   GROUP BY g.CATEGORYID, g.PRODUCTID, g.ACTIVITYCODEID),
RCV AS (
  SELECT CATEGORYID, PRODUCTID, ACTIVITYID, COUNT(*) RCV_ROWS, SUM(NVL(TOTALRECEIVEAMOUNT,0)) RCV_SUM
    FROM OAGWBG_BUDGETRECEIVEPERIODCATEGORY WHERE BUDGETYEAR = 2569
   GROUP BY CATEGORYID, PRODUCTID, ACTIVITYID)
SELECT r.CATEGORYID, r.PRODUCTID, r.ACTIVITYCODEID,
       (SELECT MAX(NAME) FROM OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V cc WHERE cc.ID = r.CATEGORYID) AS CATEGORYNAME,
       r.N_REQ, r.N_CC, t6.N_TYPE6, t6.ALLOC + NVL(t5.ADJ,0) AS APPROVED,
       (SELECT COUNT(*) FROM GL WHERE GL.SEGMENT9 = cd.BUDGETCODEID AND GL.ENTERED_DR = t6.ALLOC + NVL(t5.ADJ,0)) AS GL_LINES,
       p.PLAN_SUM, p.PLAN_MONTHS, NVL(pb.PLAN_BG,0) AS PLAN_BG,
       rc.RCV_ROWS, rc.RCV_SUM
  FROM REQ r
  JOIN T6 t6 ON t6.CATEGORYID = r.CATEGORYID AND t6.PRODUCTID = r.PRODUCTID AND t6.ACTIVITYCODEID = r.ACTIVITYCODEID
  LEFT JOIN T5 t5 ON t5.CATEGORYID = r.CATEGORYID AND t5.PRODUCTID = r.PRODUCTID AND t5.ACTIVITYCODEID = r.ACTIVITYCODEID
  LEFT JOIN CODE cd ON cd.CATEGORYID = r.CATEGORYID AND cd.PRODUCTID = r.PRODUCTID AND cd.ACTIVITYCODEID = r.ACTIVITYCODEID
  LEFT JOIN PLN p ON p.CATEGORYID = r.CATEGORYID AND p.PRODUCTID = r.PRODUCTID AND p.ACTIVITYID = r.ACTIVITYCODEID
  LEFT JOIN PLN_BG pb ON pb.CATEGORYID = r.CATEGORYID AND pb.PRODUCTID = r.PRODUCTID AND pb.ACTIVITYCODEID = r.ACTIVITYCODEID
  LEFT JOIN RCV rc ON rc.CATEGORYID = r.CATEGORYID AND rc.PRODUCTID = r.PRODUCTID AND rc.ACTIVITYID = r.ACTIVITYCODEID
 WHERE r.N_REQ >= 2 AND t6.ALLOC + NVL(t5.ADJ,0) > 0
 ORDER BY r.N_REQ DESC, APPROVED DESC
