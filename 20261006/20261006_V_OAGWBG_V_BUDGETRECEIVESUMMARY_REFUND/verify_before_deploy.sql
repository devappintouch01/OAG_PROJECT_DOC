SELECT BR.ID, BR.BUDGETRECEIVETYPE, BR.COSTCENTERID, BR.CATEGORYID, BR.PRODUCTID, BR.ACTIVITYID,
       PICK.ID AS MC_ID, PICK.ROWTYPE, PICK.COSTCENTERID AS MC_CC, PICK.CATEGORYID AS MC_CAT,
       PICK.PRODUCTID AS MC_PROD, PICK.ACTIVITYID AS MC_ACT, PICK.BUDGETCODEID AS MC_BCODE
  FROM OAGWBG_BUDGETRECEIVE BR
  JOIN OAGWBG_BUDGETALLOCATETRANSFERMORE_CATEGORY MO ON MO.ID = BR.BUDGETALLOCATETRANSFERMORECATEGORYID
  LEFT JOIN OAGWBG_BUDGETALLOCATETRANSFERMORE_CATEGORY MR ON MR.ID = MO.PARENTID
  LEFT JOIN OAGWBG_BUDGETALLOCATETRANSFERMORE_CATEGORY PICK
    ON PICK.ID = CASE WHEN BR.BUDGETRECEIVETYPE = 'G' THEN MO.ID ELSE MR.ID END
 WHERE BR.BUDGETRECEIVETYPE NOT IN ('A', 'G')
    OR PICK.ID IS NULL
    OR NVL(PICK.COSTCENTERID, '#') <> NVL(BR.COSTCENTERID, '#')
    OR NVL(TO_CHAR(PICK.CATEGORYID), '#') <> NVL(TO_CHAR(BR.CATEGORYID), '#')
    OR NVL(PICK.PRODUCTID, '#') <> NVL(BR.PRODUCTID, '#')
    OR NVL(PICK.ACTIVITYID, '#') <> NVL(BR.ACTIVITYID, '#')
 ORDER BY BR.ID;

