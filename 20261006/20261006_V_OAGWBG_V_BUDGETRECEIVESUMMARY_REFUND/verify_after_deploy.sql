-- รันหลัง deploy

-- (1) view ต้อง VALID
SELECT OBJECT_NAME, STATUS, LAST_DDL_TIME FROM USER_OBJECTS WHERE OBJECT_NAME = 'OAGWBG_V_BUDGETRECEIVESUMMARY_REFUND';

-- (2) ยอดรวมต้องเท่ากับแถว NEW ของ (1) ใน verify_before_deploy.sql
SELECT COUNT(*) AS N, SUM(TOTALBALANCEAMOUNT) AS BAL, SUM(TOTALRECEIVEAMOUNT) AS RCV,
       SUM(REFUNDAMOUNT) AS RF, COUNT(BUDGETCODEID) AS WITH_BCODE
  FROM OAGWBG.OAGWBG_V_BUDGETRECEIVESUMMARY_REFUND;

-- (3) แถวโอนจัดสรรเพิ่มเติมที่หาถังใน view ด้วยรหัสงบที่ควรได้ไม่เจอ — คาดหวัง: ผลว่าง
--     รหัสงบที่ควรได้: G → MORE_CATEGORY แถว 'O' / A → แถวแม่ 'R' (กฎเดียวกับ DDL)
SELECT BR.ID AS BUDGETRECEIVEID, BR.BUDGETRECEIVETYPE, BR.COSTCENTERID, BR.CATEGORYID, BR.TOTALBALANCEAMOUNT,
       DECODE(BR.BUDGETRECEIVETYPE, 'G', MO.BUDGETCODEID, 'A', MR.BUDGETCODEID) AS EXPECTED_BCODE
  FROM OAGWBG_BUDGETRECEIVE BR
  JOIN OAGWBG_BUDGETALLOCATETRANSFERMORE_CATEGORY MO ON MO.ID = BR.BUDGETALLOCATETRANSFERMORECATEGORYID
  LEFT JOIN OAGWBG_BUDGETALLOCATETRANSFERMORE_CATEGORY MR ON MR.ID = MO.PARENTID
 WHERE BR.BUDGETRECEIVETYPE IN ('A', 'G')
   AND NOT EXISTS (
         SELECT 1 FROM OAGWBG.OAGWBG_V_BUDGETRECEIVESUMMARY_REFUND V
          WHERE V.DEPARTMENTID   = BR.DEPARTMENTID
            AND V.COSTCENTERID   = BR.COSTCENTERID
            AND V.BUDGETYEAR     = BR.BUDGETYEAR
            AND V.BUDGETSOURCEID = NVL(BR.BUDGETSOURCEID, 100)
            AND V.CATEGORYID     = BR.CATEGORYID
            AND V.PRODUCTID      = BR.PRODUCTID
            AND V.ACTIVITYID     = BR.ACTIVITYID
            AND V.BUDGETCODEID   = DECODE(BR.BUDGETRECEIVETYPE, 'G', MO.BUDGETCODEID, 'A', MR.BUDGETCODEID)
       );

-- (4) เคสต้นเรื่อง (PREPROD): ค่าเช่าบ้าน cc 2906999999 ปี 2569 แหล่งเงิน 100
--     คาดหวัง PREPROD: ...027 = 90,784,219.36 / ...013 = -120,000 (ถังโอนเพิ่มเติม) / รหัสงบว่าง = 61,300 (แถว J)
SELECT ID, BUDGETCODEID, TOTALBALANCEAMOUNT
  FROM OAGWBG.OAGWBG_V_BUDGETRECEIVESUMMARY_REFUND
 WHERE DEPARTMENTID = '2900600000' AND COSTCENTERID = '2906999999'
   AND BUDGETYEAR = 2569 AND BUDGETSOURCEID = '100' AND CATEGORYID = 2186
 ORDER BY BUDGETCODEID NULLS LAST;
