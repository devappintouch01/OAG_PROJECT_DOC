-- ไล่ทีละโครงการว่าทำไมหน้า detail ยังไม่เลือก "รายการ" หลังแก้ ResolveLatestRefBudgetGovernmentId
-- แทน 464 ด้วย PROJECTID ที่ต้องการ

-- [A] แถวโครงการ → แถวแผนงานที่ REF ชี้ → คำขอของแถวนั้นมีลูก (เวอร์ชันใหม่) อะไรบ้าง
SELECT BG.ID AS BG_ID, BG.PROJECTID, BG.BUDGETREQUESTID AS PJ_REQ,
       BG.REF_BUDGETGOVERNMENTID AS REF_ID, BG.PRODUCTID, BG.ACTIVITYCODEID,
       O.BUDGETREQUESTID AS REF_REQ, O.RUNNING AS REF_RUNNING, O.CATEGORYTYPEID AS REF_CATTYPE,
       O.CATEGORYID AS REF_CATEGORYID, O.BUDGETYEAR AS REF_YEAR, O.CREATEON AS REF_CREATEON,
       (SELECT LISTAGG(C.ID || ' (v' || C.VERSION || ', status ' || C.STATUSID || ', ' || TO_CHAR(C.CREATEON, 'YYYY-MM-DD HH24:MI') || ')', ', ')
               WITHIN GROUP (ORDER BY C.ID)
          FROM OAGWBG_BUDGETREQUEST C WHERE C.PARENTID = O.BUDGETREQUESTID) AS REF_REQ_CHILDREN
FROM OAGWBG_BUDGETGOVERNMENT BG
JOIN OAGWBG_BUDGETGOVERNMENT O ON O.ID = BG.REF_BUDGETGOVERNMENTID
WHERE BG.PROJECTID = 464;

-- [B] แถวในคำขอเวอร์ชันใหม่ที่ "น่าจะ" เป็นตัวเดียวกัน: RUNNING ตรง หรือ CATEGORYID ตรง
--     MATCH_RUNNING = 'Y' คือตัวที่โค้ดจะเลือก (ต้องมีแค่ 1 แถว และ CATEGORYTYPEID = '2')
--     IN_VIEW = 0 แปลว่าไม่อยู่ใน OAGWBG_V_BUDGETGOVERNMENT → dropdown ไม่มีตัวเลือกนี้
--     TAKEN_BY = โครงการต้นฉบับอื่นที่ถือแถวนี้อยู่ → dropdown ตัดทิ้ง
SELECT N.ID, N.BUDGETREQUESTID, N.RUNNING, N.CATEGORYTYPEID, N.CATEGORYID,
       N.PRODUCTID, N.ACTIVITYCODEID, N.BUDGETYEAR, N.BUDGETSTATUS, N.CREATEON,
       CASE WHEN N.RUNNING = O.RUNNING THEN 'Y' ELSE 'N' END AS MATCH_RUNNING,
       (SELECT COUNT(*) FROM OAGWBG_V_BUDGETGOVERNMENT V WHERE V.ID = N.ID) AS IN_VIEW,
       (SELECT LISTAGG(P2.ID, ',') WITHIN GROUP (ORDER BY P2.ID)
          FROM OAGWBG_PROJECT P2
          JOIN OAGWBG_BUDGETGOVERNMENT BG2 ON BG2.ID = P2.BUDGETGOVERNMENTID
         WHERE BG2.REF_BUDGETGOVERNMENTID = N.ID
           AND P2.ID <> 464
           AND NOT EXISTS (SELECT 1 FROM OAGWBG_PROJECT X       WHERE X.ID       = P2.TEMP)
           AND NOT EXISTS (SELECT 1 FROM OAGWBG_BUDGETREQUEST R WHERE R.PARENTID = P2.BUDGETREQUESTID)) AS TAKEN_BY
FROM OAGWBG_BUDGETGOVERNMENT BG
JOIN OAGWBG_BUDGETGOVERNMENT O ON O.ID = BG.REF_BUDGETGOVERNMENTID
JOIN OAGWBG_BUDGETREQUEST C    ON C.PARENTID = O.BUDGETREQUESTID
JOIN OAGWBG_BUDGETGOVERNMENT N ON N.BUDGETREQUESTID = C.ID
WHERE BG.PROJECTID = 464
  AND (N.RUNNING = O.RUNNING OR N.CATEGORYID = O.CATEGORYID)
ORDER BY MATCH_RUNNING DESC, N.ID;
