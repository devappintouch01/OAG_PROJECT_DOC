-- ROLLBACK: OAGWBG_V_BUDGETALLOCATELIST ก่อนแก้ (DDL จาก DB ตามที่ผู้ใช้ export มา 2026-10-06)

CREATE OR REPLACE FORCE EDITIONABLE VIEW "OAGWBG"."OAGWBG_V_BUDGETALLOCATELIST" ("BUDGETYEAR", "TOTALREQUESTAMOUNT", "TOTALALLOCATEAMOUNT", "BUDGETSTATUS", "BUDGETALLOCATESTATUS", "BUDGETFORMTYPEID", "NAMETHAI") AS
  WITH LatestBG AS (
	SELECT
	    BG.*,
	    CASE
	        WHEN BG.BUDGETFORMTYPEID = 1 THEN BG.TOTALREQUESTAMOUNT
	        WHEN BG.BUDGETFORMTYPEID = 2 THEN OPT.ALLOCATEDBUDGET
	        ELSE BG.TOTALREQUESTAMOUNT
	    END AS TOTAL_REQUESTAMOUNT
--	    BG.REQ_TOTALREQUESTADJUSTAMOUNT,
--	    BG.REQ_TOTALALLOCATEAMOUNT ,
--	    BG.REQ_TOTALADJUSTEDAMOUNT
	FROM OAGWBG_BUDGETGOVERNMENT BG
	LEFT JOIN OAGWBG_PROJECTTARGETS OPT ON OPT.PROJECTID = BG.PROJECTID
	LEFT JOIN OAGWBG_PROJECT OP ON OP.ID = BG.PROJECTID
	WHERE
	    BG.BUDGETFORMTYPEID IN (1,2)
	    AND (BG.BUDGETGOVERNMENTTYPE = '7' OR BG.BUDGETGOVERNMENTTYPE IS NULL)
	    AND (
	    		BG.BUDGETSTATUS IN ('B','C','R')
	    		-- [CR-PRB-APPROVED] โครงการที่สถานะยังเป็น 'U' จะขึ้นหน้า พ.ร.บ. ได้
	    		-- ต่อเมื่อคำขอต้นทางยังอยู่สถานะ 20201 (อนุมัติคำของบประมาณ) เท่านั้น
	    		-- กันเคส: อนุมัติแล้ว -> สร้างคู่แฝด TEMP -> ถูกส่งกลับแก้ไข (20101/20102)
	    		--         แต่ TEMP ไม่เคยถูกล้าง รายการจึงค้างอยู่บนหน้า พ.ร.บ.
	    		OR (
	    			BG.PROJECTID IS NOT NULL
	    			AND BG.BUDGETSTATUS = 'U'
	    			AND EXISTS (
	    				SELECT 1
	    				FROM OAGWBG_BUDGETREQUEST BRA
	    				WHERE BRA.ID = BG.BUDGETREQUESTID
	    				  AND BRA.STATUSID = 20201
	    			)
	    		)
	    	)
	    AND (
		    BG.PROJECTID IS NULL
		    OR OP.TEMP IS NOT NULL
		)
	    AND BG.BUDGETREQUESTID IS NOT NULL
	    AND NOT EXISTS (
	        SELECT 1
	        FROM OAGWBG_BUDGETREQUEST BR
	        WHERE BR.PARENTID IS NOT NULL
	          AND BR.PARENTID = BG.BUDGETREQUESTID
	    )
	    AND (BG.PROJECTID IS NULL OR NOT EXISTS (
	        SELECT 1
	        FROM OAGWBG_PROJECT P
	        WHERE P.TEMP IS NOT NULL
	          AND P.TEMP = BG.PROJECTID
	    ))
),

BG4 AS (
    SELECT
        REF_BUDGETGOVERNMENTID,
        SUM(NVL(KEPTCENTRAL,0)) AS KEPTCENTRAL,
        MAX(ID) KEEP (
            DENSE_RANK FIRST ORDER BY NVL(KEPTCENTRAL,0) DESC
        ) AS ID
    FROM OAGWBG_BUDGETGOVERNMENT
    WHERE BUDGETGOVERNMENTTYPE = 4
    GROUP BY REF_BUDGETGOVERNMENTID
),

BG AS (
	SELECT
		BG.BUDGETYEAR,
		BG.CATEGORYID,
		BG.BUDGETPLANID,
		BG.PRODUCTID,
		BG.ACTIVITYCODEID,
		BG.BUDGETFORMTYPEID,
		MAX(BG.BUDGETSTATUS) AS BUDGETSTATUS,          -- ไม่แตกแถวตามสถานะ (ข้างนอกใช้ MAX อยู่แล้ว)
		SUM(NVL(BG.TOTAL_REQUESTAMOUNT,0)) AS TOTALREQUESTAMOUNT,
	    SUM(NVL(BG4.KEPTCENTRAL,0)) AS KEPTCENTRAL,
	    -- REQ_* นับเฉพาะค่ากลาง: ค่ากลางไม่มี record type 6/5/8
	    -- Category ปกติ type 6/5 = ผลรวม REQ_* ของคำขออยู่แล้ว ถ้าบวกอีกจะนับซ้ำ
	    SUM(CASE WHEN UPPER(TRIM(CC.DUMMY_FLAG)) = 'YES' THEN NVL(BG.REQ_TOTALREQUESTADJUSTAMOUNT,0) ELSE 0 END) AS REQ_TOTALREQUESTADJUSTAMOUNT,
	    SUM(CASE WHEN UPPER(TRIM(CC.DUMMY_FLAG)) = 'YES' THEN NVL(BG.REQ_TOTALALLOCATEAMOUNT,0)      ELSE 0 END) AS REQ_TOTALALLOCATEAMOUNT,
	    SUM(CASE WHEN UPPER(TRIM(CC.DUMMY_FLAG)) = 'YES' THEN NVL(BG.REQ_TOTALADJUSTEDAMOUNT,0)      ELSE 0 END) AS REQ_TOTALADJUSTEDAMOUNT
	FROM LatestBG BG
	LEFT JOIN BG4 ON BG.ID = BG4.REF_BUDGETGOVERNMENTID
	LEFT JOIN OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CC ON CC.ID = BG.CATEGORYID
	GROUP BY                                            -- 1 แถวต่อ 1 รายการเท่านั้น
		BG.BUDGETYEAR,
		BG.CATEGORYID,
		BG.BUDGETFORMTYPEID,
		BG.BUDGETPLANID,
		BG.PRODUCTID,
		BG.ACTIVITYCODEID
),

BG6 AS (
    SELECT
        CATEGORYID,
        BUDGETYEAR,
        BUDGETFORMTYPEID,
        BUDGETPLANID,
        PRODUCTID,
        ACTIVITYCODEID,
        SUM(NVL(TOTALALLOCATEAMOUNT, 0)) AS TOTALALLOCATEAMOUNT
    FROM OAGWBG_BUDGETGOVERNMENT
    WHERE BUDGETGOVERNMENTTYPE = '6'
    GROUP BY CATEGORYID, BUDGETYEAR, BUDGETFORMTYPEID,
        BUDGETPLANID,
        PRODUCTID,
        ACTIVITYCODEID
),

BG8 AS (
    SELECT
        CATEGORYID,
        BUDGETYEAR,
        BUDGETFORMTYPEID,
        BUDGETPLANID,
        PRODUCTID,
        ACTIVITYCODEID,
        SUM(NVL(TOTALREQUESTADJUSTAMOUNT, 0)) AS TOTALALLOCATEAMOUNT
    FROM OAGWBG_BUDGETGOVERNMENT
    WHERE BUDGETGOVERNMENTTYPE = '8'
    GROUP BY CATEGORYID, BUDGETYEAR, BUDGETFORMTYPEID,
        BUDGETPLANID,
        PRODUCTID,
        ACTIVITYCODEID
),

BG5 AS (
    SELECT
        CATEGORYID,
        BUDGETYEAR,
        BUDGETFORMTYPEID,
        BUDGETPLANID,
        PRODUCTID,
        ACTIVITYCODEID,
        SUM(NVL(TOTALADJUSTEDAMOUNT, 0)) AS TOTALADJUSTEDAMOUNT
    FROM OAGWBG_BUDGETGOVERNMENT
    WHERE BUDGETGOVERNMENTTYPE = '5'
    GROUP BY CATEGORYID, BUDGETYEAR, BUDGETFORMTYPEID,
        BUDGETPLANID,
        PRODUCTID,
        ACTIVITYCODEID
)

SELECT
    BG.BUDGETYEAR,
    CASE
    	WHEN BG.BUDGETFORMTYPEID = 1 THEN SUM(BG.TOTALREQUESTAMOUNT) + SUM(NVL(BG.KEPTCENTRAL, 0)) + SUM(NVL(BG8.TOTALALLOCATEAMOUNT, 0))
    	ELSE SUM(BG.TOTALREQUESTAMOUNT)
    END AS TOTALREQUESTAMOUNT,
    CASE
    	WHEN BG.BUDGETFORMTYPEID = 1 THEN SUM(NVL(BG6.TOTALALLOCATEAMOUNT, 0)) + SUM(NVL(BG5.TOTALADJUSTEDAMOUNT, 0)) + SUM(NVL(BG.REQ_TOTALALLOCATEAMOUNT, 0)) + SUM(NVL(BG.REQ_TOTALADJUSTEDAMOUNT, 0))
    	ELSE SUM(BG.TOTALREQUESTAMOUNT)
    END AS TOTALALLOCATEAMOUNT,
    MAX(BG.BUDGETSTATUS) AS BUDGETSTATUS,
    CASE
        WHEN MAX(BG.BUDGETSTATUS) = 'A' THEN 'อยู่ระหว่างรอจัดสรร'
        WHEN MAX(BG.BUDGETSTATUS) IN ('C', 'R') THEN 'บันทึกการจัดสรร'
        WHEN MAX(BG.BUDGETSTATUS) IN ('U','B') THEN 'อยู่ระหว่างรอพิจารณา'
        ELSE 'ไม่ระบุ'
    END AS BUDGETALLOCATESTATUS,
    BG.BUDGETFORMTYPEID,
    BF.NAMETHAI
FROM BG
LEFT JOIN OAGWBG_MASTERBUDGETFORMTYPE BF
    ON BF.ID = BG.BUDGETFORMTYPEID
LEFT JOIN BG6
    ON BG6.BUDGETYEAR = BG.BUDGETYEAR
    AND BG6.CATEGORYID = BG.CATEGORYID
    AND BG6.BUDGETFORMTYPEID = BG.BUDGETFORMTYPEID
    AND BG6.BUDGETPLANID = BG.BUDGETPLANID
	AND BG6.PRODUCTID = BG.PRODUCTID
	AND BG6.ACTIVITYCODEID = BG.ACTIVITYCODEID
LEFT JOIN BG5
    ON BG5.BUDGETYEAR = BG.BUDGETYEAR
    AND BG5.CATEGORYID = BG.CATEGORYID
    AND BG5.BUDGETFORMTYPEID = BG.BUDGETFORMTYPEID
    AND BG5.BUDGETPLANID = BG.BUDGETPLANID
	AND BG5.PRODUCTID = BG.PRODUCTID
	AND BG5.ACTIVITYCODEID = BG.ACTIVITYCODEID
LEFT JOIN BG8
    ON BG8.BUDGETYEAR = BG.BUDGETYEAR
    AND BG8.CATEGORYID = BG.CATEGORYID
    AND BG8.BUDGETFORMTYPEID = BG.BUDGETFORMTYPEID
    AND BG8.BUDGETPLANID = BG.BUDGETPLANID
	AND BG8.PRODUCTID = BG.PRODUCTID
	AND BG8.ACTIVITYCODEID = BG.ACTIVITYCODEID
GROUP BY
    BG.BUDGETYEAR,
    BG.BUDGETFORMTYPEID,
    BF.NAMETHAI
ORDER BY
    BG.BUDGETYEAR ASC,
    BG.BUDGETFORMTYPEID ASC;
