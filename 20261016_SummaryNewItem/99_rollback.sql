CREATE OR REPLACE FORCE EDITIONABLE VIEW "OAGWBG"."OAGWBG_V_BUDGETREQUEST" ("ID", "STATUSID", "STATUSNAME", "CODE", "ROUNDNUMBER", "BUDGETYEAR", "RUNNING", "BUDGETTYPEID", "BUDGETTYPENAME", "FUNDID", "FUNDNAME", "DEPARTMENTID", "DEPARTMENTNAME", "COSTCENTERID", "COSTCENTERNAME", "BUDGETFORMTYPEID", "BUDGETFORMTYPENAME", "TOTALREQUESTAMOUNT", "TOTALALLOCATEAMOUNT", "TOTALTRANSFERAMOUNT", "TOTALRECEIVEAMOUNT", "TOTALPAYMENTAMOUNT", "TOTALOBLIGATIONAMOUNT", "TOTALBALANCEAMOUNT", "REQUESTDATE", "ISCHECKOPENDATE", "BUDGETSOURCEID", "REGIONID", "REGIONNAME", "RN", "IS_COSTCENTER", "IS_APPROVE", "BOOKNUMBER", "PROCESSSTARTDATE") AS 
  WITH GovReq AS (
    -- BR  BG (GOVERNMENT REQUEST)
    SELECT 
        BR.ID AS BRID,
        SUM(BG.TOTALREQUESTAMOUNT) AS GOV_AMOUNT
    FROM 
        OAGWBG_BUDGETREQUEST BR
        LEFT JOIN OAGWBG_BUDGETGOVERNMENT BG ON BG.BUDGETREQUESTID = BR.ID
    WHERE BG.BUDGETSTATUS != 'X'
    GROUP BY BR.ID
),

ProjectReq AS (
    -- BR  OP  OPT (PROJECT TARGET REQUEST)
    -- 1 BR มีหลาย OP แต่ 1 OP มี 1 OPT  SUM ถูกต้องไม่คูณซ้ำ
    SELECT
        BR.ID AS BRID,
        SUM(OPT.ALLOCATEDBUDGET) AS PROJECT_AMOUNT
    FROM
        OAGWBG_BUDGETREQUEST BR
        LEFT JOIN OAGWBG_PROJECT OP ON OP.BUDGETREQUESTID = BR.ID
        LEFT JOIN OAGWBG_PROJECTTARGETS OPT ON OP.ID = OPT.PROJECTID
        LEFT JOIN OAGWBG_BUDGETGOVERNMENT BG ON BG.PROJECTID = OP.ID
    WHERE BG.BUDGETSTATUS != 'X'
    GROUP BY BR.ID
),

ReqAmount AS (
    -- รวมยอดตามประเภทฟอร์ม (ตาม CASE เดิม)
    SELECT
        BR.ID AS BRID,
        CASE
            WHEN BR.BUDGETFORMTYPEID IN (1,3) THEN COALESCE(GR.GOV_AMOUNT,0)
            WHEN BR.BUDGETFORMTYPEID IN (2,4) THEN COALESCE(PR.PROJECT_AMOUNT,0)
            ELSE 0
        END AS TOTALREQUESTAMOUNT
    FROM 
        OAGWBG_BUDGETREQUEST BR
        LEFT JOIN GovReq GR ON GR.BRID = BR.ID
        LEFT JOIN ProjectReq PR ON PR.BRID = BR.ID
),
ALL_DATA AS (
    SELECT
        BR.ID,
        BR.STATUSID,
        MS.NAME AS STATUSNAME,
        BR.CODE,
        BR.ROUNDNUMBER,
        BR.BUDGETYEAR,
        BR.RUNNING,
        BR.BUDGETTYPEID,
        BT.NAMETHAI AS BUDGETTYPENAME,
        BR.FUNDID,
        MF.NAMETHAI AS FUNDNAME,
        BR.DEPARTMENTID,
        CC.DEPARTMENTNAME,
        BR.COSTCENTERID,
        CC.NAME AS COSTCENTERNAME,
        BR.BUDGETFORMTYPEID,
        BFT.NAMETHAI AS BUDGETFORMTYPENAME,

        RA.TOTALREQUESTAMOUNT,  -- ใช้ยอดจาก CTE รวมถูกต้องไม่คูณ

        BR.TOTALALLOCATEAMOUNT,
        BR.TOTALTRANSFERAMOUNT,
        BR.TOTALRECEIVEAMOUNT,
        BR.TOTALPAYMENTAMOUNT,
        BR.TOTALOBLIGATIONAMOUNT,
        BR.TOTALBALANCEAMOUNT,
        BR.REQUESTDATE,
        OAGWBG_FN_CHECKOPENDATEFUND (BR.FUNDID, SYSDATE) AS ISCHECKOPENDATE,
        BR.BUDGETSOURCEID,
        CC.REGIONID,
        CC.REGIONNAME,
        BR.PARENTID AS RN,
        BR.IS_COSTCENTER,
        BR.IS_APPROVE,
        BR.BOOKNUMBER,
        BR.PROCESSSTARTDATE
    FROM
        OAGWBG_BUDGETREQUEST BR
        LEFT JOIN ReqAmount RA ON RA.BRID = BR.ID
        LEFT JOIN OAGWBG_MASTERSTATUS MS ON BR.STATUSID = MS.ID
        LEFT JOIN OAGWBG_MASTERBUDGETTYPE BT ON BR.BUDGETTYPEID = BT.ID
        LEFT JOIN OAGWBG_MASTERFUND MF ON BR.FUNDID = MF.ID
        LEFT JOIN OAGWBG_V_EXT_OAGGL_COST_CENTER_V CC ON CC.ID = BR.COSTCENTERID
        LEFT JOIN OAGWBG_MASTERBUDGETFORMTYPE BFT ON BR.BUDGETFORMTYPEID = BFT.ID
    WHERE BR.STATUSID NOT IN ('10199', '10198')
)
SELECT
"ID",
"STATUSID",
"STATUSNAME",
"CODE",
"ROUNDNUMBER",
"BUDGETYEAR",
"RUNNING",
"BUDGETTYPEID",
"BUDGETTYPENAME",
"FUNDID", 
"FUNDNAME",
"DEPARTMENTID",
"DEPARTMENTNAME",
"COSTCENTERID",
"COSTCENTERNAME",
"BUDGETFORMTYPEID",
"BUDGETFORMTYPENAME",
"TOTALREQUESTAMOUNT",
"TOTALALLOCATEAMOUNT",
"TOTALTRANSFERAMOUNT",
"TOTALRECEIVEAMOUNT",
"TOTALPAYMENTAMOUNT",
"TOTALOBLIGATIONAMOUNT",
"TOTALBALANCEAMOUNT",
"REQUESTDATE",
"ISCHECKOPENDATE",
"BUDGETSOURCEID",
"REGIONID",
"REGIONNAME",
"RN",
"IS_COSTCENTER",
"IS_APPROVE",
"BOOKNUMBER",
"PROCESSSTARTDATE"
FROM
  ALL_DATA
ORDER BY
  STATUSID,
  BUDGETYEAR
/

