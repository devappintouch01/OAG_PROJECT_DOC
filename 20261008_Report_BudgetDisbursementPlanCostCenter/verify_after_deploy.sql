-- รันหลัง deploy: ต้องได้ COUNT 20,191 (หรือเท่ากับก่อน deploy) และ TOTALQ = RAW_ITEMS ทุกปี
SELECT COUNT(*) N, SUM(TOTALQ) TQ FROM OAGWBG_R_BUDGETDISBURSEMENTPLANCOST;

WITH V AS (SELECT BUDGETYEAR, SUM(TOTALQ) TQ FROM OAGWBG_R_BUDGETDISBURSEMENTPLANCOST GROUP BY BUDGETYEAR),
     R AS (SELECT P.BUDGETYEAR, SUM(NVL(P.ALLOCATEAMOUNT,0)) RAW_AMT
             FROM OAGWBG_V_BUDGETDISBURSEMENTPLANITEM P
             JOIN OAGWBG_BUDGETGOVERNMENT G ON G.ID = P.BUDGETGOVERNMENTID
            WHERE G.BUDGETFORMTYPEID = 1 AND P.BUDGETDISBURSEMENTPLANID IS NOT NULL
            GROUP BY P.BUDGETYEAR)
SELECT V.BUDGETYEAR, V.TQ VIEW_TQ, R.RAW_AMT RAW_ITEMS, V.TQ - NVL(R.RAW_AMT,0) DIFF
  FROM V LEFT JOIN R ON R.BUDGETYEAR = V.BUDGETYEAR ORDER BY 1;

