CREATE OR REPLACE FORCE EDITIONABLE VIEW "OAGWBG"."OAGWBG_R_BUDGETDISBURSEMENTPLANCOST" ("BUDGETYEAR", "ID", "COSTCENTERID", "COSTCENTERNAME", "CODE", "CATEGORYID", "PLANID", "ACTIVITYID", "PRODUCTID", "PLANNAME", "ACTIVITYNAME", "PRODUCTNAME", "EXPENSETYPEID", "EXPENSETYPENAME", "BUDGETTYPENAME", "CATEGORYNAME", "TOTALALLOCATEAMOUNT", "Q1", "MONTH10", "MONTH11", "MONTH12", "Q2", "MONTH1", "MONTH2", "MONTH3", "Q3", "MONTH4", "MONTH5", "MONTH6", "Q4", "MONTH7", "MONTH8", "MONTH9", "TOTALQ") AS 
  WITH 
	BG6_SUM AS (
	SELECT
		CATEGORYID, BUDGETYEAR, BUDGETFORMTYPEID,
		SUM(TOTALALLOCATEAMOUNT) AS TOTALALLOCATEAMOUNT, PRODUCTID, ACTIVITYCODEID, EXPENSETYPEID--, BUDGETEXPENSETYPEID
	FROM OAGWBG_BUDGETGOVERNMENT
	WHERE BUDGETGOVERNMENTTYPE = '6'
		AND BUDGETFORMTYPEID IN (1,2)
	GROUP BY CATEGORYID, BUDGETYEAR, BUDGETFORMTYPEID, PRODUCTID, ACTIVITYCODEID, EXPENSETYPEID--, BUDGETEXPENSETYPEID 
),
BG5_SUM AS (
	SELECT
		CATEGORYID, BUDGETYEAR, BUDGETFORMTYPEID,
		SUM(TOTALADJUSTEDAMOUNT) AS TOTALADJUSTEDAMOUNT, PRODUCTID, ACTIVITYCODEID, EXPENSETYPEID--, BUDGETEXPENSETYPEID
	FROM OAGWBG_BUDGETGOVERNMENT
	WHERE BUDGETGOVERNMENTTYPE = '5'
		AND BUDGETFORMTYPEID IN (1,2)
	GROUP BY CATEGORYID, BUDGETYEAR, BUDGETFORMTYPEID, PRODUCTID, ACTIVITYCODEID, EXPENSETYPEID--, BUDGETEXPENSETYPEID 
)

SELECT 
    -- คอลัมน์ที่ต้องการแสดงผล
    BUDGETYEAR, ID, COSTCENTERID, COSTCENTERNAME, 
    CODE, CATEGORYID, PLANID, ACTIVITYID, PRODUCTID, PLANNAME, ACTIVITYNAME, 
    PRODUCTNAME, EXPENSETYPEID, EXPENSETYPENAME, BUDGETTYPENAME, CATEGORYNAME, TOTALALLOCATEAMOUNT,
    -- คอลัมน์รายเดือน (ใช้ NVL เพื่อให้แสดงเลข 0 แทนค่าว่าง)
    
    (NVL(MONTH10, 0) + NVL(MONTH11, 0) + NVL(MONTH12, 0)) AS Q1,
    NVL(MONTH10, 0) AS MONTH10, NVL(MONTH11, 0) AS MONTH11, NVL(MONTH12, 0) AS MONTH12,
    (NVL(MONTH1, 0) + NVL(MONTH2, 0) + NVL(MONTH3, 0)) AS Q2,
    NVL(MONTH1, 0) AS MONTH1,   NVL(MONTH2, 0) AS MONTH2,   NVL(MONTH3, 0) AS MONTH3,
    (NVL(MONTH4, 0) + NVL(MONTH5, 0) + NVL(MONTH6, 0)) AS Q3,
    NVL(MONTH4, 0) AS MONTH4,   NVL(MONTH5, 0) AS MONTH5,   NVL(MONTH6, 0) AS MONTH6,
    (NVL(MONTH7, 0) + NVL(MONTH8, 0) + NVL(MONTH9, 0)) AS Q4,
    NVL(MONTH7, 0) AS MONTH7,   NVL(MONTH8, 0) AS MONTH8,   NVL(MONTH9, 0) AS MONTH9,
    
    -- รวมยอดรายไตรมาส (ต้องใส่ NVL ทุกคอลัมน์ก่อนบวก)
    
    -- ยอดรวมทั้งปี
    (NVL(MONTH10, 0) + NVL(MONTH11, 0) + NVL(MONTH12, 0) + 
     NVL(MONTH1, 0) + NVL(MONTH2, 0) + NVL(MONTH3, 0) + 
     NVL(MONTH4, 0) + NVL(MONTH5, 0) + NVL(MONTH6, 0) + 
     NVL(MONTH7, 0) + NVL(MONTH8, 0) + NVL(MONTH9, 0)) AS TotalQ
FROM (
    -- 1. เตรียมข้อมูลพื้นฐาน (Source Data)
    SELECT 
        BDPI.BUDGETYEAR, 
        BDPI.BUDGETDISBURSEMENTPLANID AS ID, 
        BDPI.COSTCENTERID, 
        BDPI.COSTCENTERNAME, 
        CC.CODE AS CODE, 
        CC.ID AS CATEGORYID, 
        CC.PLANID AS PLANID, 
        AC.ACTIVITY_ID AS ACTIVITYID, 
        PV.ID AS PRODUCTID, 
        CC.BUDGET_PLAN_NAME AS PLANNAME,
        AC.ACTIVITY_NAME AS ACTIVITYNAME, 
        PV.NAME AS PRODUCTNAME, 
        CC.EXPENSE_TYPE_ID AS EXPENSETYPEID, 
        CC.EXPENSE_TYPE_NAME AS EXPENSETYPENAME, 
        CC.BUDGET_TYPE_NAME AS BUDGETTYPENAME, 
        CC.name AS CATEGORYNAME,
        MONTH, 
        NVL(ALLOCATEAMOUNT,0) AS ALLOCATEAMOUNT,
        -- NVL(BG6.TOTALALLOCATEAMOUNT, 0) AS TOTALALLOCATEAMOUNT,
		-- NVL(BG5.TOTALADJUSTEDAMOUNT, 0) AS TOTALADJUSTEDAMOUNT,
		NVL(NVL(BG5.TOTALADJUSTEDAMOUNT, 0) + NVL(BG6.TOTALALLOCATEAMOUNT, 0),0) AS TOTALALLOCATEAMOUNT
    FROM OAGWBG_V_BUDGETDISBURSEMENTPLANITEM BDPI
    LEFT JOIN OAGWBG_BUDGETGOVERNMENT BG ON BG.ID = BDPI.BUDGETGOVERNMENTID 
    LEFT JOIN OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CC ON BDPI.CATEGORYID = CC.ID
	LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_PRODUCT_V PV
		ON PV.ID = CASE WHEN TO_CHAR(BG.PRODUCTID) ='0' THEN '00000'ELSE TO_CHAR(BG.PRODUCTID) END
		AND PV.BUDGETPLAN_ID = CC.BUDGET_PLAN_ID
    LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_ACTIVITY_V AC
		ON AC.ACTIVITY_ID = CASE WHEN TO_CHAR(BG.ACTIVITYCODEID) = '0' THEN '00000' ELSE TO_CHAR(BG.ACTIVITYCODEID) END
		AND AC.BUDGETPLANID = CC.BUDGET_PLAN_ID	
	LEFT JOIN BG6_SUM BG6
		ON BG6.CATEGORYID       = BG.CATEGORYID
		AND BG6.BUDGETYEAR       = BG.BUDGETYEAR
		AND BG6.BUDGETFORMTYPEID = BG.BUDGETFORMTYPEID
		AND BG6.PRODUCTID = BG.PRODUCTID
		AND BG6.ACTIVITYCODEID = BG.ACTIVITYCODEID
		--AND BG6.BUDGETEXPENSETYPEID = BG.BUDGETEXPENSETYPEID
	LEFT JOIN BG5_SUM BG5
		ON BG5.CATEGORYID       = BG.CATEGORYID
		AND BG5.BUDGETYEAR       = BG.BUDGETYEAR
		AND BG5.BUDGETFORMTYPEID = BG.BUDGETFORMTYPEID
		AND BG6.PRODUCTID = BG.PRODUCTID
		AND BG6.ACTIVITYCODEID = BG.ACTIVITYCODEID
		--AND BG6.BUDGETEXPENSETYPEID = BG.BUDGETEXPENSETYPEID
    -- สามารถใส่ WHERE หรือ ROW_NUMBER() กรองข้อมูลล่าสุดตรงนี้ได้
		WHERE BG.BUDGETFORMTYPEID = 1
)
PIVOT (
    SUM(ALLOCATEAMOUNT) FOR MONTH IN (
		'10' AS MONTH10, '11' AS MONTH11, '12' AS MONTH12,
        '1' AS MONTH1,   '2' AS MONTH2,   '3' AS MONTH3,
        '4' AS MONTH4,   '5' AS MONTH5,   '6' AS MONTH6,
        '7' AS MONTH7,   '8' AS MONTH8,   '9' AS MONTH9
    )
)
WHERE ID IS NOT NULL
ORDER BY BUDGETYEAR, ID, code

