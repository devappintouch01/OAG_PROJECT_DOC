    CCG.DEPARTMENTNAME, CCG.NAME,
    RF.ACTIVITYID, RF.PRODUCTID,
    RF.TOTALREFUNDAMOUNT, CAST(NULL AS NUMBER), CAST(NULL AS NUMBER),
