    OAS.ACTIVITYID, OAS.PRODUCTID,
    OAS.TOTALRECEIVEAMOUNT, CAST(NULL AS NUMBER), BR.TOTALREQUESTAMOUNT,
    'SENDER', OAS.BUDGETSOURCEID,
    CAST(NULL AS NUMBER), TO_CHAR(BR.RUNNING), '4', BR.TOTALREQUESTAMOUNT,
