    RF.ID,
    NVL(TO_CHAR(G.BUDGETYEAR), TO_CHAR(RF.BUDGETYEAR)),
    NVL(G.DEPARTMENTNAME, CCG.DEPARTMENTNAME),
    NVL(G.COSTCENTERNAME, CCG.NAME),
    RF.ACTIVITYID, RF.PRODUCTID,
    RF.TOTALREFUNDAMOUNT, CAST(NULL AS NUMBER), G.TOTALBALANCEAMOUNT,
    'SENDER', RF.BUDGETSOURCEID,
