       ON ACTV.ACTIVITY_ID = RF.ACTIVITYID AND ACTV.PLAN_ID = RF.BUDGETPLANID
LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_PRODUCT_V  PRODV
