--
-- หลักการ:
--   - คำขอ "ไม่แตะ" OAGWBG_BUDGETRECEIVE เลย การตัดยอดยังเกิดที่ SaveBudgetTransferDetailV2 ตามเดิม
--   - ดึงได้ระดับรายการ: 1 คำขอแตกไปหลายใบโอนกลับได้ (ดึงบางส่วน)
