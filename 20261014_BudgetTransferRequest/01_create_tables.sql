-- -----------------------------------------------------------------------------
-- 1. หัวคำขอ
-- -----------------------------------------------------------------------------
CREATE TABLE OAGWBG_BUDGETTRANSFERREQUEST (
    ID                    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CREATEBY              NUMBER(10)     DEFAULT -1 NOT NULL,
    CREATEON              TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATEBY              NUMBER(10),
    UPDATEON              TIMESTAMP(6),

    -- เลขที่คำขอ (ออกเลขต่อปี: RUNNING + UNIQUE กันชน)
    REQUESTRUNNING        NUMBER(10),
    REQUESTNO             VARCHAR2(50 CHAR),
    REQUESTDATE           TIMESTAMP(6),

    -- อ้างอิงเอกสารโอนจัดสรร ("เลขที่โอน" ใน requirement)
    -- ROUNDNO ไม่ unique 100% (PREPROD มีซ้ำ 2 คู่ เป็นใบร่าง) จึงเก็บ ID คู่ไว้ด้วย
    ALLOCATETRANSFERTYPE  VARCHAR2(1 CHAR),          -- '1' = โอนจัดสรร, '4' = โอนจัดสรรเพิ่มเติม (AllocateTransferReportType)
    ALLOCATETRANSFERID    NUMBER(10),                -- BUDGETALLOCATETRANSFER.ID หรือ BUDGETALLOCATETRANSFERMORE.ID ตาม TYPE
    ALLOCATEROUNDNO       NUMBER(10),                -- ROUNDNO ของใบโอนจัดสรร

    -- ส่วนหัวเหมือนหน้าโอนเงินกลับ
    BUDGETYEAR            NUMBER(10),                -- ปีงบประมาณที่รับโอน
    FROMBUDGETYEAR        NUMBER(10),                -- ปีงบประมาณที่โอน (ใช้คำนวณโอนข้ามปี)
    TRANSFERORGTYPE       VARCHAR2(255 CHAR),        -- หน่วยงานที่โอน
    SEARCHMODE            VARCHAR2(1 CHAR),          -- '1' ปกติ, '2' เลขที่เงินกัน
    BUDGETSOURCEID        VARCHAR2(150 CHAR),
    RESERVEDBUDGETYEAR    NUMBER(10),                -- ปีที่กันเงิน (SEARCHMODE = 2)
    RESERVEDNO            VARCHAR2(200 CHAR),        -- เลขที่เงินกัน (SEARCHMODE = 2)
    TRANSFERREGION        VARCHAR2(100 CHAR),
    DEPARTMENTID          VARCHAR2(150 CHAR),
    COSTCENTERID          VARCHAR2(150 CHAR),
    ITEMDETAIL            VARCHAR2(4000 CHAR),
    REASON                VARCHAR2(4000 CHAR),
    TOTALREQUESTAMOUNT    NUMBER(14,2) DEFAULT 0,

    -- สถานะ (OAGWBG_MASTERSTATUS 70xxx)
    STATUSID              NUMBER(10)   DEFAULT 70101 NOT NULL,
    SUBMITBY              NUMBER(10),
    SUBMITON              TIMESTAMP(6),

    -- เผื่ออนาคต: ขั้นอนุมัติ
    APPROVEBY             NUMBER(10),
    APPROVEON             TIMESTAMP(6),
    APPROVENOTE           VARCHAR2(4000 CHAR),

    -- เผื่ออนาคต: ส่งเรื่องถึง role (null = ทุกคนที่เข้าหน้าโอนเงินกลับได้)
    TARGETROLEID          NUMBER(10),

    CANCELBY              NUMBER(10),
    CANCELON              TIMESTAMP(6),
    CANCELREASON          VARCHAR2(4000 CHAR),

    CONSTRAINT PK_OAGWBG_BUDGETTRANSFERREQUEST PRIMARY KEY (ID),
    CONSTRAINT UQ_OAGWBG_BTRQ_RUNNING UNIQUE (BUDGETYEAR, REQUESTRUNNING)
);

CREATE INDEX IX_OAGWBG_BTRQ_STATUS ON OAGWBG_BUDGETTRANSFERREQUEST (STATUSID, BUDGETYEAR);

