-- คำขอโอนเงินกลับ — เลขที่โอนของชุดบัญชี + ประวัติการแทนที่ยอด
-- วันที่: 2026-10-16 (ต่อจาก 02_create_item_note.sql)
--
-- 1) OAGWBG_BUDGETTRANSFERREQUESTITEM_SOURCE
--    ตอนบันทึก เก็บเลขที่โอนของ "ทุกเอกสาร" ที่ทำให้เกิดเงินในชุดบัญชี (บรรทัดงบ) นั้น ไม่ว่าเกิดจากโอนอะไร
--    รวมใบร่าง/ใบยกเลิกด้วย (เก็บสถานะไว้) เพราะแถวรับโอนจัดสรรของใบร่างมีเงินอยู่ในถังแล้ว
--    ที่มา (OAGWBG_BUDGETRECEIVE.BUDGETRECEIVETYPE):
--      A + BUDGETALLOCATETRANSFERID      → ALLOCATE      : OAGWBG_BUDGETALLOCATETRANSFER.ROUNDNO
--      A + BUDGETALLOCATETRANSFERMOREID  → ALLOCATEMORE  : OAGWBG_BUDGETALLOCATETRANSFERMORE.ROUNDNO
--      J (BUDGETTRANSFERID)              → ADJUST        : OAGWBG_BUDGETTRANSFER.ROUNDNO (โอนเปลี่ยนแปลง)
--      O (BUDGETRESERVEDCATEGORYID)      → RESERVED      : OAGWBG_BUDGETRESERVED.TRANSFERNO (เลขที่เงินกัน)
--      G + BUDGETRECEIVEPERIODID         → PERIOD        : OAGWBG_BUDGETRECEIVEPERIOD.ROUNDNO (รับงบตามงวด)
--      G + ALLOCATE/MORE/TRANSFER        → ตามเอกสารนั้น (ฝั่งผู้ให้)
--    1 แถวต่อ (รายการคำขอ, เอกสาร) — PREPROD ปี 2569 เฉลี่ย 3.2 เอกสารต่อชุดบัญชี สูงสุด 33
--
-- 2) OAGWBG_BUDGETTRANSFERREQUEST_HISTORY
--    ประวัติการเปลี่ยนแปลงรายการของคำขอ — ตอนนี้ใช้กรณีเดียว: ชุดบัญชีที่เคยบันทึกเป็น "ยอดกรอกตรง"
--    ถูกแทนด้วย "ผลรวมโน้ต" (ตกลงกับผู้ใช้ 2026-10-16: แทนที่ แต่เก็บรายการเก่าเป็นประวัติ)
--    ผูกกับหัวคำขอ ไม่ผูกกับรายการ เพราะร่างลบ-เขียนรายการใหม่ทุกครั้งที่บันทึก
--
-- ⚠️ รันหลัง 02_create_item_note.sql และก่อน deploy code รอบนี้
-- =============================================================================

CREATE TABLE OAGWBG_BUDGETTRANSFERREQUESTITEM_SOURCE (
    ID               NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CREATEBY         NUMBER(10)     DEFAULT -1 NOT NULL,
    CREATEON         TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,

    REQUESTITEMID    NUMBER(10) NOT NULL,
    RECEIVETYPE      VARCHAR2(1 CHAR),      -- BUDGETRECEIVETYPE ของแถวในถัง
    SOURCETYPE       VARCHAR2(20 CHAR),     -- ALLOCATE / ALLOCATEMORE / ADJUST / RESERVED / PERIOD / OTHER
    DOCUMENTID       NUMBER(10),            -- ID ของเอกสารตาม SOURCETYPE
    DOCUMENTNO       VARCHAR2(50 CHAR),     -- เลขที่โอน / เลขที่เงินกัน
    DOCUMENTSTATUS   VARCHAR2(20 CHAR),     -- สถานะเอกสาร ณ วันที่บันทึก (เช่น 80101 ร่าง, 80201 ยืนยัน, 80501 ยกเลิก)
    RECEIVEAMOUNT    NUMBER(14,2),          -- ยอดที่เอกสารนี้ให้กับชุดบัญชี (SUM TOTALRECEIVEAMOUNT)
    BALANCEAMOUNT    NUMBER(14,2),          -- ยอดคงเหลือในถังของแถวจากเอกสารนี้ ณ วันที่บันทึก

    CONSTRAINT PK_OAGWBG_BTRQ_ITEM_SRC PRIMARY KEY (ID),
    CONSTRAINT FK_OAGWBG_BTRQ_ITEM_SRC_ITEM FOREIGN KEY (REQUESTITEMID)
        REFERENCES OAGWBG_BUDGETTRANSFERREQUESTITEM (ID) ON DELETE CASCADE
);

CREATE INDEX IX_OAGWBG_BTRQ_ITEM_SRC_ITEM ON OAGWBG_BUDGETTRANSFERREQUESTITEM_SOURCE (REQUESTITEMID);
CREATE INDEX IX_OAGWBG_BTRQ_ITEM_SRC_DOC  ON OAGWBG_BUDGETTRANSFERREQUESTITEM_SOURCE (DOCUMENTNO);

COMMENT ON TABLE  OAGWBG_BUDGETTRANSFERREQUESTITEM_SOURCE                IS 'คำขอโอนเงินกลับ — เลขที่โอนของทุกเอกสารที่ทำให้เกิดเงินในชุดบัญชีของรายการ';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFERREQUESTITEM_SOURCE.REQUESTITEMID  IS 'อ้างอิง OAGWBG_BUDGETTRANSFERREQUESTITEM.ID';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFERREQUESTITEM_SOURCE.RECEIVETYPE    IS 'BUDGETRECEIVETYPE ของแถวในถัง (A/G/J/O)';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFERREQUESTITEM_SOURCE.SOURCETYPE     IS 'ALLOCATE/ALLOCATEMORE/ADJUST/RESERVED/PERIOD/OTHER';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFERREQUESTITEM_SOURCE.DOCUMENTID     IS 'ID ของเอกสารตาม SOURCETYPE';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFERREQUESTITEM_SOURCE.DOCUMENTNO     IS 'เลขที่โอน / เลขที่เงินกัน';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFERREQUESTITEM_SOURCE.DOCUMENTSTATUS IS 'สถานะเอกสาร ณ วันที่บันทึก';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFERREQUESTITEM_SOURCE.RECEIVEAMOUNT  IS 'ยอดที่เอกสารนี้ให้กับชุดบัญชี';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFERREQUESTITEM_SOURCE.BALANCEAMOUNT  IS 'ยอดคงเหลือในถังของแถวจากเอกสารนี้ ณ วันที่บันทึก';

CREATE TABLE OAGWBG_BUDGETTRANSFERREQUEST_HISTORY (
    ID                NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CREATEBY          NUMBER(10)     DEFAULT -1 NOT NULL,
    CREATEON          TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,

    REQUESTID         NUMBER(10) NOT NULL,
    ACTIONTYPE        VARCHAR2(30 CHAR) NOT NULL,   -- REPLACE_BY_NOTE
    BUDGETRECEIVEID   NUMBER(10),                   -- ชุดบัญชี (ID ของบรรทัดงบใน view)
    COSTCENTERID      VARCHAR2(150 CHAR),
    CATEGORYID        NUMBER(10),
    BUDGETCODEID      VARCHAR2(255 CHAR),
    OLDREQUESTAMOUNT  NUMBER(14,2),
    OLDNOTE           VARCHAR2(4000 CHAR),
    NEWREQUESTAMOUNT  NUMBER(14,2),
    DETAIL            VARCHAR2(4000 CHAR),

    CONSTRAINT PK_OAGWBG_BTRQ_HIST PRIMARY KEY (ID),
    CONSTRAINT FK_OAGWBG_BTRQ_HIST_REQ FOREIGN KEY (REQUESTID)
        REFERENCES OAGWBG_BUDGETTRANSFERREQUEST (ID) ON DELETE CASCADE
);

CREATE INDEX IX_OAGWBG_BTRQ_HIST_REQ ON OAGWBG_BUDGETTRANSFERREQUEST_HISTORY (REQUESTID);

COMMENT ON TABLE  OAGWBG_BUDGETTRANSFERREQUEST_HISTORY                  IS 'คำขอโอนเงินกลับ — ประวัติการเปลี่ยนแปลงรายการ (เช่น ยอดกรอกตรงถูกแทนด้วยผลรวมโน้ต)';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFERREQUEST_HISTORY.REQUESTID        IS 'อ้างอิง OAGWBG_BUDGETTRANSFERREQUEST.ID';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFERREQUEST_HISTORY.ACTIONTYPE       IS 'REPLACE_BY_NOTE = ยอดกรอกตรงถูกแทนด้วยผลรวมโน้ต';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFERREQUEST_HISTORY.BUDGETRECEIVEID  IS 'ชุดบัญชี (ID ของบรรทัดงบใน OAGWBG_V_BUDGETRECEIVESUMMARY_REFUND)';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFERREQUEST_HISTORY.OLDREQUESTAMOUNT IS 'ยอดเดิมก่อนถูกแทน';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFERREQUEST_HISTORY.OLDNOTE          IS 'หมายเหตุเดิม';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFERREQUEST_HISTORY.NEWREQUESTAMOUNT IS 'ยอดใหม่ (ผลรวมโน้ต)';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFERREQUEST_HISTORY.DETAIL           IS 'รายละเอียดเพิ่มเติม (เช่น โน้ตที่ใช้)';

