-- =============================================================================
-- คำขอโอนเงินกลับ — ยอดขอโอนกลับราย note ของโอนจัดสรร
-- วันที่: 2026-10-14 (ต่อจาก 01_create_tables.sql)
--
-- ที่มา: ค้นหาด้วยเลขที่โอนจัดสรร (ROUNDNO) แล้วกรอกยอดโอนกลับตาม note ของโอนจัดสรร
--        (OAGWBG_BUDGETALLOCATETRANSFER_COSTCENTER_NOTE) ยอดของรายการ = ผลรวมของ note
--
-- 1 รายการคำขอ (= 1 บรรทัดงบของ view OAGWBG_V_BUDGETRECEIVESUMMARY_REFUND) มีได้หลาย note
-- เพราะ view ยุบหลายแถว BUDGETRECEIVE เป็นบรรทัดเดียว และ 1 แถว type 'A' มีได้หลาย note
--
-- ⚠️ รันหลัง 01_create_tables.sql และก่อน deploy code รอบนี้
-- =============================================================================

CREATE TABLE OAGWBG_BUDGETTRANSFERREQUESTITEM_NOTE (
    ID               NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CREATEBY         NUMBER(10)     DEFAULT -1 NOT NULL,
    CREATEON         TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATEBY         NUMBER(10),
    UPDATEON         TIMESTAMP(6),

    REQUESTITEMID    NUMBER(10) NOT NULL,
    ALLOCATENOTEID   NUMBER(10),            -- OAGWBG_BUDGETALLOCATETRANSFER_COSTCENTER_NOTE.ID (null = แถวโอนจัดสรรที่ไม่มี note)
    RECEIVEID        NUMBER(10),            -- OAGWBG_BUDGETRECEIVE.ID แถว type 'A' ของโอนจัดสรร
    ALLOCATEROUNDNO  NUMBER(10),            -- ROUNDNO ของใบโอนจัดสรร (snapshot)
    SEQUENCE         NUMBER(10),
    NOTE             VARCHAR2(4000 CHAR),   -- ข้อความ note ณ วันที่ขอ (snapshot)
    ALLOCATEAMOUNT   NUMBER(14,2),          -- ยอดของ note ในใบโอนจัดสรร (snapshot)
    REQUESTAMOUNT    NUMBER(14,2) NOT NULL, -- ยอดขอโอนกลับของ note นี้

    CONSTRAINT PK_OAGWBG_BTRQ_ITEM_NOTE PRIMARY KEY (ID),
    CONSTRAINT FK_OAGWBG_BTRQ_ITEM_NOTE_ITEM FOREIGN KEY (REQUESTITEMID)
        REFERENCES OAGWBG_BUDGETTRANSFERREQUESTITEM (ID) ON DELETE CASCADE
);

CREATE INDEX IX_OAGWBG_BTRQ_ITEM_NOTE_ITEM ON OAGWBG_BUDGETTRANSFERREQUESTITEM_NOTE (REQUESTITEMID);

COMMENT ON TABLE  OAGWBG_BUDGETTRANSFERREQUESTITEM_NOTE                 IS 'คำขอโอนเงินกลับ — ยอดขอโอนกลับราย note ของโอนจัดสรร (ผลรวม = REQUESTAMOUNT ของรายการ)';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFERREQUESTITEM_NOTE.REQUESTITEMID   IS 'อ้างอิง OAGWBG_BUDGETTRANSFERREQUESTITEM.ID';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFERREQUESTITEM_NOTE.ALLOCATENOTEID  IS 'อ้างอิง OAGWBG_BUDGETALLOCATETRANSFER_COSTCENTER_NOTE.ID (null = แถวโอนจัดสรรที่ไม่มี note)';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFERREQUESTITEM_NOTE.RECEIVEID       IS 'อ้างอิง OAGWBG_BUDGETRECEIVE.ID แถวรับโอนจัดสรร (type A)';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFERREQUESTITEM_NOTE.ALLOCATEROUNDNO IS 'เลขที่โอนจัดสรร (ROUNDNO)';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFERREQUESTITEM_NOTE.SEQUENCE        IS 'ลำดับ note ในใบโอนจัดสรร';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFERREQUESTITEM_NOTE.NOTE            IS 'ข้อความ note ณ วันที่ขอ';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFERREQUESTITEM_NOTE.ALLOCATEAMOUNT  IS 'ยอดของ note ในใบโอนจัดสรร ณ วันที่ขอ';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFERREQUESTITEM_NOTE.REQUESTAMOUNT   IS 'ยอดขอโอนกลับของ note นี้';

-- ยืนยันผล — ต้องได้ 1 แถว
SELECT table_name FROM user_tables WHERE table_name = 'OAGWBG_BUDGETTRANSFERREQUESTITEM_NOTE';
