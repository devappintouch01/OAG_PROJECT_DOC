-- =============================================================================
-- โอนเงินกลับ — ยอดโอนกลับราย note ของโอนจัดสรร (หน้าโอนเงินกลับ)
-- วันที่: 2026-10-21 (ต่อจาก 04_status_inprogress.sql)
--
-- ที่มา: ให้หน้าโอนเงินกลับค้นหาจากใบโอนจัดสรรและกรอกยอดราย note ได้เหมือนหน้าแจ้งโอนกลับ
--        (ใบที่ดึงจากรายการแจ้งโอนกลับก็ยกยอดราย note มาเก็บที่นี่)
--
-- ข้อตกลง (ผู้ใช้ 2026-10-21):
--   - ยอดราย note เป็นข้อมูลประกอบ — SaveBudgetTransferDetailV2 ยังตัดยอดถังระดับบรรทัดงบเหมือนเดิม
--     (ไม่ได้ตัดตาม RECEIVEID ของ note) และ Interface ยังรวมตามบัญชี
--   - ผลรวม TRANSFERAMOUNT ของบรรทัดงบ = ยอดโอนกลับของบรรทัดนั้นในใบ
--
-- ผูกกับ "ใบ + บรรทัดงบ" ไม่ผูกกับ OAGWBG_BUDGETRECEIVEREFUND.ID เพราะ V2 ลบ link แล้วสร้างใหม่ทุกครั้งที่บันทึก
-- บรรทัดงบ = (DEPARTMENTID, COSTCENTERID, BUDGETYEAR, CATEGORYID, PRODUCTID, BUDGETRESERVEDCATEGORYID)
-- ชุดเดียวกับ RequestLineKey ที่ใช้ผูกรายการแจ้งโอนกลับกับใบโอนกลับ
--
-- ⚠️ รันก่อน deploy API รอบนี้ — SaveBudgetTransferDetailV2 เขียนตารางนี้ทุกครั้งที่บันทึกใบโอนกลับ
-- =============================================================================

CREATE TABLE OAGWBG_BUDGETTRANSFER_NOTE (
    ID                        NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CREATEBY                  NUMBER(10)     DEFAULT -1 NOT NULL,
    CREATEON                  TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATEBY                  NUMBER(10),
    UPDATEON                  TIMESTAMP(6),

    TRANSFERID                NUMBER(10) NOT NULL,   -- OAGWBG_BUDGETTRANSFER.ID

    -- บรรทัดงบ (ฝั่งผู้โอน)
    DEPARTMENTID              VARCHAR2(150 CHAR),
    COSTCENTERID              VARCHAR2(150 CHAR),
    BUDGETYEAR                NUMBER(10),
    CATEGORYID                NUMBER(10),
    PRODUCTID                 VARCHAR2(150 CHAR),
    BUDGETRESERVEDCATEGORYID  NUMBER(10),

    -- note ของโอนจัดสรร (snapshot ณ วันที่บันทึก)
    ALLOCATENOTEID            NUMBER(10),            -- OAGWBG_BUDGETALLOCATETRANSFER_COSTCENTER_NOTE.ID (null = แถวที่ไม่มี note)
    RECEIVEID                 NUMBER(10),            -- OAGWBG_BUDGETRECEIVE.ID แถวรับโอนจัดสรร (type A)
    ALLOCATEROUNDNO           NUMBER(10),
    SEQUENCE                  NUMBER(10),
    NOTE                      VARCHAR2(4000 CHAR),
    ALLOCATEAMOUNT            NUMBER(14,2),

    TRANSFERAMOUNT            NUMBER(14,2) NOT NULL, -- ยอดโอนกลับของ note นี้
    REMARK                    VARCHAR2(4000 CHAR),   -- หมายเหตุราย note
    REQUESTITEMID             NUMBER(10),            -- รายการแจ้งโอนกลับต้นทาง (ถ้าดึงมาจากรายการแจ้ง)

    CONSTRAINT PK_OAGWBG_BT_NOTE PRIMARY KEY (ID)
);

CREATE INDEX IX_OAGWBG_BT_NOTE_TRANSFER ON OAGWBG_BUDGETTRANSFER_NOTE (TRANSFERID);
CREATE INDEX IX_OAGWBG_BT_NOTE_ALLOCNOTE ON OAGWBG_BUDGETTRANSFER_NOTE (ALLOCATENOTEID);
CREATE INDEX IX_OAGWBG_BT_NOTE_RECEIVE  ON OAGWBG_BUDGETTRANSFER_NOTE (RECEIVEID);

COMMENT ON TABLE  OAGWBG_BUDGETTRANSFER_NOTE                IS 'โอนเงินกลับ — ยอดโอนกลับราย note ของโอนจัดสรร ต่อบรรทัดงบของใบ (ข้อมูลประกอบ ไม่ใช่ตัวตัดยอดถัง)';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFER_NOTE.TRANSFERID     IS 'อ้างอิง OAGWBG_BUDGETTRANSFER.ID';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFER_NOTE.ALLOCATENOTEID IS 'อ้างอิง OAGWBG_BUDGETALLOCATETRANSFER_COSTCENTER_NOTE.ID (null = แถวโอนจัดสรรที่ไม่มี note)';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFER_NOTE.RECEIVEID      IS 'อ้างอิง OAGWBG_BUDGETRECEIVE.ID แถวรับโอนจัดสรร (type A)';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFER_NOTE.TRANSFERAMOUNT IS 'ยอดโอนกลับของ note นี้ — ผลรวมของบรรทัดงบ = ยอดโอนกลับของบรรทัดในใบ';
COMMENT ON COLUMN OAGWBG_BUDGETTRANSFER_NOTE.REQUESTITEMID  IS 'อ้างอิง OAGWBG_BUDGETTRANSFERREQUESTITEM.ID ที่เป็นต้นทาง (null = กรอกในหน้าโอนเงินกลับเอง)';

