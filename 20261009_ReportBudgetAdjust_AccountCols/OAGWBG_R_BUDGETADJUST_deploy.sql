CREATE OR REPLACE FORCE EDITIONABLE VIEW "OAGWBG"."OAGWBG_R_BUDGETADJUST"
( "RECEIVE_ID", "BUDGETYEAR", "DEPARTMENTNAME", "COSTCENTERNAME", "ACTIVITYID", "PRODUCTID",
  "TOTALTRANSFERAMOUNT", "TOTALRECEIVEAMOUNT", "TOTALBALANCEAMOUNT", "ROLETYPE",
  "BUDGETSOURCEID", "TRANSFER_ID", "TRANSFERNO", "TRANSFERTYPE", "TRANSFER_AMOUNT",
  "BUDGETSOURCENAME", "BUDGETPLANNAME", "ACTIVITYNAME", "PRODUCTNAME", "ROUNDNO",
  "ITEMDETAIL", "BUDGETTYPENAME", "CATEGORYNAME",
  "BUDGETCODE", "CATEGORYID", "ACCOUNTNO", "ACCOUNTNAME", "SUBACCOUNTNO" )
AS
SELECT
    U.RECEIVE_ID, U.BUDGETYEAR, U.DEPARTMENTNAME, U.COSTCENTERNAME, U.ACTIVITYID, U.PRODUCTID,
    U.TOTALTRANSFERAMOUNT, U.TOTALRECEIVEAMOUNT, U.TOTALBALANCEAMOUNT, U.ROLETYPE,
    U.BUDGETSOURCEID, U.TRANSFER_ID, U.TRANSFERNO, U.TRANSFERTYPE, U.TRANSFER_AMOUNT,
    U.BUDGETSOURCENAME, U.BUDGETPLANNAME, U.ACTIVITYNAME, U.PRODUCTNAME, U.ROUNDNO,
    U.ITEMDETAIL, U.BUDGETTYPENAME, U.CATEGORYNAME,
    U.BUDGETCODE,
    U.CATEGORYID,
    NVL(U.ACCOUNTNO, RL.ACCOUNTNO)           AS ACCOUNTNO,
    AV.NAME                                  AS ACCOUNTNAME,
    NVL(U.SUBACCOUNTNO, RL.SUBACCOUNTNO)     AS SUBACCOUNTNO
FROM (
-- ============================================================ 1) โอนเปลี่ยนแปลงงบประมาณ — ฝั่งโอนออก
SELECT
    A.ID                                     AS RECEIVE_ID,
    TO_CHAR(NVL(A.BUDGETYEAR, T.BUDGETYEAR)) AS BUDGETYEAR,
    CC.DEPARTMENTNAME                        AS DEPARTMENTNAME,
    CC.NAME                                  AS COSTCENTERNAME,
    A.ACTIVITYID                             AS ACTIVITYID,
    A.PRODUCTID                              AS PRODUCTID,
    A.TOTALTRANSFERAMOUNT                    AS TOTALTRANSFERAMOUNT,
    CAST(NULL AS NUMBER)                     AS TOTALRECEIVEAMOUNT,
    A.REMAININGAMOUNT                        AS TOTALBALANCEAMOUNT,
    'SENDER'                                 AS ROLETYPE,
    A.BUDGETSOURCEID                         AS BUDGETSOURCEID,
    T.ID                                     AS TRANSFER_ID,
    T.TRANSFERNO                             AS TRANSFERNO,
    '1'                                      AS TRANSFERTYPE,
    T.TOTALTRANSFERAMOUNT                    AS TRANSFER_AMOUNT,
    SRCV.NAME                                AS BUDGETSOURCENAME,
    PLANV.NAME                               AS BUDGETPLANNAME,
    ACTV.ACTIVITY_NAME                       AS ACTIVITYNAME,
    PRODV.NAME                               AS PRODUCTNAME,
    TO_CHAR(T.ROUNDNO)                       AS ROUNDNO,
    T.ITEMDETAIL                             AS ITEMDETAIL,
    CAT.BUDGET_TYPE_NAME                     AS BUDGETTYPENAME,
    CAT.NAME                                 AS CATEGORYNAME,
    A.BUDGETCODE                             AS BUDGETCODE,
    A.CATEGORYID                             AS CATEGORYID,
    CAST(NULL AS VARCHAR2(150))              AS ACCOUNTNO,
    CAST(NULL AS VARCHAR2(150))              AS SUBACCOUNTNO
FROM OAGWBG_BUDGETTRANSFER T
JOIN OAGWBG_BUDGETADJUST A ON A.BUDGETTRANSFERID = T.ID
LEFT JOIN OAGWBG_V_EXT_OAGGL_COST_CENTER_V     CC    ON CC.ID    = A.COSTCENTERID
LEFT JOIN OAGWBG_V_EXT_BUDGET_SOURCE_V         SRCV  ON SRCV.ID  = A.BUDGETSOURCEID
LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_PLAN_V     PLANV ON PLANV.ID = A.BUDGETPLANID
LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_ACTIVITY_V ACTV
       ON ACTV.ACTIVITY_ID = A.ACTIVITYID AND ACTV.PLAN_ID = A.BUDGETPLANID
LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_PRODUCT_V  PRODV
       ON PRODV.ID = A.PRODUCTID AND PRODV.BUDGETPLANCODE_ID = A.BUDGETPLANID
LEFT JOIN OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CAT   ON CAT.ID   = A.CATEGORYID
WHERE T.TRANSFERTYPE = '1'

UNION ALL
-- ============================================================ 1) โอนเปลี่ยนแปลงงบประมาณ — ฝั่งรับโอน
SELECT
    R.ID, TO_CHAR(R.BUDGETYEAR), R.DEPARTMENTNAME, R.COSTCENTERNAME,
    R.ACTIVITYID, R.PRODUCTID,
    CAST(NULL AS NUMBER), R.TOTALRECEIVEAMOUNT, R.TOTALBALANCEAMOUNT,
    'RECEIVER', R.BUDGETSOURCEID,
    T.ID, T.TRANSFERNO, '1', T.TOTALTRANSFERAMOUNT,
    R.BUDGETSOURCEIDNAME, R.PLANNAME, R.ACTIVITYNAME, R.PRODUCTNAME,
    TO_CHAR(T.ROUNDNO),
    T.ITEMDETAIL, CAT.BUDGET_TYPE_NAME, NVL(CAT.NAME, R.CATEGORYNAME),
    R.BUDGETCODEID, R.CATEGORYID, NULL, NULL
FROM OAGWBG_BUDGETTRANSFER T
JOIN OAGWBG_BUDGETADJUST    A ON A.BUDGETTRANSFERID = T.ID
JOIN OAGWBG_V_BUDGETRECEIVE R ON R.BUDGETADJUSTID   = A.ID
LEFT JOIN OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CAT ON CAT.ID = R.CATEGORYID
WHERE T.TRANSFERTYPE = '1'

UNION ALL
-- ============================================================ 2) โอนเงินกลับ
SELECT
    R.ID, TO_CHAR(R.BUDGETYEAR), R.DEPARTMENTNAME, R.COSTCENTERNAME,
    R.ACTIVITYID, R.PRODUCTID,
    CAST(NULL AS NUMBER), R.TOTALRECEIVEAMOUNT, R.TOTALBALANCEAMOUNT,
    'RECEIVER', R.BUDGETSOURCEID,
    T.ID, T.TRANSFERNO, '2', T.TOTALTRANSFERAMOUNT,
    R.BUDGETSOURCEIDNAME, R.PLANNAME, R.ACTIVITYNAME, R.PRODUCTNAME,
    TO_CHAR(T.ROUNDNO),
    T.ITEMDETAIL, CAT.BUDGET_TYPE_NAME, NVL(CAT.NAME, R.CATEGORYNAME),
    R.BUDGETCODEID, R.CATEGORYID, NULL, NULL
FROM OAGWBG_BUDGETTRANSFER T
JOIN OAGWBG_V_BUDGETRECEIVE R
       ON R.BUDGETTRANSFERID = T.ID AND R.BUDGETRECEIVETYPE = 'T'
LEFT JOIN OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CAT ON CAT.ID = R.CATEGORYID
WHERE T.TRANSFERTYPE = '2'

UNION ALL
-- ============================================================ 2) โอนเงินกลับ — ฝั่งโอนออก
-- GIVERID resolve ไม่ครบ (มีแถวค้าง) จึงใช้ LEFT JOIN แล้ว NVL ไปหาฟิลด์ giver บนตัว link
SELECT
    RF.ID,
    NVL(TO_CHAR(G.BUDGETYEAR), TO_CHAR(RF.BUDGETYEAR)),
    NVL(G.DEPARTMENTNAME, CCG.DEPARTMENTNAME),
    NVL(G.COSTCENTERNAME, CCG.NAME),
    RF.ACTIVITYID, RF.PRODUCTID,
    RF.TOTALREFUNDAMOUNT, CAST(NULL AS NUMBER), G.TOTALBALANCEAMOUNT,
    'SENDER', RF.BUDGETSOURCEID,
    T.ID, T.TRANSFERNO, '2', T.TOTALTRANSFERAMOUNT,
    NVL(G.BUDGETSOURCEIDNAME, SRCV.NAME),
    NVL(G.PLANNAME, PLANV.NAME),
    NVL(G.ACTIVITYNAME, ACTV.ACTIVITY_NAME),
    NVL(G.PRODUCTNAME, PRODV.NAME),
    TO_CHAR(T.ROUNDNO),
    T.ITEMDETAIL, CAT.BUDGET_TYPE_NAME, NVL(CAT.NAME, G.CATEGORYNAME),
    NVL(RF.BUDGETCODEID, G.BUDGETCODEID), RF.CATEGORYID, NULL, NULL
FROM OAGWBG_BUDGETTRANSFER T
JOIN OAGWBG_BUDGETRECEIVEREFUND RF ON RF.TRANSFERID = T.ID
LEFT JOIN OAGWBG_V_BUDGETRECEIVE               G     ON G.ID     = RF.GIVERID
LEFT JOIN OAGWBG_V_EXT_OAGGL_COST_CENTER_V     CCG   ON CCG.ID   = RF.COSTCENTERIDGIVER
LEFT JOIN OAGWBG_V_EXT_BUDGET_SOURCE_V         SRCV  ON SRCV.ID  = RF.BUDGETSOURCEID
LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_PLAN_V     PLANV ON PLANV.ID = RF.BUDGETPLANID
LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_ACTIVITY_V ACTV
       ON ACTV.ACTIVITY_ID = RF.ACTIVITYID AND ACTV.PLAN_ID = RF.BUDGETPLANID
LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_PRODUCT_V  PRODV
       ON PRODV.ID = RF.PRODUCTID AND PRODV.BUDGETPLANCODE_ID = RF.BUDGETPLANID
LEFT JOIN OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CAT   ON CAT.ID   = RF.CATEGORYID
WHERE T.TRANSFERTYPE = '2'

UNION ALL
-- ============================================================ 3) โอนปรับเงินเหลือจ่าย — ฝั่งรับโอน
SELECT
    R.ID, TO_CHAR(R.BUDGETYEAR), R.DEPARTMENTNAME, R.COSTCENTERNAME,
    R.ACTIVITYID, R.PRODUCTID,
    CAST(NULL AS NUMBER), R.TOTALRECEIVEAMOUNT, R.TOTALBALANCEAMOUNT,
    'RECEIVER', R.BUDGETSOURCEID,
    T.ID, T.TRANSFERNO, '3', T.TOTALTRANSFERAMOUNT,
    R.BUDGETSOURCEIDNAME, R.PLANNAME, R.ACTIVITYNAME, R.PRODUCTNAME,
    TO_CHAR(T.ROUNDNO),
    T.ITEMDETAIL, CAT.BUDGET_TYPE_NAME, NVL(CAT.NAME, R.CATEGORYNAME),
    R.BUDGETCODEID, R.CATEGORYID, NULL, NULL
FROM OAGWBG_BUDGETTRANSFER T
JOIN OAGWBG_V_BUDGETRECEIVE R
       ON R.BUDGETTRANSFERID = T.ID AND R.BUDGETRECEIVETYPE = 'R'
LEFT JOIN OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CAT ON CAT.ID = R.CATEGORYID
WHERE T.TRANSFERTYPE = '3'

UNION ALL
-- ============================================================ 3) โอนปรับเงินเหลือจ่าย — ฝั่งโอนออก
-- ฝั่งโอนออกอยู่ใน OAGWBG_BUDGETRECEIVEREFUND: 1 แถว = 1 กองเงินต้นทางที่ถูกตัด
-- มิติงบประมาณทั้งหมดอ่านจากแถวต้นทาง G — รหัสงบ/หมวดก็ใช้ของ G ให้ตรงกับคอลัมน์อื่นในแถว
SELECT
    RF.ID, TO_CHAR(G.BUDGETYEAR), G.DEPARTMENTNAME, G.COSTCENTERNAME,
    G.ACTIVITYID, G.PRODUCTID,
    RF.TOTALREFUNDAMOUNT, CAST(NULL AS NUMBER), G.TOTALBALANCEAMOUNT,
    'SENDER', G.BUDGETSOURCEID,
    T.ID, T.TRANSFERNO, '3', T.TOTALTRANSFERAMOUNT,
    G.BUDGETSOURCEIDNAME, G.PLANNAME, G.ACTIVITYNAME, G.PRODUCTNAME,
    TO_CHAR(T.ROUNDNO),
    T.ITEMDETAIL, CAT.BUDGET_TYPE_NAME, NVL(CAT.NAME, G.CATEGORYNAME),
    G.BUDGETCODEID, G.CATEGORYID, NULL, NULL
FROM OAGWBG_BUDGETTRANSFER T
JOIN OAGWBG_BUDGETRECEIVEREFUND RF ON RF.TRANSFERID = T.ID
JOIN OAGWBG_V_BUDGETRECEIVE     G  ON G.ID = RF.GIVERID
LEFT JOIN OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CAT ON CAT.ID = G.CATEGORYID
WHERE T.TRANSFERTYPE = '3'

UNION ALL
-- ============================================================ 4) เบิกแทนกัน — ฝั่งโอนออก
-- บัญชีหลัก/รายจ่ายย่อยถูกเลือกเก็บไว้ใน ACCOUNT_SEGMENT ตรง ๆ ไม่ต้องหาจาก rule
SELECT
    OAS.ID, BR.BUDGETYEAR, CC.DEPARTMENTNAME, CC.NAME,
    OAS.ACTIVITYID, OAS.PRODUCTID,
    OAS.TOTALRECEIVEAMOUNT, CAST(NULL AS NUMBER), BR.TOTALREQUESTAMOUNT,
    'SENDER', OAS.BUDGETSOURCEID,
    CAST(NULL AS NUMBER), TO_CHAR(BR.RUNNING), '4', BR.TOTALREQUESTAMOUNT,
    SRCV.NAME, PLANV.NAME, ACTV.ACTIVITY_NAME, PRODV.NAME,
    TO_CHAR(BR.RUNNING),
    OAS.DESCRIPTION, BTV.NAME, BCV.NAME,
    OAS.BUDGETCODENAME, CAST(NULL AS NUMBER), OAS.ACCOUNT, OAS.SUBACCOUNT
FROM OAGWBG_BUDGETREQUISITION BR
LEFT JOIN OAGWBG_ACCOUNT_SEGMENT OAS
       ON OAS.REFERENCEID = BR.ID AND OAS.REFERENCETABLE = 'BudgetRequisition'
LEFT JOIN OAGWBG_V_EXT_OAGGL_COST_CENTER_V     CC    ON CC.ID    = NVL(OAS.COSTCENTERID, BR.COSTCENTERID)
LEFT JOIN OAGWBG_V_EXT_BUDGET_SOURCE_V         SRCV  ON SRCV.ID  = OAS.BUDGETSOURCEID
LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_PLAN_V     PLANV ON PLANV.ID = OAS.BUDGETPLANID
LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_ACTIVITY_V ACTV
       ON ACTV.ACTIVITY_ID = OAS.ACTIVITYID AND ACTV.PLAN_ID = OAS.BUDGETPLANID
LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_PRODUCT_V  PRODV
       ON PRODV.ID = OAS.PRODUCTID AND PRODV.BUDGETPLANCODE_ID = OAS.BUDGETPLANID
LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_TYPE_V     BTV   ON BTV.ID   = OAS.BUDGETTYPEID
LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_CODE_V     BCV   ON BCV.ID   = OAS.BUDGETCODENAME
WHERE BR.TRANSFERTYPE = 'O'

UNION ALL
-- ============================================================ 4) เบิกแทนกัน — ฝั่งรับโอน
SELECT
    OAS.ID, BR.BUDGETYEAR, CC.DEPARTMENTNAME, CC.NAME,
    OAS.ACTIVITYID, OAS.PRODUCTID,
    CAST(NULL AS NUMBER), OAS.TOTALRECEIVEAMOUNT, BR.TOTALREQUESTAMOUNT,
    'RECEIVER', OAS.BUDGETSOURCEID,
    CAST(NULL AS NUMBER), TO_CHAR(BR.RUNNING), '4', BR.TOTALREQUESTAMOUNT,
    SRCV.NAME, PLANV.NAME, ACTV.ACTIVITY_NAME, PRODV.NAME,
    TO_CHAR(BR.RUNNING),
    OAS.DESCRIPTION, BTV.NAME, BCV.NAME,
    OAS.BUDGETCODENAME, CAST(NULL AS NUMBER), OAS.ACCOUNT, OAS.SUBACCOUNT
FROM OAGWBG_BUDGETREQUISITION BR
LEFT JOIN OAGWBG_ACCOUNT_SEGMENT OAS
       ON OAS.REFERENCEID = BR.ID AND OAS.REFERENCETABLE = 'BudgetRequisition'
LEFT JOIN OAGWBG_V_EXT_OAGGL_COST_CENTER_V     CC    ON CC.ID    = NVL(OAS.COSTCENTERID, BR.COSTCENTERID)
LEFT JOIN OAGWBG_V_EXT_BUDGET_SOURCE_V         SRCV  ON SRCV.ID  = OAS.BUDGETSOURCEID
LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_PLAN_V     PLANV ON PLANV.ID = OAS.BUDGETPLANID
LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_ACTIVITY_V ACTV
       ON ACTV.ACTIVITY_ID = OAS.ACTIVITYID AND ACTV.PLAN_ID = OAS.BUDGETPLANID
LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_PRODUCT_V  PRODV
       ON PRODV.ID = OAS.PRODUCTID AND PRODV.BUDGETPLANCODE_ID = OAS.BUDGETPLANID
LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_TYPE_V     BTV   ON BTV.ID   = OAS.BUDGETTYPEID
LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_CODE_V     BCV   ON BCV.ID   = OAS.BUDGETCODENAME
WHERE BR.TRANSFERTYPE = 'I'

UNION ALL
-- ============================================================ 5) โอนเงินกลับหลายปี
SELECT
    R.ID, TO_CHAR(R.BUDGETYEAR), R.DEPARTMENTNAME, R.COSTCENTERNAME,
    R.ACTIVITYID, R.PRODUCTID,
    CAST(NULL AS NUMBER), R.TOTALRECEIVEAMOUNT, R.TOTALBALANCEAMOUNT,
    'RECEIVER', R.BUDGETSOURCEID,
    T.ID, T.TRANSFERNO, '5', T.TOTALTRANSFERAMOUNT,
    R.BUDGETSOURCEIDNAME, R.PLANNAME, R.ACTIVITYNAME, R.PRODUCTNAME,
    TO_CHAR(T.ROUNDNO),
    T.ITEMDETAIL, CAT.BUDGET_TYPE_NAME, NVL(CAT.NAME, R.CATEGORYNAME),
    R.BUDGETCODEID, R.CATEGORYID, NULL, NULL
FROM OAGWBG_BUDGETTRANSFER T
JOIN OAGWBG_V_BUDGETRECEIVE R
       ON R.BUDGETTRANSFERID = T.ID AND R.BUDGETRECEIVETYPE = 'T'
LEFT JOIN OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CAT ON CAT.ID = R.CATEGORYID
WHERE T.TRANSFERTYPE = '4'

UNION ALL
-- ============================================================ 5) โอนเงินกลับหลายปี — ฝั่งโอนออก
-- GIVERID เป็น NULL ทั้งหมด (flow ไม่ได้ตัดกองเงินต้นทาง) — ทุกมิติอ่านจากฟิลด์บนตัว link
SELECT
    RF.ID, TO_CHAR(RF.BUDGETYEAR),
    CCG.DEPARTMENTNAME, CCG.NAME,
    RF.ACTIVITYID, RF.PRODUCTID,
    RF.TOTALREFUNDAMOUNT, CAST(NULL AS NUMBER), CAST(NULL AS NUMBER),
    'SENDER', RF.BUDGETSOURCEID,
    T.ID, T.TRANSFERNO, '5', T.TOTALTRANSFERAMOUNT,
    SRCV.NAME, PLANV.NAME, ACTV.ACTIVITY_NAME, PRODV.NAME,
    TO_CHAR(T.ROUNDNO),
    T.ITEMDETAIL, CAT.BUDGET_TYPE_NAME, CAT.NAME,
    RF.BUDGETCODEID, RF.CATEGORYID, NULL, NULL
FROM OAGWBG_BUDGETTRANSFER T
JOIN OAGWBG_BUDGETRECEIVEREFUND RF ON RF.TRANSFERID = T.ID
LEFT JOIN OAGWBG_V_EXT_OAGGL_COST_CENTER_V     CCG   ON CCG.ID   = RF.COSTCENTERIDGIVER
LEFT JOIN OAGWBG_V_EXT_BUDGET_SOURCE_V         SRCV  ON SRCV.ID  = RF.BUDGETSOURCEID
LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_PLAN_V     PLANV ON PLANV.ID = RF.BUDGETPLANID
LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_ACTIVITY_V ACTV
       ON ACTV.ACTIVITY_ID = RF.ACTIVITYID AND ACTV.PLAN_ID = RF.BUDGETPLANID
LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_PRODUCT_V  PRODV
       ON PRODV.ID = RF.PRODUCTID AND PRODV.BUDGETPLANCODE_ID = RF.BUDGETPLANID
LEFT JOIN OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CAT   ON CAT.ID   = RF.CATEGORYID
WHERE T.TRANSFERTYPE = '4'
) U
-- ============================================================ บัญชีหลัก / รายจ่ายย่อย — join ด้วย CATEGORYID
LEFT JOIN (
    SELECT CATEGORYID,
           MIN(ACCOUNTNO)    KEEP (DENSE_RANK FIRST ORDER BY ACCOUNTNO, SUBACCOUNTNO) AS ACCOUNTNO,
           MIN(SUBACCOUNTNO) KEEP (DENSE_RANK FIRST ORDER BY ACCOUNTNO, SUBACCOUNTNO) AS SUBACCOUNTNO
    FROM   OAGWBG_V_EXT_OAGPO_EXPENSE_ACCOUNT_RULE_V
    GROUP  BY CATEGORYID
) RL ON RL.CATEGORYID = U.CATEGORYID
LEFT JOIN OAGWBG_V_EXT_OAGGL_ACCOUNT_V AV ON AV.ID = NVL(U.ACCOUNTNO, RL.ACCOUNTNO);
