--   *rule view มีหลายแถวต่อ CATEGORYID (แยกตามปี/ผลผลิต/กิจกรรม) join ตรง ๆ จะทำแถวบาน
--    จึงยุบเหลือ 1 แถวต่อ CATEGORYID ก่อน join (RL) — ตรวจ PREPROD 2026-10-09:
--    rule 1,443 แถว / 738 category และไม่มี category ไหนมีบัญชีหลัก+รายจ่ายย่อยเกิน 1 คู่
--    การยุบจึงไม่ทิ้งข้อมูล ถ้าอนาคตมี category ที่บัญชีต่างกันตามปี จะได้คู่ที่น้อยที่สุดคู่เดียว
--    (KEEP DENSE_RANK FIRST ให้บัญชีหลักกับรายจ่ายย่อยมาจากแถวเดียวกันเสมอ ไม่สลับคู่)
--   *join ครั้งเดียวที่ชั้นนอกของ UNION ALL ไม่ต้องใส่ซ้ำทุก branch
