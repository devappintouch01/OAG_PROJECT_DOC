-- deploy: view ใหม่สำหรับ "รายละเอียดแจ้งโอนกลับ" (ReportService region #19) — 2026-10-16
-- 1 แถว = 1 รายการ note (OAGWBG_BUDGETTRANSFERREQUESTITEM_NOTE) หรือ 1 item ที่ไม่มี note
--   ITEM_REQUESTAMOUNT ซ้ำทุกแถว note ของ item เดียวกัน → อย่า SUM ตรง ๆ ให้ใช้ LINE_REQUESTAMOUNT
--   (ยืนยันแล้ว: ยอด note รวมของ item = ITEM.REQUESTAMOUNT, ยอด item รวม = HEADER.TOTALREQUESTAMOUNT)
-- ใบโอนของบรรทัด (LINE_ROUNDNO) = ALLOCATEROUNDNO ของ note ถ้าไม่มี note ใช้เลขโอนของ receive ที่ item ผูก
--   ไม่ใช้ H.ALLOCATEROUNDNO เพราะเป็นแค่ใบที่ใช้ค้นตอนสร้างคำขอ (RQ700001 header 6910018 แต่ receive 6910010)
--   ROUNDNO เลียนแบบ OAGWBG_V_BUDGETRECEIVE (NVL(BAT.ROUNDNO, BT.ROUNDNO)) แต่ join ตารางตรง ไม่ผ่าน view นั้น (hard parse ช้า)
-- แหล่งเงินใช้ H.BUDGETSOURCEID (= I.FROMBUDGETSOURCE = segment 4 ใน GL) ไม่ใช่ I.BUDGETSOURCEID (200 = แหล่งปลายทาง)
-- BUDGETTYPECODE = segment 8 ของ GL account (เช่น 110001) — I.BUDGETTYPEID (2125) เป็น id ใช้สร้าง account ไม่ได้
-- ธนาคาร: OAGWBG_BUDGETTRANSFERREQUEST_COSTCENTER มี 1 แถวต่อ (คำขอ + ศูนย์ต้นทุน + แผนงาน + ประเภทรายจ่าย) ไม่ใช่ต่อ header
-- master ที่ไม่ unique ตาม ID (PRODUCT_V 21/15, ACTIVITY_V 22/10) จับคู่แบบเดียวกับ V_BUDGETRECEIVE แล้ว GROUP BY กันแถวแตก
-- ยอด งบประมาณ/กันไว้เบิก/เบิกจ่าย/คงเหลือ + TEMPLATE_NAME ไม่อยู่ใน view — ต้องดึงจาก EBS (insert BYPASS) ในโค้ด
-- ตรวจ: COUNT(view) = COUNT(item LEFT JOIN note) = 18 บน PREPROD 2026-10-16
-- v2 2026-10-19: เพิ่ม ITEM_NOTE (หมายเหตุรายการจากหน้าจอแจ้งโอนกลับ = ITEM.NOTE) และ NOTE_REMARK (หมายเหตุราย note = NOTE.REQBUDGETITEMNOTE)
--   ต่อท้ายคอลัมน์ ไม่เลื่อนตำแหน่งเดิม — ต้องรัน _brain_OAGBUDGET/20261019_TransferRequestNoteRemark/deploy_add_REQBUDGETITEMNOTE.sql ก่อน
--   ย้อน: rollback_v2_to_v1_OAGWBG_R_BUDGETTRANSFERREQUEST.sql
CREATE OR REPLACE FORCE EDITIONABLE VIEW "OAGWBG"."OAGWBG_R_BUDGETTRANSFERREQUEST" ("REQUESTID", "REQUESTNO", "REQUESTDATE", "BUDGETYEAR", "FROMBUDGETYEAR", "STATUSID", "STATUSNAME", "DEPARTMENTID", "DEPARTMENTNAME", "COSTCENTERID", "COSTCENTERNAME", "ALLOCATEROUNDNO", "BUDGETSOURCEID", "BUDGETSOURCENAME", "RESERVEDNO", "ITEMDETAIL", "TOTALREQUESTAMOUNT", "REQUESTITEMID", "BUDGETRECEIVEID", "RECEIVEROUNDNO", "ITEM_BUDGETYEAR", "ITEM_DEPARTMENTID", "ITEM_COSTCENTERID", "ITEM_COSTCENTERNAME", "BUDGETPLANID", "PLANNAME", "PRODUCTID", "PRODUCTNAME", "ACTIVITYID", "ACTIVITYNAME", "EXPENSETYPEID", "EXPENSETYPENAME", "BUDGETTYPEID", "BUDGETTYPECODE", "BUDGETTYPENAME", "CATEGORYID", "CATEGORYNAME", "BUDGETCODEID", "FROMBUDGETSOURCE", "ITEM_BUDGETSOURCEID", "ITEM_RESERVEDNO", "ITEM_REQUESTAMOUNT", "BALANCEATREQUEST", "REQUESTITEMNOTEID", "NOTESEQUENCE", "NOTE_ALLOCATEROUNDNO", "NOTE", "NOTE_ALLOCATEAMOUNT", "NOTE_REQUESTAMOUNT", "LINE_ROUNDNO", "LINE_REQUESTAMOUNT", "BANKACCOUNTGIVERID", "BANKACCOUNTNUM", "BANKACCOUNTNAME", "ITEM_NOTE", "NOTE_REMARK") AS
  WITH PROD AS (
    SELECT ID, BUDGETPLANCODE_ID, MAX(NAME) AS NAME
    FROM OAGWBG_V_EXT_OAGGL_BUDGET_PRODUCT_V
    GROUP BY ID, BUDGETPLANCODE_ID
),
ACT AS (
    SELECT ACTIVITY_ID, PLAN_ID, MAX(ACTIVITY_NAME) AS NAME
    FROM OAGWBG_V_EXT_OAGGL_BUDGET_ACTIVITY_V
    GROUP BY ACTIVITY_ID, PLAN_ID
),
BANK AS (
    SELECT RC.REQUESTID, RC.COSTCENTERID, RC.BUDGETPLANID, RC.EXPENSETYPEID,
           RC.BANKACCOUNTGIVERID, BA.BANK_ACCOUNT_NUM, BA.BANK_ACCOUNT_NAME,
           ROW_NUMBER() OVER (PARTITION BY RC.REQUESTID, RC.COSTCENTERID, RC.BUDGETPLANID, RC.EXPENSETYPEID
                              ORDER BY RC.ID) AS RN
    FROM OAGWBG_BUDGETTRANSFERREQUEST_COSTCENTER RC
    LEFT JOIN OAGWBG_V_EXT_OAGCE_BANK_ACCOUNT_V BA ON BA.BANK_ACCOUNT_ID = RC.BANKACCOUNTGIVERID
)
SELECT
    H.ID                                    AS REQUESTID,
    H.REQUESTNO,
    H.REQUESTDATE,
    H.BUDGETYEAR,
    H.FROMBUDGETYEAR,
    H.STATUSID,
    MS.NAME                                 AS STATUSNAME,
    H.DEPARTMENTID,
    HCC.DEPARTMENTNAME,
    H.COSTCENTERID,
    HCC.NAME                                AS COSTCENTERNAME,
    H.ALLOCATEROUNDNO,
    H.BUDGETSOURCEID,
    HBS.NAME                                AS BUDGETSOURCENAME,
    H.RESERVEDNO,
    H.ITEMDETAIL,
    H.TOTALREQUESTAMOUNT,
    I.ID                                    AS REQUESTITEMID,
    I.BUDGETRECEIVEID,
    NVL(BAT.ROUNDNO, BT.ROUNDNO)            AS RECEIVEROUNDNO,
    I.BUDGETYEAR                            AS ITEM_BUDGETYEAR,
    I.DEPARTMENTID                          AS ITEM_DEPARTMENTID,
    I.COSTCENTERID                          AS ITEM_COSTCENTERID,
    ICC.NAME                                AS ITEM_COSTCENTERNAME,
    I.BUDGETPLANID,
    PL.NAME                                 AS PLANNAME,
    I.PRODUCTID,
    PR.NAME                                 AS PRODUCTNAME,
    I.ACTIVITYID,
    AC.NAME                                 AS ACTIVITYNAME,
    CAT.EXPENSE_TYPE_ID                     AS EXPENSETYPEID,
    CAT.EXPENSE_TYPE_NAME                   AS EXPENSETYPENAME,
    I.BUDGETTYPEID,
    REGEXP_SUBSTR(CAT.BUDGET_TYPE_CODE, '[^.]+', 1, 3) AS BUDGETTYPECODE,
    CAT.BUDGET_TYPE_NAME                    AS BUDGETTYPENAME,
    I.CATEGORYID,
    CAT.NAME                                AS CATEGORYNAME,
    I.BUDGETCODEID,
    I.FROMBUDGETSOURCE,
    I.BUDGETSOURCEID                        AS ITEM_BUDGETSOURCEID,
    I.RESERVEDNO                            AS ITEM_RESERVEDNO,
    I.REQUESTAMOUNT                         AS ITEM_REQUESTAMOUNT,
    I.BALANCEATREQUEST,
    N.ID                                    AS REQUESTITEMNOTEID,
    N.SEQUENCE                              AS NOTESEQUENCE,
    N.ALLOCATEROUNDNO                       AS NOTE_ALLOCATEROUNDNO,
    N.NOTE,
    N.ALLOCATEAMOUNT                        AS NOTE_ALLOCATEAMOUNT,
    N.REQUESTAMOUNT                         AS NOTE_REQUESTAMOUNT,
    NVL(N.ALLOCATEROUNDNO, NVL(BAT.ROUNDNO, BT.ROUNDNO)) AS LINE_ROUNDNO,
    NVL(N.REQUESTAMOUNT, I.REQUESTAMOUNT)   AS LINE_REQUESTAMOUNT,
    BK.BANKACCOUNTGIVERID,
    BK.BANK_ACCOUNT_NUM                     AS BANKACCOUNTNUM,
    BK.BANK_ACCOUNT_NAME                    AS BANKACCOUNTNAME,
    I.NOTE                                  AS ITEM_NOTE,
    N.REQBUDGETITEMNOTE                     AS NOTE_REMARK
FROM OAGWBG_BUDGETTRANSFERREQUEST H
JOIN OAGWBG_BUDGETTRANSFERREQUESTITEM I
    ON I.REQUESTID = H.ID
LEFT JOIN OAGWBG_BUDGETTRANSFERREQUESTITEM_NOTE N
    ON N.REQUESTITEMID = I.ID
LEFT JOIN OAGWBG_MASTERSTATUS MS
    ON MS.ID = H.STATUSID
LEFT JOIN OAGWBG_V_EXT_OAGGL_COST_CENTER_V HCC
    ON HCC.ID = H.COSTCENTERID
LEFT JOIN OAGWBG_V_EXT_OAGGL_COST_CENTER_V ICC
    ON ICC.ID = I.COSTCENTERID
LEFT JOIN OAGWBG_V_EXT_BUDGET_SOURCE_V HBS
    ON HBS.ID = H.BUDGETSOURCEID
LEFT JOIN OAGWBG_BUDGETRECEIVE BR
    ON BR.ID = I.BUDGETRECEIVEID
LEFT JOIN OAGWBG_BUDGETALLOCATETRANSFER BAT
    ON BAT.ID = BR.BUDGETALLOCATETRANSFERID
LEFT JOIN OAGWBG_BUDGETTRANSFER BT
    ON BT.ID = BR.BUDGETTRANSFERID
LEFT JOIN OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CAT
    ON CAT.ID = I.CATEGORYID
LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_PLAN_V PL
    ON PL.ID = I.BUDGETPLANID
LEFT JOIN PROD PR
    ON PR.ID = I.PRODUCTID AND PR.BUDGETPLANCODE_ID = I.BUDGETPLANID
LEFT JOIN ACT AC
    ON AC.ACTIVITY_ID = I.ACTIVITYID AND AC.PLAN_ID = I.BUDGETPLANID
LEFT JOIN BANK BK
    ON BK.REQUESTID = H.ID
   AND BK.COSTCENTERID = I.COSTCENTERID
   AND BK.BUDGETPLANID = I.BUDGETPLANID
   AND BK.EXPENSETYPEID = CAT.EXPENSE_TYPE_ID
   AND BK.RN = 1
