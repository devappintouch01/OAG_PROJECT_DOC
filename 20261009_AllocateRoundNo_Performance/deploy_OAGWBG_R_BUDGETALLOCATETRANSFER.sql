-- OAGWBG_R_BUDGETALLOCATETRANSFER: เปลี่ยน join ศูนย์ต้นทุน (CC) จาก OR เป็น CASE — ดู README.md
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "OAGWBG"."OAGWBG_R_BUDGETALLOCATETRANSFER" ("BUDGETYEAR", "REGIONID", "REGIONNAME", "PLANID", "PLANNAME", "PRODUCTID", "PRODUCTNAME", "ACTIVITYID", "ACTIVITYNAME", "BOOKNO", "BOOKDATE", "ROUNDNO", "BANKACCOUNTNUMBERGIVER", "BANKACCOUNTNAMEGIVER", "TRANFEERDATE", "EXPENSETYPEID", "EXPENSETYPENAME", "BUDGET_TYPE_ID", "BUDGET_TYPE_NAME", "BUDGET_TYPE_CODE", "COSTCENTERID", "COSTCENTERNAME", "TOTALTRANSFERAMOUNT", "BANKACCOUNTNAME", "BANKACCOUNTNUMBER", "NOTE", "NOTE_SEQ", "BUDGETALLOCATETRANSFERID", "CODE", "CATEGORYNAME", "DEPARTMENTID", "DEPARTMENTNAME", "RECEIVENOTE", "BUDGETCODEID", "BUDGETSOURCEID", "BUDGETSOURCENAME", "BFR_YEAR", "CATEGORYID", "SUMMARYACCOUNTCODE", "BUDGETALLOCATETRANSFER_CATEGORY_ID", "BUDGETALLOCATETRANSFER_CATEGORY_REF") AS 
  SELECT
	  bt.BUDGETYEAR AS BUDGETYEAR,
	  bt.REGIONID AS REGIONID,
  	  VR.NAME AS REGIONNAME,
	  PLAN.ID AS PLANID,
	  PLAN.NAME AS PLANNAME,
	  BATC.PRODUCTID ,
	  VEOBPV.NAME AS PRODUCTNAME ,
	  BATC.ACTIVITYID ,
	  VEOBAV.ACTIVITY_NAME AS ACTIVITYNAME,
	  
	  bt.BOOKNO AS BOOKNO,
	  bt.BOOKDATE AS BOOKDATE,
	  bt.ROUNDNO AS ROUNDNO,
	  EOBAVG.BANK_ACCOUNT_NUM AS BANKACCOUNTNUMBERGIVER, -- เลขที่บัญชีผู้โอน
	  EOBAVG.BANK_ACCOUNT_NAME AS BANKACCOUNTNAMEGIVER,
	  bt.TRANSFERDATE AS TRANFEERDATE,
	  
	  CATC.EXPENSE_TYPE_ID   AS EXPENSETYPEID,
	  CATC.EXPENSE_TYPE_NAME AS EXPENSETYPENAME,
	  CATC.BUDGET_TYPE_ID,
	  CATC.BUDGET_TYPE_NAME,
	  CATC.BUDGET_TYPE_CODE,
	  CC.ID AS COSTCENTERID,
	  CC.NAME AS COSTCENTERNAME,
	  COALESCE( BACN.TOTALALLOCATEAMOUNT, BATC.TOTALALLOCATEAMOUNT,
	  			BATC.TOTALRECEIVEAMOUNT,BR.TOTALRECEIVEAMOUNT, 0 ) AS TOTALTRANSFERAMOUNT,
	  EOBAV.BANK_ACCOUNT_NAME AS BANKACCOUNTNAME,
	  EOBAV.BANK_ACCOUNT_NUM AS BANKACCOUNTNUMBER,
	  NVL(BACN.NOTE,BR.NOTE) AS NOTE,
	  NVL(BACN.SEQUENCE, 1) AS NOTE_SEQ,
	  
	  BR.BUDGETALLOCATETRANSFERID,
	  
	  -- ของรายงานที่ 13 
	  CATC.CODE,
	  CATC.NAME AS CATEGORYNAME,
	  --BATC.DEPARTMENTID,
	  CASE WHEN BATC.BUDGETSOURCEID = 100 THEN COALESCE(BATC.DEPARTMENTID, BR.DEPARTMENTID) ELSE COALESCE(BATC.DEPARTMENTID, BR.DEPARTMENTID) END AS DEPARTMENTID,
	  BR.DEPARTMENTNAME AS DEPARTMENTNAME,
	  NVL(BACN.NOTE,BR.NOTE) AS RECEIVENOTE,
	  BATC.BUDGETCODEID,
	  BATC.BUDGETSOURCEID,
	  BSOURCE.NAME AS BUDGETSOURCENAME,
	  BATC.BUDGETYEAR AS BFR_YEAR,
	  BATC.CATEGORYID AS CATEGORYID,
	  BATC.SUMMARYACCOUNTCODE AS SUMMARYACCOUNTCODE,
	  BATC.ID AS BUDGETALLOCATETRANSFER_CATEGORY_ID,
	  BATC.REF AS BUDGETALLOCATETRANSFER_CATEGORY_REF
	FROM OAGWBG_V_BUDGETALLOCATETRANSFER bt 
	INNER JOIN OAGWBG_BUDGETALLOCATETRANSFER_CATEGORY BATC
		ON BATC.BUDGETALLOCATETRANSFERID  = bt.ID
	LEFT JOIN OAGWBG_V_BUDGETRECEIVE BR
	    ON BATC.ID = BR.BUDGETALLOCATETRANSFERCATEGORYID  
	    
    LEFT JOIN OAGWBG_BUDGETALLOCATETRANSFER_COSTCENTER_NOTE BACN
    	ON BACN.RECEIVEID = BR.ID
		
	LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_PRODUCT_V VEOBPV 
	    ON BATC.PRODUCTID = VEOBPV.ID 
	    AND BATC.BUDGETPLANID = VEOBPV.BUDGETPLANCODE_ID
	
	LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_ACTIVITY_V VEOBAV 
	    ON BATC.ACTIVITYID = VEOBAV.ACTIVITY_ID 
	    AND BATC.BUDGETPLANID = VEOBAV.PLAN_ID
	
	LEFT JOIN OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CATC 
		ON CATC.ID = BATC.CATEGORYID
	
	LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_PLAN_V PLAN 
		ON PLAN.ID = BATC.BUDGETPLANID
	
	LEFT JOIN OAGWBG_BUDGETALLOCATETRANSFER_COSTCENTER BAC 
	  	ON BAC.BUDGETALLOCATETRANSFERID = BR.BUDGETALLOCATETRANSFERID 
	  	AND BAC.COSTCENTERID = BR.COSTCENTERID
	  	AND BAC.BUDGETPLANID = BR.BUDGETPLANID
	  	AND BAC.EXPENSETYPEID = NVL(CATC.EXPENSE_TYPE_ID,'0')
	  	AND BAC.BUDGETSOURCEID = BR.BUDGETSOURCEID
	  
	
	  	
	LEFT JOIN OAGWBG_V_EXT_OAGGL_COST_CENTER_V CC 
		-- เดิมใช้ OR (BR ก่อน ถ้า BR ไม่มีศูนย์ต้นทุนและเป็นแถวลูกใช้ของ BATC) — Oracle hash join เงื่อนไข OR ไม่ได้
		-- เขียนเป็น CASE ให้ได้ key เดียว ผลเหมือนเดิมทุกแถว
		ON CC.ID = CASE
		             WHEN BR.COSTCENTERID IS NOT NULL THEN BR.COSTCENTERID
		             WHEN BATC.REF IS NOT NULL THEN BATC.COSTCENTERID
		           END
    
	LEFT JOIN OAGWBG_V_EXT_OAGCE_BANK_ACCOUNT_V EOBAV 
	    ON BAC.BANKACCOUNTID = EOBAV.BANK_ACCOUNT_ID
	    
    LEFT JOIN OAGWBG_V_EXT_OAGCE_BANK_ACCOUNT_V EOBAVG 
	    ON BAC.BANKACCOUNTGIVERID = EOBAVG.BANK_ACCOUNT_ID
	    
	LEFT JOIN OAGWBG_V_REGION VR 
	    ON bt.REGIONID = VR.ID
	
	LEFT JOIN OAGWBG.OAGWBG_V_EXT_BUDGET_SOURCE_V BSOURCE
		ON BSOURCE.ID = BR.BUDGETSOURCEID
;
