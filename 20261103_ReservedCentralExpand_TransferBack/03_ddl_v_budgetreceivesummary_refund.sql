-- OAGWBG_V_BUDGETRECEIVESUMMARY_REFUND: เพิ่มยอด PO/PR ที่ขยายจากเงินกันส่วนกลาง (region C) เข้ามาเป็นบรรทัดงบ
--
-- ปัญหา: ค้นหน้าโอนกลับด้วยเลขที่เงินกัน (เช่น 681203) ได้แค่ถัง O ที่ศูนย์ต้นทุนส่วนกลาง
--   ยอด EXPAND_PO / EXPAND_PR อยู่ใน OAGWBG_BUDGETRESERVEDITEM อย่างเดียว ไม่มีแถวใน BUDGETRECEIVE
--   (681203: ยอดใบ 25,874,940 = ถัง O 25,837,440 + PO/PR รอบ 2570/3 37,500)
--
-- แก้ (ตกลงกับผู้ใช้ 2026-11-03):
--   - UNION ALL ไว้ "ก่อน" GROUP BY (CTE SRC) ไม่ใช่ต่อท้าย — ยอดขยาย (+) กับแถว 'E' ที่รับการตัด (−) ต้องรวมเป็นบรรทัดเดียว
--   - ยอดขยาย = SUM(USAGEAMOUNT) ของ EXPAND_PO/EXPAND_PR ใน "รอบล่าสุด" ของใบ (คู่ OVERLAPYEAR, OVERLAPROUND สูงสุด)
--     ไม่หัก CANCEL_* และไม่ยุ่งถัง O
--   - แถว 'E' นับเฉพาะรอบล่าสุด เพราะยอดขยายรอบใหม่ถูกกรอกโดยหักยอดที่โอนกลับไปแล้ว
--   - ครอบทุกใบ region C
--   - หาหมวด (CATEGORYID) และใบ (BUDGETRESERVEDCATEGORYID) จาก BUDGETRESERVED_CATEGORY ของใบเดียวกัน
--     ที่แผนงาน/ผลผลิต/กิจกรรมตรงกับ ACCOUNTCODE — มีหลายแถวให้เลือกตัวที่รหัสงบตรงก่อน
--     รายการที่จับคู่ไม่ได้จะหลุด (ดู verify_before ข้อ 3)
--   - ID: บรรทัดที่มีแถวจริงใช้ MIN(BUDGETRECEIVE.ID) เหมือนเดิม
--         บรรทัดที่มีแต่ยอดขยาย/แถว 'E' ใช้เลขติดลบที่คำนวณจาก key ของบรรทัด
--         ต้องคงที่ข้ามรอบ เพราะ BUDGETTRANSFERREQUESTITEM.BUDGETRECEIVEID เก็บ ID นี้ไว้
--   - คอลัมน์ใหม่ ISEXPANDLINE = 1 เมื่อบรรทัดมียอดขยายหรือแถว 'E' (ให้ API กรอง/แยกเส้นบันทึก)
--
-- ต้องรัน 01_alter_budgetreceive_add_expand_columns.sql ก่อน (CTE E_SRC อ่าน OVERLAPYEAR/OVERLAPROUND/BUDGETCODEID)
-- ลำดับ: verify_before_deploy.sql → 01 → ไฟล์นี้ → verify_after_deploy.sql (ถอยกลับ: 99_rollback.sql)

  CREATE OR REPLACE FORCE EDITIONABLE VIEW "OAGWBG"."OAGWBG_V_BUDGETRECEIVESUMMARY_REFUND" ("ID", "DEPARTMENTID", "DEPARTMENTNAME", "COSTCENTERID", "COSTCENTERNAME", "BUDGETYEAR", "BUDGETSOURCEID", "BUDGETCODEID", "CATEGORYID", "BUDGETTYPEID", "BUDGETTYPENAME", "CATEGORYNAME", "PRODUCTID", "PRODUCTNAME", "ACTIVITYID", "ACTIVITYNAME", "BUDGETPLANID", "PLANNAME", "TOTALREQUESTAMOUNT", "TOTALALLOCATEAMOUNT", "TOTALRECEIVEAMOUNT", "TOTALTRANSFERAMOUNT", "TOTALBALANCEAMOUNT", "REFUNDAMOUNT", "NOTE", "BUDGETRESERVEDCATEGORYID", "RESERVEDNO", "RESERVEDBUDGETYEAR", "EXPENSE_TYPE_ID", "EXPENSE_TYPE_NAME", "TOTALPAYMENTAMOUNT", "TOTALOBLIGATIONAMOUNT", "ISEXPANDLINE") AS
  WITH
-- ===== (1) แถวจริงใน BUDGETRECEIVE — เงื่อนไขและ COALESCE รหัสงบเหมือนฉบับ 20261006 ทุกตัว ย้ายมาเป็นระดับแถว =====
BR_SRC AS (
  SELECT
    BR.ID,
    BR.DEPARTMENTID,
    BR.COSTCENTERID,
    BR.BUDGETYEAR,
    NVL(BR.BUDGETSOURCEID, 100)         AS BUDGETSOURCEID,
    BR.CATEGORYID,
    BR.PRODUCTID,
    BR.ACTIVITYID,
    BR.BUDGETPLANID,
    BR.NOTE,
    BR.BUDGETRESERVEDCATEGORYID,
    COALESCE(
      BCC_A.BUDGETCODEID,
      BCC_G.BUDGETCODEID,
      DECODE(BR.BUDGETRECEIVETYPE, 'G', BMC_O.BUDGETCODEID, 'A', BMC_R.BUDGETCODEID),
      BCY_P1.BUDGETCODEID,
      BCY_P2.BUDGETCODEID,
      RSC.BUDGETCODEID
    )                                   AS BUDGETCODEID,
    NVL(BR.TOTALRECEIVEAMOUNT,  0)      AS TOTALRECEIVEAMOUNT,
    NVL(BR.TOTALTRANSFERAMOUNT, 0)      AS TOTALTRANSFERAMOUNT,
    NVL(BR.TOTALBALANCEAMOUNT,  0)      AS TOTALBALANCEAMOUNT,
    NVL(BR.REFUNDAMOUNT,        0)      AS REFUNDAMOUNT,
    NVL(BR.TOTALPAYMENTAMOUNT,    0)    AS TOTALPAYMENTAMOUNT,
    NVL(BR.TOTALOBLIGATIONAMOUNT, 0)    AS TOTALOBLIGATIONAMOUNT,
    0                                   AS ISEXPAND
  FROM OAGWBG_V_BUDGETRECEIVE BR

  LEFT JOIN OAGWBG_BUDGETALLOCATETRANSFER_CATEGORY BCC_A
    ON  BR.BUDGETRECEIVETYPE     = 'A'
    AND BCC_A.ID                 = BR.BUDGETALLOCATETRANSFERCATEGORYID

  LEFT JOIN OAGWBG_BUDGETALLOCATETRANSFER_CATEGORY BCC_G
    ON  BR.BUDGETRECEIVETYPE     = 'G'
    AND BR.BUDGETRECEIVEPERIODID IS NULL
    AND BCC_G.ID                 = BR.BUDGETALLOCATETRANSFERCATEGORYID

  LEFT JOIN OAGWBG_BUDGETRECEIVE BRT
    ON  BR.BUDGETRECEIVETYPE IN ('A', 'G')
    AND BRT.ID                   = BR.ID
  LEFT JOIN OAGWBG_BUDGETALLOCATETRANSFERMORE_CATEGORY BMC_O
    ON  BR.BUDGETRECEIVETYPE IN ('A', 'G')
    AND BRT.BUDGETALLOCATETRANSFERMORECATEGORYID IS NOT NULL
    AND BMC_O.ID                 = BRT.BUDGETALLOCATETRANSFERMORECATEGORYID
  LEFT JOIN OAGWBG_BUDGETALLOCATETRANSFERMORE_CATEGORY BMC_R
    ON  BR.BUDGETRECEIVETYPE     = 'A'
    AND BMC_R.ID                 = BMC_O.PARENTID

  LEFT JOIN OAGWBG_BUDGETRECEIVEPERIOD BRP
    ON  BR.BUDGETRECEIVETYPE     NOT IN ('A')
    AND BRP.ID                   = BR.BUDGETRECEIVEPERIODID

  LEFT JOIN OAGWBG_BUDGETCODE_YEAR BCY_P1
    ON  BR.BUDGETRECEIVETYPE     NOT IN ('A')
    AND BRP.PERIOD_TYPE          = 1
    AND BCY_P1.BUDGETYEAR        = BR.BUDGETYEAR
    AND BCY_P1.CATEGORYID        = BR.CATEGORYID
    AND BCY_P1.PRODUCTID         = BR.PRODUCTID
    AND BCY_P1.ACTIVITYCODEID    = BR.ACTIVITYID

  LEFT JOIN OAGWBG_BUDGETCODEMORE_YEAR BCY_P2
    ON  BR.BUDGETRECEIVETYPE     NOT IN ('A')
    AND NVL(BRP.PERIOD_TYPE, 0)  != 1
    AND BCY_P2.BUDGETYEAR        = BR.BUDGETYEAR
    AND BCY_P2.CATEGORYID        = BR.CATEGORYID
    AND BCY_P2.PRODUCTID         = BR.PRODUCTID
    AND BCY_P2.ACTIVITYCODEID    = BR.ACTIVITYID
    AND BCY_P2.BUDGETGOVERNMENTID = BRP.BUDGETGOVERNMENTID
    AND BCY_P2.BUDGETSOURCEID    = BRP.BUDGETSOURCEID

  LEFT JOIN OAGWBG_BUDGETRESERVED_CATEGORY RSC
    ON  RSC.ID = BR.BUDGETRESERVEDCATEGORYID

  -- 'E' ไม่อ่านจากตรงนี้ — ต้องกรองรอบล่าสุด ซึ่ง OAGWBG_V_BUDGETRECEIVE ไม่มีคอลัมน์รอบ (ดู E_SRC)
  WHERE BR.BUDGETRECEIVETYPE NOT IN ('T', 'R', 'E')
),

-- ===== (2) รอบล่าสุดของใบเงินกันส่วนกลาง — คู่ (ปี, รอบ) สูงสุดของรายการทุกชนิดในใบ =====
LR AS (
  SELECT
    I.BUDGETREVERSEDID                                                                AS BUDGETRESERVEDID,
    MAX(I.OVERLAPYEAR)  KEEP (DENSE_RANK LAST ORDER BY I.OVERLAPYEAR, I.OVERLAPROUND) AS OVERLAPYEAR,
    MAX(I.OVERLAPROUND) KEEP (DENSE_RANK LAST ORDER BY I.OVERLAPYEAR, I.OVERLAPROUND) AS OVERLAPROUND
  FROM OAGWBG_BUDGETRESERVEDITEM I
  JOIN OAGWBG_BUDGETRESERVED RS
    ON  RS.ID                   = I.BUDGETREVERSEDID
    AND RS.BUDGETRESERVEDREGION = 'C'
  WHERE I.OVERLAPYEAR IS NOT NULL
    AND I.OVERLAPROUND IS NOT NULL
  GROUP BY I.BUDGETREVERSEDID
),

-- ===== (3) ยอดขยาย PO/PR รอบล่าสุด แตก ACCOUNTCODE 13 segment =====
EXP_ITEM AS (
  SELECT
    I.ID,
    I.BUDGETREVERSEDID                          AS BUDGETRESERVEDID,
    NVL(I.USAGEAMOUNT, 0)                       AS USAGEAMOUNT,
    REGEXP_SUBSTR(I.ACCOUNTCODE, '[^.]+', 1, 1) AS S1,
    REGEXP_SUBSTR(I.ACCOUNTCODE, '[^.]+', 1, 2) AS S2,
    REGEXP_SUBSTR(I.ACCOUNTCODE, '[^.]+', 1, 3) AS S3,
    REGEXP_SUBSTR(I.ACCOUNTCODE, '[^.]+', 1, 4) AS S4,
    REGEXP_SUBSTR(I.ACCOUNTCODE, '[^.]+', 1, 5) AS S5,
    REGEXP_SUBSTR(I.ACCOUNTCODE, '[^.]+', 1, 6) AS S6,
    REGEXP_SUBSTR(I.ACCOUNTCODE, '[^.]+', 1, 7) AS S7,
    REGEXP_SUBSTR(I.ACCOUNTCODE, '[^.]+', 1, 9) AS S9
  FROM OAGWBG_BUDGETRESERVEDITEM I
  JOIN LR
    ON  LR.BUDGETRESERVEDID = I.BUDGETREVERSEDID
    AND LR.OVERLAPYEAR      = I.OVERLAPYEAR
    AND LR.OVERLAPROUND     = I.OVERLAPROUND
  WHERE I.BUDGETRESERVEDTYPE IN ('EXPAND_PO', 'EXPAND_PR')
    AND I.ACCOUNTCODE IS NOT NULL
),

-- หมวดของรายการ: BUDGETRESERVED_CATEGORY ของใบเดียวกันที่ แผนงาน/ผลผลิต/กิจกรรม ตรง — หลายตัวเลือกรหัสงบตรงก่อน
EXP_MAP AS (
  SELECT
    E.*,
    C.ID          AS RSCID,
    C.CATEGORYID,
    ROW_NUMBER() OVER (
      PARTITION BY E.ID
      ORDER BY CASE WHEN C.BUDGETCODEID = E.S9 THEN 0 ELSE 1 END, C.ID
    )             AS RN
  FROM EXP_ITEM E
  JOIN OAGWBG_BUDGETRESERVED_CATEGORY C
    ON  C.BUDGETRESERVEDID = E.BUDGETRESERVEDID
    AND C.BUDGETPLANID     = E.S5
    AND C.PRODUCTID        = E.S6
    AND C.ACTIVITYID       = E.S7
),

EXP_SRC AS (
  SELECT
    -M.ID                               AS ID,
    M.S1                                AS DEPARTMENTID,
    M.S2                                AS COSTCENTERID,
    2500 + TO_NUMBER(M.S3)              AS BUDGETYEAR,
    M.S4                                AS BUDGETSOURCEID,
    M.CATEGORYID,
    M.S6                                AS PRODUCTID,
    M.S7                                AS ACTIVITYID,
    M.S5                                AS BUDGETPLANID,
    CAST(NULL AS VARCHAR2(2000))        AS NOTE,
    M.RSCID                             AS BUDGETRESERVEDCATEGORYID,
    M.S9                                AS BUDGETCODEID,
    M.USAGEAMOUNT                       AS TOTALRECEIVEAMOUNT,
    0                                   AS TOTALTRANSFERAMOUNT,
    M.USAGEAMOUNT                       AS TOTALBALANCEAMOUNT,
    0                                   AS REFUNDAMOUNT,
    0                                   AS TOTALPAYMENTAMOUNT,
    0                                   AS TOTALOBLIGATIONAMOUNT,
    1                                   AS ISEXPAND
  FROM EXP_MAP M
  WHERE M.RN = 1
),

-- ===== (4) แถว 'E' ที่รับการตัดยอด — เฉพาะรอบล่าสุดของใบ (อ่านตารางจริง เพราะ view ฐานไม่มีคอลัมน์รอบ) =====
E_SRC AS (
  SELECT
    B.ID,
    B.DEPARTMENTID,
    B.COSTCENTERID,
    B.BUDGETYEAR,
    NVL(B.BUDGETSOURCEID, 100)          AS BUDGETSOURCEID,
    B.CATEGORYID,
    B.PRODUCTID,
    B.ACTIVITYID,
    B.BUDGETPLANID,
    B.NOTE,
    B.BUDGETRESERVEDCATEGORYID,
    B.BUDGETCODEID,
    NVL(B.TOTALRECEIVEAMOUNT,  0)       AS TOTALRECEIVEAMOUNT,
    NVL(B.TOTALTRANSFERAMOUNT, 0)       AS TOTALTRANSFERAMOUNT,
    NVL(B.TOTALBALANCEAMOUNT,  0)       AS TOTALBALANCEAMOUNT,
    NVL(B.REFUNDAMOUNT,        0)       AS REFUNDAMOUNT,
    NVL(B.TOTALPAYMENTAMOUNT,    0)     AS TOTALPAYMENTAMOUNT,
    NVL(B.TOTALOBLIGATIONAMOUNT, 0)     AS TOTALOBLIGATIONAMOUNT,
    1                                   AS ISEXPAND
  FROM OAGWBG_BUDGETRECEIVE B
  JOIN OAGWBG_BUDGETRESERVED_CATEGORY C
    ON  C.ID = B.BUDGETRESERVEDCATEGORYID
  JOIN LR
    ON  LR.BUDGETRESERVEDID = C.BUDGETRESERVEDID
    AND LR.OVERLAPYEAR      = B.OVERLAPYEAR
    AND LR.OVERLAPROUND     = B.OVERLAPROUND
  WHERE B.BUDGETRECEIVETYPE = 'E'
),

SRC AS (
  SELECT * FROM BR_SRC
  UNION ALL
  SELECT * FROM EXP_SRC
  UNION ALL
  SELECT * FROM E_SRC
),

BR_GRP AS (
  SELECT
    -- บรรทัดที่มีแถวจริง: MIN(ID) เหมือนเดิม / บรรทัดขยายล้วน: เลขติดลบจาก key (คงที่ข้ามรอบ, ไม่ชน ID จริง)
    NVL(
      MIN(CASE WHEN S.ISEXPAND = 0 THEN S.ID END),
      -(S.BUDGETRESERVEDCATEGORYID * 100000
        + MOD(ORA_HASH(S.DEPARTMENTID || '|' || S.COSTCENTERID || '|' || S.BUDGETYEAR || '|' || S.BUDGETSOURCEID || '|' ||
                       S.CATEGORYID || '|' || S.PRODUCTID || '|' || S.ACTIVITYID || '|' || S.BUDGETPLANID || '|' ||
                       S.BUDGETCODEID), 100000))
    )                                   AS ID,
    S.DEPARTMENTID,
    S.COSTCENTERID,
    S.BUDGETYEAR,
    S.BUDGETSOURCEID,
    S.CATEGORYID,
    S.PRODUCTID,
    S.ACTIVITYID,
    S.BUDGETPLANID,
    MAX(S.NOTE)                         AS NOTE,
    S.BUDGETRESERVEDCATEGORYID,
    MAX(RS.TRANSFERNO)                  AS RESERVEDNO,
    MAX(RS.BUDGETYEAR)                  AS RESERVEDBUDGETYEAR,
    S.BUDGETCODEID,
    SUM(S.TOTALRECEIVEAMOUNT)           AS TOTALRECEIVEAMOUNT,
    SUM(S.TOTALTRANSFERAMOUNT)          AS TOTALTRANSFERAMOUNT,
    SUM(S.TOTALBALANCEAMOUNT)           AS TOTALBALANCEAMOUNT,
    SUM(S.REFUNDAMOUNT)                 AS REFUNDAMOUNT,
    SUM(S.TOTALPAYMENTAMOUNT)           AS TOTALPAYMENTAMOUNT,
    SUM(S.TOTALOBLIGATIONAMOUNT)        AS TOTALOBLIGATIONAMOUNT,
    MAX(S.ISEXPAND)                     AS ISEXPANDLINE
  FROM SRC S
  LEFT JOIN OAGWBG_BUDGETRESERVED_CATEGORY RSC
    ON  RSC.ID = S.BUDGETRESERVEDCATEGORYID
  LEFT JOIN OAGWBG_BUDGETRESERVED RS
    ON  RS.ID  = RSC.BUDGETRESERVEDID
  GROUP BY
    S.DEPARTMENTID,
    S.COSTCENTERID,
    S.BUDGETYEAR,
    S.BUDGETSOURCEID,
    S.CATEGORYID,
    S.PRODUCTID,
    S.ACTIVITYID,
    S.BUDGETPLANID,
    S.BUDGETRESERVEDCATEGORYID,
    S.BUDGETCODEID
),

CC_DIM AS (
  SELECT
    ID,
    MAX(DEPARTMENTNAME) AS DEPARTMENTNAME,
    MAX(NAME)           AS NAME
  FROM OAGWBG_V_EXT_OAGGL_COST_CENTER_V
  GROUP BY ID
),

EXTCC_DIM AS (
  SELECT
    ID,
    MAX(NAME)             AS NAME,
    MAX(BUDGET_TYPE_ID)   AS BUDGET_TYPE_ID,
    MAX(BUDGET_TYPE_NAME) AS BUDGET_TYPE_NAME,
    MAX(EXPENSE_TYPE_ID)  AS EXPENSE_TYPE_ID,
    MAX(EXPENSE_TYPE_NAME) AS  EXPENSE_TYPE_NAME
  FROM OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V
  GROUP BY ID
),

BP_DIM AS (
  SELECT ID, MAX(NAME) AS DESCRIPTION
  FROM OAGWBG_V_EXT_OAGGL_BUDGET_PRODUCT_V
  GROUP BY ID
),

BA_DIM AS (
  SELECT ACTIVITY_ID, MAX(ACTIVITY_NAME) AS DESCRIPTION
  FROM OAGWBG_V_EXT_OAGGL_BUDGET_ACTIVITY_V
  GROUP BY ACTIVITY_ID
),

P_DIM AS (
  SELECT ID, NAME AS PLANNAME
  FROM OAGWBG_V_EXT_OAGGL_BUDGET_PLAN_V
  GROUP BY ID, NAME
)

SELECT
  A.ID,
  A.DEPARTMENTID,
  CC.DEPARTMENTNAME,
  A.COSTCENTERID,
  CC.NAME                 AS COSTCENTERNAME,
  A.BUDGETYEAR,
  A.BUDGETSOURCEID,
  A.BUDGETCODEID,
  A.CATEGORYID,
  EXTCC.BUDGET_TYPE_ID    AS BUDGETTYPEID,
  EXTCC.BUDGET_TYPE_NAME  AS BUDGETTYPENAME,
  EXTCC.NAME              AS CATEGORYNAME,
  A.PRODUCTID,
  BP.DESCRIPTION          AS PRODUCTNAME,
  A.ACTIVITYID,
  BA.DESCRIPTION          AS ACTIVITYNAME,
  A.BUDGETPLANID,
  PD.PLANNAME             AS PLANNAME,
  0                       AS TOTALREQUESTAMOUNT,
  0                       AS TOTALALLOCATEAMOUNT,
  A.TOTALRECEIVEAMOUNT,
  A.TOTALTRANSFERAMOUNT,
  A.TOTALBALANCEAMOUNT,
  A.REFUNDAMOUNT,
  A.NOTE,
  A.BUDGETRESERVEDCATEGORYID,
  A.RESERVEDNO,
  A.RESERVEDBUDGETYEAR,
  EXTCC.EXPENSE_TYPE_ID AS EXPENSE_TYPE_ID,
  EXTCC.EXPENSE_TYPE_NAME AS EXPENSE_TYPE_NAME,
  A.TOTALPAYMENTAMOUNT,
  A.TOTALOBLIGATIONAMOUNT,
  A.ISEXPANDLINE

FROM BR_GRP A
LEFT JOIN CC_DIM    CC    ON CC.ID          = A.COSTCENTERID
LEFT JOIN EXTCC_DIM EXTCC ON EXTCC.ID       = A.CATEGORYID
LEFT JOIN BP_DIM    BP    ON BP.ID          = A.PRODUCTID
LEFT JOIN BA_DIM    BA    ON BA.ACTIVITY_ID = A.ACTIVITYID
LEFT JOIN P_DIM     PD    ON PD.ID          = A.BUDGETPLANID
ORDER BY
  A.BUDGETYEAR,
  A.DEPARTMENTID,
  A.COSTCENTERID,
  A.BUDGETSOURCEID,
  A.CATEGORYID,
  A.PRODUCTID,
  A.ACTIVITYID,
  A.BUDGETPLANID;
