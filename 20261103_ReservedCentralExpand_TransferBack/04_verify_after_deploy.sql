-- รันหลัง deploy 01 + 03 (ก่อนขึ้นโค้ด API) — แต่ละข้อรันแยกได้
-- ค่าในวงเล็บ "PREPROD" = ผลที่คาดจาก 02_verify_before_deploy.sql เมื่อ 2026-11-03

-- (1) view ใช้ได้ + ยอดรวม: ISEXPANDLINE = 0 ต้องเท่ากับ "OLD" ในข้อ (2) ของ 02 ทุกช่อง
--     PREPROD: 0 → 17,369 แถว / BAL 17,133,467,112.59 ; 1 → 4 แถว / 44,000
SELECT ISEXPANDLINE, COUNT(*) N, SUM(TOTALBALANCEAMOUNT) BAL, SUM(TOTALRECEIVEAMOUNT) RCV, SUM(REFUNDAMOUNT) RF
  FROM OAGWBG.OAGWBG_V_BUDGETRECEIVESUMMARY_REFUND
 GROUP BY ISEXPANDLINE;

-- (2) บรรทัดขยาย — PREPROD: 681203 ที่ 2900600001 = 24,500 / 2900600014 = 5,000 / 2900600027 = 8,000
--                          68030001 ที่ 2900600001 = 6,500 — ID ติดลบทั้งหมด
SELECT ID, DEPARTMENTID, COSTCENTERID, BUDGETYEAR, BUDGETSOURCEID, BUDGETCODEID, CATEGORYID, CATEGORYNAME,
       TOTALRECEIVEAMOUNT, TOTALBALANCEAMOUNT, REFUNDAMOUNT, BUDGETRESERVEDCATEGORYID, RESERVEDNO
  FROM OAGWBG.OAGWBG_V_BUDGETRECEIVESUMMARY_REFUND
 WHERE ISEXPANDLINE = 1
 ORDER BY RESERVEDNO, COSTCENTERID;

-- (3) หลังทดสอบบันทึกใบโอนกลับจากบรรทัดขยาย: แถว 'E' ที่ถูกสร้าง
--     คาดว่า: TOTALRECEIVEAMOUNT = 0, TOTALBALANCEAMOUNT = −ยอดโอนกลับ, REFUNDAMOUNT = +ยอดโอนกลับ
--             BUDGETRESERVEDID ว่าง, OVERLAPYEAR/OVERLAPROUND = รอบล่าสุดของใบ, 1 แถวต่อบรรทัดต่อรอบ
SELECT B.ID, B.DEPARTMENTID, B.COSTCENTERID, B.BUDGETYEAR, B.BUDGETSOURCEID, B.CATEGORYID, B.BUDGETCODEID,
       B.BUDGETRESERVEDCATEGORYID, B.BUDGETRESERVEDID, B.OVERLAPYEAR, B.OVERLAPROUND,
       B.TOTALRECEIVEAMOUNT, B.TOTALBALANCEAMOUNT, B.REFUNDAMOUNT, B.CREATEON
  FROM OAGWBG.OAGWBG_BUDGETRECEIVE B
 WHERE B.BUDGETRECEIVETYPE = 'E'
 ORDER BY B.ID;

-- (4) link ของใบโอนกลับที่ตัดจากแถว 'E' — GIVERID ต้องชี้แถว 'E' ใน (3) ยอดรวมต้องเท่ากับ REFUNDAMOUNT ของแถวนั้น
SELECT RF.TRANSFERID, RF.GIVERID, SUM(RF.TOTALREFUNDAMOUNT) AS LINK_AMOUNT
  FROM OAGWBG.OAGWBG_BUDGETRECEIVEREFUND RF
  JOIN OAGWBG.OAGWBG_BUDGETRECEIVE B ON B.ID = RF.GIVERID AND B.BUDGETRECEIVETYPE = 'E'
 GROUP BY RF.TRANSFERID, RF.GIVERID
 ORDER BY RF.TRANSFERID;

-- (5) แถว 'E' ห้ามซ้ำในรอบเดียวกัน — ต้องได้ 0 แถว
SELECT BUDGETRESERVEDCATEGORYID, DEPARTMENTID, COSTCENTERID, BUDGETYEAR, CATEGORYID, BUDGETCODEID, OVERLAPYEAR, OVERLAPROUND, COUNT(*)
  FROM OAGWBG.OAGWBG_BUDGETRECEIVE
 WHERE BUDGETRECEIVETYPE = 'E'
 GROUP BY BUDGETRESERVEDCATEGORYID, DEPARTMENTID, COSTCENTERID, BUDGETYEAR, CATEGORYID, BUDGETCODEID, OVERLAPYEAR, OVERLAPROUND
HAVING COUNT(*) > 1;
