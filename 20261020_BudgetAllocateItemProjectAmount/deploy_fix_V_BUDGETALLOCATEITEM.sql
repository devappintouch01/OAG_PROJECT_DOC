-- แก้ยอดโครงการ (BUDGETFORMTYPEID = 2) ใน OAGWBG_V_BUDGETALLOCATEITEM เป็น 0 ทุกแถว
--
-- สาเหตุ: CTE BG join PJ_ALLOCATE ด้วย PJ.ID = BG.PROJECTID
--         แต่ PJ_ALLOCATE.ID = MIN(BG.ID) (ID แถวงบประมาณ) ไม่ใช่ ID โครงการ → ไม่เคย match
-- แก้:    join ด้วย PROJECTID + CATEGORYID + BUDGETYEAR (คีย์ที่ PJ_ALLOCATE GROUP BY)
--         เปลี่ยนบรรทัดเดียว ที่เหลือเหมือน DDL สดจาก PREPROD วันที่ 2026-10-20 ทุกตัวอักษร
--
-- ทดสอบก่อน deploy (PREPROD 2026-10-20):
--   COUNT เท่าเดิม 1,893 แถว / MINUS สองทางต่างกัน 44 แถว = แถวโครงการปี 2569 ทั้งหมด
--   แถวแผนงาน (form 1) ไม่เปลี่ยน
-- ทดสอบ PROD (2026-10-20, อ่านอย่างเดียว):
--   DDL ของ view ใน PROD ตรงกับ PREPROD ทุกตัวอักษร (มีบั๊กเดียวกัน) → ใช้ไฟล์นี้กับ PROD ได้
--   COUNT เท่าเดิม 1,897 แถว / MINUS สองทางต่างกัน 44 แถว = โครงการปี 2569 form 2 ทั้งหมด
--   ยอดรวมที่เพิ่มขึ้นเท่ากับ PREPROD: TOTALREQUESTAMOUNT +109,356,663 / TOTALALLOCATEAMOUNT +87,291,458
-- Rollback: rollback_V_BUDGETALLOCATEITEM_before.sql
-- =====================================================================

CREATE OR REPLACE FORCE EDITIONABLE VIEW "OAGWBG"."OAGWBG_V_BUDGETALLOCATEITEM" ("BUDGETYEAR", "CREATEON", "BUDGET_PLAN_ID", "BUDGET_PLAN_NAME", "BUDGET_TYPE_ID", "BUDGET_TYPE_NAME", "CODE", "EXPENSETYPEID", "CATEGORY_ID", "CATEGORY_NAME", "DUMMY_FLAG", "BUDGETGOVERNMENTTYPE", "BUDGETREQUESTID", "PARENTID", "BUDGET_GOVERNMENT_ID", "PROJECTID", "BUDGETDETAIL", "BUDGETFORMTYPEID", "BUDGETSTATUS", "ITEMDETAIL", "TOTALREQUESTSIMMARYAMOUNT", "TOTALREQUESTAMOUNT", "TOTALREQUESTSUMADJUSTAMOUNT", "ALLOCATEID", "TOTALALLOCATEAMOUNT", "KEPTCENTRALID", "KEPTCENTRAL", "ADJUSTEDID", "TOTALADJUSTEDAMOUNT", "REQUESTADJUSTID", "TOTALREQUESTADJUSTAMOUNT", "BUDGETCODEID", "BUDGETCODEYEARID", "PRODUCTID", "ACTIVITYCODEID", "PRODUCTNAME", "ACTIVITYNAME") AS 
  WITH 
    BCY_CAT_DIM AS (
        SELECT
		    BUDGETYEAR,
		    CATEGORYID,
		    PRODUCTID,
		    ACTIVITYCODEID,
		    MIN(BUDGETCODEID) AS BUDGETCODEID,
		    MIN(ID) AS ID
		FROM OAGWBG_BUDGETCODE_YEAR
		WHERE CATEGORYID IS NOT NULL
		GROUP BY BUDGETYEAR, CATEGORYID, PRODUCTID, ACTIVITYCODEID
    ),

    BCY_PROJ_DIM AS (
        SELECT
            BUDGETYEAR,
            PROJECTID,
            MIN(BUDGETCODEID) AS BUDGETCODEID,
            MIN(ID) AS ID
        FROM OAGWBG_BUDGETCODE_YEAR
        WHERE PROJECTID IS NOT NULL
        GROUP BY BUDGETYEAR, PROJECTID
    ),

    BG4 AS (
	    SELECT
	        REF_BUDGETGOVERNMENTID,
	        SUM(NVL(KEPTCENTRAL,0)) AS KEPTCENTRAL,
	        MAX(ID) KEEP (
	            DENSE_RANK FIRST ORDER BY ID
	        ) AS ID
	    FROM OAGWBG_BUDGETGOVERNMENT
	    WHERE BUDGETGOVERNMENTTYPE = 4
	    GROUP BY REF_BUDGETGOVERNMENTID
	),

    PJ_ALLOCATE AS (
        SELECT
            BG.BUDGETYEAR,
            BG.CATEGORYID,
            BG.PROJECTID,
            MIN(BG.ID) AS ID,
            SUM(NVL(PT.ALLOCATEDBUDGET, 0)) AS TOTALALLOCATEAMOUNT
        FROM OAGWBG_BUDGETGOVERNMENT BG
        LEFT JOIN OAGWBG_PROJECTTARGETS PT ON PT.PROJECTID = BG.PROJECTID
        WHERE BG.BUDGETFORMTYPEID = 2
            AND BG.PROJECTID IS NOT NULL
        GROUP BY BG.BUDGETYEAR, BG.CATEGORYID, BG.PROJECTID
    ),

	BG AS (
	    SELECT
	        BG.ID,
	        BG.BUDGETYEAR,
	        BG.CREATEON,
	        BG.BUDGETFORMTYPEID,
	        BG.CATEGORYID,
	        BG.BUDGETSTATUS,
	        BG.PROJECTID,
	        BG.BUDGETPLANID,
	        BG.PRODUCTID,
	        BG.ACTIVITYCODEID,
	        BG.EXPENSETYPEID,
	        BG.BUDGETEXPENSETYPEID,
	        BG.BUDGETREQUESTID,
	        BG4.REF_BUDGETGOVERNMENTID,
	        CASE
	        	WHEN BUDGETFORMTYPEID = 1 THEN NVL(BG.TOTALREQUESTAMOUNT, 0)
	        	ELSE NVL(PJ.TOTALALLOCATEAMOUNT, 0)
	        END AS REQ_AMOUNT,
	        NVL(BG4.KEPTCENTRAL, 0) AS KEPT_AMOUNT
	    FROM OAGWBG_BUDGETGOVERNMENT BG
	    LEFT JOIN BG4 ON BG.ID = BG4.REF_BUDGETGOVERNMENTID
		LEFT JOIN PJ_ALLOCATE PJ ON PJ.PROJECTID = BG.PROJECTID AND PJ.CATEGORYID = BG.CATEGORYID AND PJ.BUDGETYEAR = BG.BUDGETYEAR
	    WHERE BG.BUDGETSTATUS IN ('B','C')
	        AND BG.BUDGETFORMTYPEID IN (1, 2)
	        AND BG.BUDGETREQUESTID IS NOT NULL
	        AND ( BG.BUDGETGOVERNMENTTYPE = '7' OR BG.BUDGETGOVERNMENTTYPE IS NULL )
	        AND BG.BUDGETREQUESTID NOT IN (
	            SELECT DISTINCT PARENTID
	            FROM OAGWBG_BUDGETREQUEST
	            WHERE PARENTID IS NOT NULL
	        )
	        AND (
	            BG.PROJECTID NOT IN (
	                SELECT DISTINCT TEMP
	                FROM OAGWBG_PROJECT
	                WHERE TEMP IS NOT NULL
	            )
	            OR BG.PROJECTID IS NULL
	        )
    ),

	BG5 AS (
	    SELECT
	        BG.BUDGETYEAR,
	        BG.CATEGORYID,
	        BG.BUDGETPLANID AS BUDGET_PLAN_ID,
	        BG.PRODUCTID,
	        BG.ACTIVITYCODEID,
	        MIN(BG.ID) AS ADJUSTEDID,
	        SUM(NVL(BG.TOTALADJUSTEDAMOUNT, 0)) AS TOTALADJUSTEDAMOUNT
	    FROM OAGWBG_BUDGETGOVERNMENT BG
	    WHERE BG.BUDGETGOVERNMENTTYPE = '5'
	        AND BG.BUDGETFORMTYPEID = 1
	    GROUP BY BG.BUDGETYEAR, BG.CATEGORYID, BG.BUDGETPLANID, BG.PRODUCTID, BG.ACTIVITYCODEID
	),
    
    BG6 AS (
        SELECT
	        BG.BUDGETYEAR,
	        BG.CATEGORYID,
	        BG.BUDGETPLANID AS BUDGET_PLAN_ID,
	        BG.PRODUCTID,
	        BG.ACTIVITYCODEID,
	        MIN(BG.ID) AS ALLOCATEID,
	        SUM(NVL(BG.TOTALALLOCATEAMOUNT, 0)) AS TOTALALLOCATEAMOUNT
	    FROM OAGWBG_BUDGETGOVERNMENT BG
	    WHERE BG.BUDGETGOVERNMENTTYPE = '6'
	        AND BG.BUDGETFORMTYPEID = 1
	    GROUP BY BG.BUDGETYEAR, BG.CATEGORYID, BG.BUDGETPLANID, BG.PRODUCTID, BG.ACTIVITYCODEID
    ),
	
	BG8 AS (
	    SELECT
	        BG.BUDGETYEAR,
	        BG.CATEGORYID,
	        BG.BUDGETPLANID AS BUDGET_PLAN_ID,
	        BG.PRODUCTID,
	        BG.ACTIVITYCODEID,
	        SUM(NVL(BG.TOTALREQUESTADJUSTAMOUNT, 0)) AS SUM_REQ_ADJ_8,
	        MIN(BG.ID) AS ANY_8_ID
	    FROM OAGWBG_BUDGETGOVERNMENT BG
	    WHERE BG.BUDGETGOVERNMENTTYPE = '8'
	        AND BG.BUDGETFORMTYPEID = 1
	    GROUP BY BG.BUDGETYEAR, BG.CATEGORYID, BG.BUDGETPLANID, BG.PRODUCTID, BG.ACTIVITYCODEID
	),
	
	NON_YES_BASE AS (
		SELECT
			MIN(BG.ID) AS ID,
			BG.BUDGETYEAR,
	        MIN(BG.CREATEON) AS CREATEON,
	        BG.BUDGETFORMTYPEID,
	        BG.CATEGORYID,
	        BG.BUDGETSTATUS,
	        BG.PROJECTID,
	        BG.BUDGETPLANID AS BUDGET_PLAN_ID,
	        BG.PRODUCTID,
	        BG.ACTIVITYCODEID,
	        BG.EXPENSETYPEID,
	        BG.BUDGETEXPENSETYPEID,
	        BG.BUDGETREQUESTID,
	        SUM(REQ_AMOUNT) AS TOTALREQUESTAMOUNT,
	        SUM(KEPT_AMOUNT) AS TOTALKEPTCENTRAL
		FROM BG
		LEFT JOIN OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CC
			ON CC.ID = BG.CATEGORYID
		WHERE NVL(CC.DUMMY_FLAG, 'NO') <> 'YES'
		GROUP BY 
			BG.BUDGETYEAR,
	        BG.BUDGETFORMTYPEID,
	        BG.CATEGORYID,
	        BG.BUDGETSTATUS,
	        BG.PROJECTID,
	        BG.BUDGETPLANID,
	        BG.PRODUCTID,
	        BG.ACTIVITYCODEID,
	        BG.EXPENSETYPEID,
	        BG.BUDGETEXPENSETYPEID,
	        BG.BUDGETREQUESTID
	),
	ALL_NON_YES AS (
        SELECT
            BG.BUDGETYEAR,
            BG.CREATEON,
            BG.BUDGET_PLAN_ID,
            BG.BUDGETEXPENSETYPEID AS BUDGET_TYPE_ID,
            BG.CATEGORYID AS CATEGORY_ID,
            BG.EXPENSETYPEID,
            'REQ' AS BUDGETGOVERNMENTTYPE,
            BG.BUDGETREQUESTID AS BUDGETREQUESTID,
            BR.PARENTID,
            BG.ID AS BUDGET_GOVERNMENT_ID,
            BG.PROJECTID,
            CAST(NULL AS VARCHAR2(4000)) AS BUDGETDETAIL,
            COALESCE(BG.BUDGETFORMTYPEID, 1) AS BUDGETFORMTYPEID,
            BG.BUDGETSTATUS,
            NVL(BG.TOTALREQUESTAMOUNT, 0) + NVL(BG.TOTALKEPTCENTRAL, 0) AS TOTALREQUESTSIMMARYAMOUNT,
            NVL(BG.TOTALREQUESTAMOUNT, 0) AS TOTALREQUESTAMOUNT,
            NVL(BG.TOTALREQUESTAMOUNT, 0) + NVL(BG.TOTALKEPTCENTRAL, 0) + NVL(BG8.SUM_REQ_ADJ_8, 0) AS TOTALREQUESTSUMADJUSTAMOUNT,
            CASE
                WHEN COALESCE(BG.BUDGETFORMTYPEID, 1) = 1 THEN BG6.ALLOCATEID
                WHEN COALESCE(BG.BUDGETFORMTYPEID, 1) = 2 THEN BG.ID
                ELSE BG6.ALLOCATEID
            END AS ALLOCATEID,
            CASE
                WHEN COALESCE(BG.BUDGETFORMTYPEID, 1) = 1 THEN NVL(BG6.TOTALALLOCATEAMOUNT, 0)
                WHEN COALESCE(BG.BUDGETFORMTYPEID, 1) = 2 THEN NVL(BG.TOTALREQUESTAMOUNT, 0)
                ELSE NVL(BG6.TOTALALLOCATEAMOUNT, 0)
            END AS TOTALALLOCATEAMOUNT,
            0 AS KEPTCENTRALID,
            NVL(BG.TOTALKEPTCENTRAL, 0) AS KEPTCENTRAL,
            BG5.ADJUSTEDID,
            NVL(BG5.TOTALADJUSTEDAMOUNT, 0) AS TOTALADJUSTEDAMOUNT,
            BG8.ANY_8_ID AS REQUESTADJUSTID,
            NVL(BG8.SUM_REQ_ADJ_8, 0) AS TOTALREQUESTADJUSTAMOUNT,
            COALESCE(BCY_CAT.BUDGETCODEID, BCY_PROJ.BUDGETCODEID) AS BUDGETCODEID,
            COALESCE(BCY_CAT.ID, BCY_PROJ.ID) AS BUDGETCODEYEARID,
            BG.PRODUCTID,
            BG.ACTIVITYCODEID
        FROM NON_YES_BASE BG
        LEFT JOIN OAGWBG_BUDGETREQUEST BR
        	ON BR.ID = BG.BUDGETREQUESTID
		LEFT JOIN BG5
		    ON BG5.BUDGETYEAR = BG.BUDGETYEAR
		    AND BG5.CATEGORYID = BG.CATEGORYID
		    AND (BG5.BUDGET_PLAN_ID = BG.BUDGET_PLAN_ID OR (BG5.BUDGET_PLAN_ID IS NULL AND BG.BUDGET_PLAN_ID IS NULL))
		    AND (BG5.PRODUCTID = BG.PRODUCTID OR (BG5.PRODUCTID IS NULL AND BG.PRODUCTID IS NULL))
		    AND (BG5.ACTIVITYCODEID = BG.ACTIVITYCODEID OR (BG5.ACTIVITYCODEID IS NULL AND BG.ACTIVITYCODEID IS NULL))
        LEFT JOIN BG6
		    ON BG6.BUDGETYEAR = BG.BUDGETYEAR
		    AND BG6.CATEGORYID = BG.CATEGORYID
		    AND (BG6.BUDGET_PLAN_ID = BG.BUDGET_PLAN_ID OR (BG6.BUDGET_PLAN_ID IS NULL AND BG.BUDGET_PLAN_ID IS NULL))
		    AND (BG6.PRODUCTID = BG.PRODUCTID OR (BG6.PRODUCTID IS NULL AND BG.PRODUCTID IS NULL))
		    AND (BG6.ACTIVITYCODEID = BG.ACTIVITYCODEID OR (BG6.ACTIVITYCODEID IS NULL AND BG.ACTIVITYCODEID IS NULL))
		LEFT JOIN BG8
		    ON BG8.BUDGETYEAR = BG.BUDGETYEAR
		    AND BG8.CATEGORYID = BG.CATEGORYID
		    AND (BG8.BUDGET_PLAN_ID = BG.BUDGET_PLAN_ID OR (BG8.BUDGET_PLAN_ID IS NULL AND BG.BUDGET_PLAN_ID IS NULL))
		    AND (BG8.PRODUCTID = BG.PRODUCTID OR (BG8.PRODUCTID IS NULL AND BG.PRODUCTID IS NULL))
		    AND (BG8.ACTIVITYCODEID = BG.ACTIVITYCODEID OR (BG8.ACTIVITYCODEID IS NULL AND BG.ACTIVITYCODEID IS NULL))
        LEFT JOIN BCY_CAT_DIM BCY_CAT
            ON BCY_CAT.BUDGETYEAR = BG.BUDGETYEAR
            AND BCY_CAT.CATEGORYID = BG.CATEGORYID
            AND BCY_CAT.PRODUCTID = BG.PRODUCTID
            AND BCY_CAT.ACTIVITYCODEID = BG.ACTIVITYCODEID
        LEFT JOIN BCY_PROJ_DIM BCY_PROJ
            ON BCY_PROJ.BUDGETYEAR = BG.BUDGETYEAR
            AND BCY_PROJ.PROJECTID = BG.PROJECTID
    ),
    FINAL_NON_YES AS (
    	SELECT
            BUDGETYEAR,
		    MIN(CREATEON) AS CREATEON,
		    BUDGET_PLAN_ID,
		    BUDGET_TYPE_ID,
		    MIN(EXPENSETYPEID) AS EXPENSETYPEID,
		    CATEGORY_ID,
		    MIN(BUDGETGOVERNMENTTYPE) AS BUDGETGOVERNMENTTYPE,
		    MIN(BUDGETREQUESTID) AS BUDGETREQUESTID,
		    MIN(PARENTID) AS PARENTID,
		    MIN(BUDGET_GOVERNMENT_ID) AS BUDGET_GOVERNMENT_ID,
		    MIN(PROJECTID) AS PROJECTID,
		    MIN(BUDGETDETAIL) AS BUDGETDETAIL,
		    MIN(BUDGETFORMTYPEID) AS BUDGETFORMTYPEID,
		    MIN(BUDGETSTATUS) AS BUDGETSTATUS,
		    SUM(TOTALREQUESTSIMMARYAMOUNT) AS TOTALREQUESTSIMMARYAMOUNT,
		    SUM(TOTALREQUESTAMOUNT) AS TOTALREQUESTAMOUNT,
		    (SUM(TOTALREQUESTSIMMARYAMOUNT) + MAX(TOTALREQUESTADJUSTAMOUNT)) AS TOTALREQUESTSUMADJUSTAMOUNT,
		    MIN(ALLOCATEID) AS ALLOCATEID,
		    MAX(TOTALALLOCATEAMOUNT) AS TOTALALLOCATEAMOUNT,
		    MIN(KEPTCENTRALID) AS KEPTCENTRALID,
		    MAX(KEPTCENTRAL) AS KEPTCENTRAL,
		    MIN(ADJUSTEDID) AS ADJUSTEDID,
		    MAX(TOTALADJUSTEDAMOUNT) AS TOTALADJUSTEDAMOUNT,
		    MIN(REQUESTADJUSTID) AS REQUESTADJUSTID,
		    MAX(TOTALREQUESTADJUSTAMOUNT) AS TOTALREQUESTADJUSTAMOUNT,
		    MIN(BUDGETCODEID) AS BUDGETCODEID,
		    MIN(BUDGETCODEYEARID) AS BUDGETCODEYEARID,
		    MIN(PRODUCTID) AS PRODUCTID,
		    MIN(ACTIVITYCODEID) AS ACTIVITYCODEID
    	FROM ALL_NON_YES
		GROUP BY
		    BUDGETYEAR,
		    BUDGET_PLAN_ID,
		    BUDGET_TYPE_ID,
		    CATEGORY_ID,
		    PRODUCTID,
		    ACTIVITYCODEID
    ),
    FINAL_YES_BG AS (
    	SELECT
            BG.BUDGETYEAR,
            BG.CREATEON,
            BG.BUDGETPLANID AS BUDGET_PLAN_ID,
            BG.BUDGETEXPENSETYPEID AS BUDGET_TYPE_ID,
            BG.EXPENSETYPEID,
            BG.CATEGORYID AS CATEGORY_ID,
            'DUMMY' AS BUDGETGOVERNMENTTYPE,
            BG.BUDGETREQUESTID AS BUDGETREQUESTID,
            BR.PARENTID,
            BG.ID AS BUDGET_GOVERNMENT_ID,
            BG.PROJECTID,
            CAST(NULL AS VARCHAR2(4000)) AS BUDGETDETAIL,
            COALESCE(BG.BUDGETFORMTYPEID, 1) AS BUDGETFORMTYPEID,
            BG.BUDGETSTATUS,
            NVL(BG.REQ_AMOUNT, 0) + NVL(BG.KEPT_AMOUNT, 0) AS TOTALREQUESTSIMMARYAMOUNT,
            NVL(BG.REQ_AMOUNT, 0) AS TOTALREQUESTAMOUNT,
            NVL(BG.REQ_AMOUNT, 0) + NVL(BG.KEPT_AMOUNT, 0) AS TOTALREQUESTSUMADJUSTAMOUNT,
            0 AS ALLOCATEID,
            0 AS TOTALALLOCATEAMOUNT,
            0 AS KEPTCENTRALID,
            NVL(BG.KEPT_AMOUNT, 0) AS KEPTCENTRAL,
            0 AS ADJUSTEDID,
            0 AS TOTALADJUSTEDAMOUNT,
            0 AS REQUESTADJUSTID,
            0 AS TOTALREQUESTADJUSTAMOUNT,
            COALESCE(BCY_CAT.BUDGETCODEID, BCY_PROJ.BUDGETCODEID) AS BUDGETCODEID,
            COALESCE(BCY_CAT.ID, BCY_PROJ.ID) AS BUDGETCODEYEARID,
            BG.PRODUCTID,
            BG.ACTIVITYCODEID
        FROM BG
        LEFT JOIN OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CC
			ON CC.ID = BG.CATEGORYID
        LEFT JOIN OAGWBG_BUDGETREQUEST BR
        	ON BR.ID = BG.BUDGETREQUESTID
    	LEFT JOIN BCY_CAT_DIM BCY_CAT
            ON BCY_CAT.BUDGETYEAR = BG.BUDGETYEAR
            AND BCY_CAT.CATEGORYID = BG.CATEGORYID
            AND BCY_CAT.PRODUCTID = BG.PRODUCTID
            AND BCY_CAT.ACTIVITYCODEID = BG.ACTIVITYCODEID
        LEFT JOIN BCY_PROJ_DIM BCY_PROJ
            ON BCY_PROJ.BUDGETYEAR = BG.BUDGETYEAR
            AND BCY_PROJ.PROJECTID = BG.PROJECTID
        WHERE NVL(CC.DUMMY_FLAG, 'NO') = 'YES'
    ),
    ALL_DATA AS (
    	SELECT * FROM FINAL_NON_YES
    	UNION ALL
    	SELECT * FROM FINAL_YES_BG
    )
	SELECT
	    BG.BUDGETYEAR,
	    BG.CREATEON,
	    CC.BUDGET_PLAN_ID,
	    CC.BUDGET_PLAN_NAME,
	    CC.BUDGET_TYPE_ID,
	    CC.BUDGET_TYPE_NAME,
	    CC.CODE,
	    CC.EXPENSE_TYPE_ID AS EXPENSETYPEID,
	    BG.CATEGORY_ID,
	    CC.NAME AS CATEGORY_NAME,
	    CC.DUMMY_FLAG,
	    BG.BUDGETGOVERNMENTTYPE,
	    BG.BUDGETREQUESTID,
	    BG.PARENTID,
	    BG.BUDGET_GOVERNMENT_ID,
	    BG.PROJECTID,
	    BG.BUDGETDETAIL,
	    BG.BUDGETFORMTYPEID,
	    BG.BUDGETSTATUS,
	    CASE
            WHEN COALESCE(BG.BUDGETFORMTYPEID, 1) = 1 THEN CC.NAME
            ELSE PJ.PROJECTNAME
        END AS ITEMDETAIL,
	    BG.TOTALREQUESTSIMMARYAMOUNT,
	    BG.TOTALREQUESTAMOUNT,
	    BG.TOTALREQUESTSUMADJUSTAMOUNT,
	    BG.ALLOCATEID,
	    BG.TOTALALLOCATEAMOUNT,
	    BG.KEPTCENTRALID,
	    BG.KEPTCENTRAL,
	    BG.ADJUSTEDID,
	    BG.TOTALADJUSTEDAMOUNT,
	    BG.REQUESTADJUSTID,
	    BG.TOTALREQUESTADJUSTAMOUNT,
	    BG.BUDGETCODEID,
	    BG.BUDGETCODEYEARID,
	    BG.PRODUCTID,
	    BG.ACTIVITYCODEID,
	    PV.NAME AS PRODUCTNAME,
    	AC.ACTIVITY_NAME AS ACTIVITYNAME
	FROM ALL_DATA BG
	LEFT JOIN OAGWBG_PROJECT PJ ON PJ.ID = BG.PROJECTID
	LEFT JOIN OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CC
		ON CC.ID = BG.CATEGORY_ID
	LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_ACTIVITY_V AC
	    ON AC.ACTIVITY_ID = CASE WHEN BG.ACTIVITYCODEID = 0 THEN '00000' ELSE TO_CHAR(BG.ACTIVITYCODEID) END
	   AND AC.BUDGETPLANID = BG.BUDGET_PLAN_ID
	LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_PRODUCT_V PV
	    ON PV.ID = CASE WHEN BG.PRODUCTID = 0 THEN '00000' ELSE TO_CHAR(BG.PRODUCTID) END
	   AND BG.BUDGET_PLAN_ID = PV.BUDGETPLAN_ID
	ORDER BY
	    BUDGETYEAR,
	    BUDGET_PLAN_ID,
	    PRODUCTID,
	    ACTIVITYCODEID,
	    CATEGORY_ID
