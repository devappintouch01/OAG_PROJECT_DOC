-- ตรวจหลังรัน deploy_R_KTBPAYMENT.sql
-- ผลที่ PREPROD 2026-10-16 (ก่อน deploy ทดสอบด้วยการรันตัว SELECT ของ DDL ใหม่):
--   TRANSFERTYPE 1 = 4831, 2 = 29 (เดิม 77), 3 = 14, 4 = 21, 5 = 16

-- 1) view ต้อง VALID
SELECT OBJECT_NAME, STATUS, LAST_DDL_TIME FROM USER_OBJECTS WHERE OBJECT_NAME = 'OAGWBG_R_KTBPAYMENT';

-- 2) จำนวนแถวแยกตามประเภท — มีแค่ TRANSFERTYPE 2 ที่ควรเปลี่ยน
SELECT TRANSFERTYPE, COUNT(*) N, SUM(TRANFERAMOUNT) AMT FROM OAGWBG_R_KTBPAYMENT GROUP BY TRANSFERTYPE ORDER BY 1;

-- 3) TRANSFERTYPE 2 ต้องเป็น 1 แถวต่อ 1 แถวบัญชี ยอดเท่ากับตารางบัญชี (คาดไว้: 29 แถว ยอดรวม 524,291,528 ทั้งสองฝั่ง)
SELECT 'KTB view' SRC, COUNT(*) N, SUM(TRANFERAMOUNT) AMT FROM OAGWBG_R_KTBPAYMENT WHERE TRANSFERTYPE = '2'
UNION ALL
SELECT 'BANKACCOUNT', COUNT(*), SUM(rb.TOTALTRANSFERAMOUNT)
FROM OAGWBG_BUDGETRESERVED_BANKACCOUNT rb
JOIN OAGWBG_BUDGETRESERVED r ON r.ID = rb.RESERVEDID
JOIN OAGWBG.OAGWBG_V_EXT_OAGGL_COST_CENTER_V COSTV ON r.COSTCENTERID = COSTV.ID
WHERE r.STATUSID IN (20202, 90102, 90109, 90201) AND r.ROUNDINTERFACE IS NOT NULL;

-- 4) ใบที่เคยซ้ำ: 2 (681230) เดิม 25 แถว / 17 (681253) เดิม 3 แถว → ต้องเหลือใบละ 1 แถว
SELECT RESERVEDID, COUNT(*) N, SUM(TRANFERAMOUNT) AMT FROM OAGWBG_R_KTBPAYMENT WHERE TRANSFERTYPE = '2' AND RESERVEDID IN (2, 17) GROUP BY RESERVEDID ORDER BY 1;
