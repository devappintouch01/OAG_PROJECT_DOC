-- Q1 overview: headers / mismatched headers / mismatched items per region + reserve year (2 first digits of header no)
WITH X AS (
  SELECT H.ID HID, H.BUDGETRESERVEDREGION REGION, SUBSTR(TRIM(H.TRANSFERNO),1,2) YY, TRIM(H.TRANSFERNO) HNO,
         I.ID IID, REGEXP_REPLACE(TRIM(I.TRANSFERNO),'[.-][0-9]+$','') IBASE
  FROM OAGWBG_BUDGETRESERVED H JOIN OAGWBG_BUDGETRESERVEDITEM I ON I.BUDGETREVERSEDID = H.ID
)
SELECT REGION, YY, COUNT(DISTINCT HID) HEADERS,
       COUNT(DISTINCT CASE WHEN IBASE IS NULL OR IBASE <> HNO THEN HID END) BAD_HEADERS,
       COUNT(*) ITEMS,
       SUM(CASE WHEN IBASE IS NULL OR IBASE <> HNO THEN 1 ELSE 0 END) BAD_ITEMS
FROM X GROUP BY REGION, YY ORDER BY REGION, YY
--;;
-- Q2 mismatched headers detail (+ interface batches sent with item no vs header no)
WITH X AS (
  SELECT H.ID HID, TRIM(H.TRANSFERNO) HNO, I.ID IID, REGEXP_REPLACE(TRIM(I.TRANSFERNO),'[.-][0-9]+$','') IBASE
  FROM OAGWBG_BUDGETRESERVED H JOIN OAGWBG_BUDGETRESERVEDITEM I ON I.BUDGETREVERSEDID = H.ID
), B AS (
  SELECT HID, COUNT(*) ITEMS, SUM(CASE WHEN IBASE IS NULL OR IBASE <> HNO THEN 1 ELSE 0 END) BAD_ITEMS,
         LISTAGG(DISTINCT NVL(IBASE,'(null)'), ',') WITHIN GROUP (ORDER BY IBASE) ITEM_NOS
  FROM X GROUP BY HID HAVING SUM(CASE WHEN IBASE IS NULL OR IBASE <> HNO THEN 1 ELSE 0 END) > 0
), L AS (
  SELECT DISTINCT WEB_BATCH_NO, STATUS FROM OAGWBG_LOG_INTERFACE WHERE ACTION_NAME LIKE '%BudgetReserved%'
)
SELECT H.ID, TRIM(H.TRANSFERNO) HNO, H.BUDGETRESERVEDREGION RG, H.BUDGETRESERVEDTYPE TP, H.STATUSID, H.ROUNDINTERFACE RND,
       TO_CHAR(H.CREATEON,'YYYY-MM-DD') CREATED, B.ITEMS, B.BAD_ITEMS, B.ITEM_NOS,
       (SELECT COUNT(*) FROM L WHERE L.WEB_BATCH_NO LIKE '%\_' || TRIM(H.TRANSFERNO) || '\_%' ESCAPE '\') LOG_BY_HNO,
       (SELECT COUNT(*) FROM L WHERE L.STATUS='S' AND EXISTS (SELECT 1 FROM X WHERE X.HID=H.ID AND X.IBASE<>X.HNO
                 AND L.WEB_BATCH_NO LIKE '%\_' || X.IBASE || '\_%' ESCAPE '\')) LOG_S_BY_ITEMNO
FROM OAGWBG_BUDGETRESERVED H JOIN B ON B.HID = H.ID
ORDER BY H.BUDGETRESERVEDREGION, H.ID
--;;
-- Q3 duplicate item numbers: same item base no used under >1 header
WITH X AS (
  SELECT DISTINCT H.ID HID, TRIM(H.TRANSFERNO) HNO, REGEXP_REPLACE(TRIM(I.TRANSFERNO),'[.-][0-9]+$','') IBASE
  FROM OAGWBG_BUDGETRESERVED H JOIN OAGWBG_BUDGETRESERVEDITEM I ON I.BUDGETREVERSEDID = H.ID
)
SELECT IBASE, COUNT(DISTINCT HID) HEADERS, LISTAGG(HID || ':' || HNO, ', ') WITHIN GROUP (ORDER BY HID) HEADER_LIST
FROM X WHERE IBASE IS NOT NULL GROUP BY IBASE HAVING COUNT(DISTINCT HID) > 1 ORDER BY IBASE
--;;
-- Q4 duplicate header numbers
SELECT TRIM(TRANSFERNO) HNO, COUNT(*) CNT, LISTAGG(ID, ',') WITHIN GROUP (ORDER BY ID) IDS
FROM OAGWBG_BUDGETRESERVED GROUP BY TRIM(TRANSFERNO) HAVING COUNT(*) > 1 ORDER BY 1
--;;
-- Q5 header number length distribution (manual numbers are 6 digits, system numbers 8)
SELECT BUDGETRESERVEDREGION RG, LENGTH(TRIM(TRANSFERNO)) LEN, COUNT(*) CNT, MIN(TRANSFERNO) MIN_NO, MAX(TRANSFERNO) MAX_NO
FROM OAGWBG_BUDGETRESERVED GROUP BY BUDGETRESERVEDREGION, LENGTH(TRIM(TRANSFERNO)) ORDER BY 1,2
--;;
-- Q6 bank account no vs header no
SELECT COUNT(*) BANK_ROWS, SUM(CASE WHEN TRIM(BA.TRANSFERNO) <> TRIM(H.TRANSFERNO) OR BA.TRANSFERNO IS NULL THEN 1 ELSE 0 END) BAD_BANK_ROWS
FROM OAGWBG_BUDGETRESERVED_BANKACCOUNT BA JOIN OAGWBG_BUDGETRESERVED H ON H.ID = BA.RESERVEDID

--;;
-- B1 bank rows mismatched vs header: what number do they hold?
SELECT H.ID HID, TRIM(H.TRANSFERNO) HNO, BA.ID BAID, BA.TRANSFERNO BANK_NO,
       (SELECT MAX(I.TRANSFERNO) FROM OAGWBG_BUDGETRESERVEDITEM I WHERE I.BUDGETREVERSEDID=H.ID) ITEM_NO
FROM OAGWBG_BUDGETRESERVED_BANKACCOUNT BA JOIN OAGWBG_BUDGETRESERVED H ON H.ID = BA.RESERVEDID
ORDER BY H.ID, BA.ID
--;;
-- B2 interface batches for region P (SaveBudgetReserved*) grouped
SELECT ACTION_NAME, STATUS, WEB_BATCH_NO, COUNT(*) LINES, MIN(TO_CHAR(CREATEON,'YYYY-MM-DD HH24:MI')) FIRST_ON
FROM OAGWBG_LOG_INTERFACE
WHERE ACTION_NAME LIKE '%BudgetReserved%' AND (WEB_BATCH_NO LIKE '%\_68%' ESCAPE '\' OR WEB_BATCH_NO LIKE '%\_69%' ESCAPE '\')
GROUP BY ACTION_NAME, STATUS, WEB_BATCH_NO ORDER BY FIRST_ON
--;;
-- B3 header 2 items (25 items, round 2)
SELECT I.ID, I.PARENTID, I.TRANSFERNO, I.RESERVEDNO_ADD, I.BOOKNUMBER, I.STATUSID, I.BUDGETRESERVEDTYPE, I.OVERLAPYEAR, I.OVERLAPROUND, I.APPROVE, TO_CHAR(I.CREATEON,'YYYY-MM-DD') CR
FROM OAGWBG_BUDGETRESERVEDITEM I WHERE I.BUDGETREVERSEDID = 2 ORDER BY I.ID
--;;
-- B4 all headers (region C too) with item count
SELECT H.ID, H.BUDGETRESERVEDREGION RG, TRIM(H.TRANSFERNO) HNO, H.TRANSFERNUMBER, H.STATUSID, H.BUDGETYEAR,
       TO_CHAR(H.CREATEON,'YYYY-MM-DD HH24:MI') CREATED, TO_CHAR(H.UPDATEON,'YYYY-MM-DD HH24:MI') UPDATED,
       (SELECT COUNT(*) FROM OAGWBG_BUDGETRESERVEDITEM I WHERE I.BUDGETREVERSEDID=H.ID) ITEMS
FROM OAGWBG_BUDGETRESERVED H ORDER BY H.ID
--;;
-- B5 any other table holding a reserved no that may be stale (receive batch no)
SELECT ID, BATCHNAME, ROUNDNO, RUNNING, RECEIVEID, INTERFACETYPE, TO_CHAR(CREATEON,'YYYY-MM-DD HH24:MI') CR
FROM OAGWBG_RECEIVE_BATCH_NO WHERE BATCHNAME LIKE '%CARRY_FORWARD%' ORDER BY ID
