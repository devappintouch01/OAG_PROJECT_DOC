CREATE OR REPLACE FORCE EDITIONABLE VIEW "OAGWBG"."OAGWBG_R_BUDGETTRANSFERCONTROL" ("CATEGORYID", "CATEGORYNAME", "ACTIVITYID", "ACTIVITYNAME", "PRODUCTID", "PRODUCTNAME", "BUDGETPLANID", "BUDGETPLANNAME", "BUDGETYEAR", "COSTCENTERNAME", "DEPARTMENTNAME", "ROUNDNO", "BUDGETSOURCEID", "BUDGETSOURCENAME", "COSTCENTERID", "DEPARTMENTID", "TRANSFERDATE", "TOTALBALANCEAMOUNT", "TRANSFERDEPT", "BUDGETRECEIVETYPE_NAME", "NOTE", "NOTE_SEQ", "STATUSNAME") AS 
  WITH SRC AS (
  SELECT
    RC.CATEGORYID,
    RC.CATEGORYNAME,
    RC.ACTIVITYID,
    RC.ACTIVITYNAME,
    RC.PRODUCTID,
    RC.PRODUCTNAME,
    RC.BUDGETPLANID,
    RC.PLANNAME AS BUDGETPLANNAME,
     CASE
      WHEN RC.BUDGETRECEIVETYPE = 'A' AND RC.BUDGETSOURCEID = 400
        THEN BAT.BUDGETYEAR
      ELSE RC.BUDGETYEAR
    END AS BUDGETYEAR,
    RC.COSTCENTERNAME,
    RC.DEPARTMENTNAME,
    RC.ROUNDNO,
    RC.BUDGETSOURCEID,
    BSV.NAME AS BUDGETSOURCENAME,
    RC.COSTCENTERID,
    RC.DEPARTMENTID,
   CASE
      WHEN RC.BUDGETRECEIVETYPE = 'A' THEN BAT.TRANSFERDATE
      WHEN RC.BUDGETRECEIVETYPE = 'J' THEN TF.TRANSFERDATE
      WHEN RC.BUDGETRECEIVETYPE = 'G' THEN TF.TRANSFERDATE
      WHEN RC.BUDGETRECEIVETYPE = 'T' THEN TF.TRANSFERDATE
      WHEN RC.BUDGETRECEIVETYPE = 'R' THEN TF.TRANSFERDATE
      WHEN RC.BUDGETRECEIVETYPE = 'O' THEN TF.TRANSFERDATE ELSE TF.TRANSFERDATE END AS TRANSFERDATE,
    RC.TOTALBALANCEAMOUNT,
    RC.BUDGETRECEIVETYPE,
    CASE 
      -- หลักที่ 3 ของเลขที่โอน: 1/3 = สบง., 2/4 = สบอ.
      -- (3/4 = running ของโอนเปลี่ยนแปลงงบประมาณ + โอนปรับเงินเหลือจ่าย เริ่ม 2026-10-16)
      WHEN SUBSTR(RC.ROUNDNO, 3, 1) IN ('1', '3') THEN 'สบง.'
      WHEN SUBSTR(RC.ROUNDNO, 3, 1) IN ('2', '4') THEN 'สบอ.'
      ELSE NULL
    END AS TRANSFERDEPT,
    CASE
      WHEN RC.BUDGETRECEIVETYPE = 'A' THEN 'โอนจัดสรร'
      WHEN RC.BUDGETRECEIVETYPE = 'J' THEN 'โอนเปลี่ยนแปลง'
      WHEN RC.BUDGETRECEIVETYPE = 'G' THEN 'บันทึกรับเงินจากกรมบัญชีกลาง'
      WHEN RC.BUDGETRECEIVETYPE = 'T' THEN 'โอนกลับ'
      WHEN RC.BUDGETRECEIVETYPE = 'R' THEN 'โอนปรับเงินเหลือจ่าย'
      WHEN RC.BUDGETRECEIVETYPE = 'O' THEN 'กันเหลื่อมปี'
      ELSE RC.BUDGETRECEIVETYPE
    END AS BUDGETRECEIVETYPE_NAME,
    NVL(BACN.NOTE, RC.NOTE) AS NOTE,
    NVL(BACN.SEQUENCE,1) AS NOTE_SEQ,
    ROW_NUMBER() OVER (
      PARTITION BY RC.CATEGORYID, RC.BUDGETRECEIVETYPE
      ORDER BY RC.CREATEON DESC, RC.ROUNDNO DESC
    ) AS RN,
    CASE
      WHEN RC.BUDGETRECEIVETYPE = 'A' THEN MS2.NAME
      WHEN RC.BUDGETRECEIVETYPE = 'J' THEN MS.NAME
      WHEN RC.BUDGETRECEIVETYPE = 'G' THEN MS.NAME
      WHEN RC.BUDGETRECEIVETYPE = 'T' THEN MS.NAME
      WHEN RC.BUDGETRECEIVETYPE = 'R' THEN MS.NAME
      WHEN RC.BUDGETRECEIVETYPE = 'O' THEN MS.NAME ELSE MS.NAME END AS STATUSNAME
  FROM OAGWBG_V_BUDGETRECEIVE RC
  LEFT JOIN OAGWBG_V_EXT_BUDGET_SOURCE_V BSV 
    ON RC.BUDGETSOURCEID = BSV.ID
  LEFT JOIN OAGWBG_BUDGETALLOCATETRANSFER BAT
  	ON BAT.ID = RC.BUDGETALLOCATETRANSFERID 
  LEFT JOIN OAGWBG_BUDGETALLOCATETRANSFER_COSTCENTER_NOTE BACN
  	ON BACN.RECEIVEID = RC.ID
  	LEFT JOIN OAGWBG.OAGWBG_BUDGETTRANSFER TF
  	ON TF.ID = RC.BUDGETTRANSFERID
  LEFT JOIN OAGWBG.OAGWBG_MASTERSTATUS MS
  	ON MS.ID = TF.TRANSFERSTATUSID
  	 LEFT JOIN OAGWBG.OAGWBG_MASTERSTATUS MS2
  	ON MS2.ID = BAT.TRANSFERSTATUS
  WHERE RC.ROUNDNO IS NOT NULL
)
SELECT
  CATEGORYID,
  CATEGORYNAME,
  ACTIVITYID,
  ACTIVITYNAME,
  PRODUCTID,
  PRODUCTNAME,
  BUDGETPLANID,
  BUDGETPLANNAME,
  BUDGETYEAR,
  COSTCENTERNAME,
  DEPARTMENTNAME,
  ROUNDNO,
  BUDGETSOURCEID,
  BUDGETSOURCENAME,
  COSTCENTERID,
  DEPARTMENTID,
  TRANSFERDATE,
  TOTALBALANCEAMOUNT,
  TRANSFERDEPT,
  BUDGETRECEIVETYPE_NAME,
  NOTE,
  NOTE_SEQ,
  STATUSNAME
FROM SRC
--WHERE RN = 1
