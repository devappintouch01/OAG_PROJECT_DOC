-- =============================================================================

-- 1. สร้างตาราง
CREATE TABLE OAGWBG_BUDGETALLOCATETRANSFER_IMPORT_EXCEL (
    ID            NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BUDGETYEAR    NUMBER(4),
    BUDGETALLOCATETRANSFERID NUMBER(10),
    ROUNDNO       NUMBER(10),
    FILENAME     VARCHAR2(500 CHAR)  NOT NULL,
    CONTENTTYPE   VARCHAR2(200 CHAR),
    FILESIZE      NUMBER(12),
    FILEHASH      VARCHAR2(64 CHAR),
    FILECONTENT   BLOB                NOT NULL,
    TOTALROWS     NUMBER(10),
    ERRORROWS     NUMBER(10),
    IMPORTSTATUS  NUMBER(10)          DEFAULT 40101 NOT NULL,
    ERRORMESSAGE  CLOB,
    NOTE          VARCHAR2(2000 CHAR),
    CREATEBY      NUMBER(10)          DEFAULT -1 NOT NULL,
    CREATEON      TIMESTAMP(6)        DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATEBY      NUMBER(10),
    UPDATEON      TIMESTAMP(6),
    CONSTRAINT PK_OAGWBG_BGALLOCTRF_IMPORT PRIMARY KEY (ID),
    CONSTRAINT CK_OAGWBG_BGALLOCTRF_IMP_STS CHECK (IMPORTSTATUS IN (40101, 40201, 40301, 40401, 40501))
);

-- ค้นไฟล์ซ้ำจาก hash (ไม่ unique เพราะไฟล์ที่ยกเลิกแล้วต้องอัปโหลดใหม่ได้)
CREATE INDEX IX_OAGWBG_BGALLOCTRF_IMP_HASH ON OAGWBG_BUDGETALLOCATETRANSFER_IMPORT_EXCEL (FILEHASH);

-- ค้นไฟล์จากเลขที่โอน / เอกสารโอน
CREATE INDEX IX_OAGWBG_BGALLOCTRF_IMP_ROUND ON OAGWBG_BUDGETALLOCATETRANSFER_IMPORT_EXCEL (ROUNDNO);
CREATE INDEX IX_OAGWBG_BGALLOCTRF_IMP_TRF   ON OAGWBG_BUDGETALLOCATETRANSFER_IMPORT_EXCEL (BUDGETALLOCATETRANSFERID);

