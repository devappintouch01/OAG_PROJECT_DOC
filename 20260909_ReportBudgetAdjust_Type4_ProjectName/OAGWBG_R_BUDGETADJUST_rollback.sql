UNION ALL
-- ============================================================ 5) โอนเงินกลับหลายปี — ฝั่งโอนออก (ใหม่ใน v4)
-- ต่างจากประเภท 2/3 ตรงที่ SaveBudgetTransferReturnMoreYearsDetail ไม่ set GIVERID เลย
-- (NULL ทั้ง 46 แถว ตรวจ PREPROD 2026-09-07) เพราะ flow นี้ไม่ได้ไปตัดกองเงินต้นทาง
-- ผู้ใช้กรอกยอดเอง — ฝั่งโอนออกจึงระบุด้วย DEPARTMENTIDGIVER / COSTCENTERIDGIVER ของ link
-- ส่วนแผนงาน/ผลผลิต/กิจกรรม/หมวด อ่านจากฟิลด์บน link ซึ่งมีครบ 46/46
