--   ไม่มีคำอธิบายรายการ/หมวดรายการจริงให้ดึง — OAGWBG_ACCOUNT_SEGMENT.CATEGORYID เป็นค่าคงที่
--   '0000' ทุกแถว และ DESCRIPTION เก็บแค่คำว่า 'โอนออก' (ตรวจ PREPROD 2026-09-07: 12/12 แถว)
--   จึงปล่อยคอลัมน์ใหม่ทั้ง 3 เป็น NULL แทนที่จะยัดค่าขยะ
