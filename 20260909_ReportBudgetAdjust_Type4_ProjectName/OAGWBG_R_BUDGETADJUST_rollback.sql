       ON ACTV.ACTIVITY_ID = RF.ACTIVITYID AND ACTV.PLAN_ID = RF.BUDGETPLANID
LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_PRODUCT_V  PRODV
       ON PRODV.ID = RF.PRODUCTID AND PRODV.BUDGETPLANCODE_ID = RF.BUDGETPLANID
LEFT JOIN OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CAT   ON CAT.ID   = RF.CATEGORYID
WHERE T.TRANSFERTYPE = '4';
