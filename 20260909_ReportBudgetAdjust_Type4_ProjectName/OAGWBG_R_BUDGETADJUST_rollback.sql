--      ทั้งคู่ขาดฝั่งโอนออกด้วยเหตุเดียวกับประเภท 3 คือฝั่งโอนออกอยู่ใน BUDGETRECEIVEREFUND
--        ประเภท 2 — 146 link, GIVERID resolve เจอ 145/146 (1 แถวเป็นข้อมูลค้าง ใช้ LEFT JOIN กันหาย)
