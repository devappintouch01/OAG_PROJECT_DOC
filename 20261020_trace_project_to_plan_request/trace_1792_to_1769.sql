-- ไล่ความเชื่อมโยง: ใบคำขอ 1792 (โครงการ) มาจากแผนงานในใบคำขอ 1769 อย่างไร — PROD
-- SELECT อย่างเดียว
--
-- เส้นทางในโค้ด (BudgetService.SaveBudgetRequestProjectDetail):
--   OAGWBG_PROJECT.BUDGETGOVERNMENTID → BUDGETGOVERNMENT แถวของโครงการ (PROJECTID = โครงการ)
--     .REF_BUDGETGOVERNMENTID → BUDGETGOVERNMENT แถวแผนงานที่ CATEGORYTYPEID = '2'
--       (แถวที่กด "เพิ่มรายการ" ประเภทคำขอ = โครงการ จากหน้า BudgetRequestDetail)
--       → BUDGETREQUESTID / BUDGETPLANID / PRODUCTID / ACTIVITYCODEID

-- Q1: หัวใบคำขอทั้งสองใบ + ใบที่เป็นเวอร์ชันลูก (PARENTID)
SELECT ID, CODE, BUDGETYEAR, BUDGETFORMTYPEID, STATUSID, PARENTID, VERSION,
       COSTCENTERID, DEPARTMENTID, BUDGETTYPEID, RUNNING, CREATEBY, CREATEON
FROM   OAGWBG_BUDGETREQUEST
WHERE  ID IN (1769, 1792) OR PARENTID IN (1769, 1792)
ORDER  BY ID;

-- Q2: แถว BUDGETGOVERNMENT ทั้งหมดในสองใบ (ดู CATEGORYTYPEID / PROJECTID / REF)
SELECT ID, BUDGETREQUESTID, PROJECTID, REF_BUDGETGOVERNMENTID, CATEGORYTYPEID,
       BUDGETPLANID, PRODUCTID, ACTIVITYCODEID, CATEGORYID, RUNNING,
       BUDGETGOVERNMENTTYPE, BUDGETSTATUS, TOTALREQUESTAMOUNT,
       SUBSTR(BUDGETDETAIL, 1, 60) AS DETAIL
FROM   OAGWBG_BUDGETGOVERNMENT
WHERE  BUDGETREQUESTID IN (1769, 1792)
ORDER  BY BUDGETREQUESTID, ID;

-- Q3: โครงการของใบ 1792 → แถวโครงการ → REF → แถวแผนงานต้นทาง (คาดว่าอยู่ใน 1769)
SELECT PJ.ID                     AS PROJECT_ID,
       SUBSTR(PJ.PROJECTNAME,1,60) AS PROJECTNAME,
       PJ.TEMP,
       PJ.BUDGETREQUESTID        AS PROJECT_REQ_ID,
       PBG.ID                    AS PROJECT_BG_ID,
       PBG.REF_BUDGETGOVERNMENTID,
       SRC.ID                    AS SRC_BG_ID,
       SRC.BUDGETREQUESTID       AS SRC_REQ_ID,
       SRC.CATEGORYTYPEID        AS SRC_CATTYPE,
       SRC.BUDGETPLANID          AS SRC_PLANID,
       SRC.PRODUCTID             AS SRC_PRODUCTID,
       SRC.ACTIVITYCODEID        AS SRC_ACTIVITYID,
       SRC.CATEGORYID            AS SRC_CATEGORYID,
       SRC.RUNNING               AS SRC_RUNNING,
       SUBSTR(SRC.BUDGETDETAIL,1,60) AS SRC_DETAIL
FROM   OAGWBG_PROJECT PJ
LEFT JOIN OAGWBG_BUDGETGOVERNMENT PBG ON PBG.ID  = PJ.BUDGETGOVERNMENTID
LEFT JOIN OAGWBG_BUDGETGOVERNMENT SRC ON SRC.ID  = PBG.REF_BUDGETGOVERNMENTID
WHERE  PJ.BUDGETREQUESTID IN (1769, 1792)
ORDER  BY PJ.ID;

-- Q4: ย้อนจากฝั่งแผนงาน — แถวใน 1769 ที่มีโครงการ (ที่ไหนก็ได้) ชี้ REF มาหา
SELECT SRC.ID                    AS SRC_BG_ID,
       SRC.BUDGETREQUESTID       AS SRC_REQ_ID,
       SRC.CATEGORYTYPEID,
       SRC.BUDGETPLANID,
       SUBSTR(SRC.BUDGETDETAIL,1,60) AS SRC_DETAIL,
       PBG.ID                    AS PROJECT_BG_ID,
       PBG.BUDGETREQUESTID       AS PROJECT_REQ_ID,
       PBG.PROJECTID
FROM   OAGWBG_BUDGETGOVERNMENT SRC
JOIN   OAGWBG_BUDGETGOVERNMENT PBG ON PBG.REF_BUDGETGOVERNMENTID = SRC.ID
WHERE  SRC.BUDGETREQUESTID = 1769
ORDER  BY SRC.ID, PBG.ID;

-- Q5: ถ้า Q3 ได้ SRC_REQ_ID ไม่ใช่ 1769 — REF อาจค้างที่ใบเวอร์ชันเก่า/ใหม่
--     ไล่สาย PARENTID ขึ้นจาก 1769 (ใบก่อนหน้า) และลงจาก 1769 (ใบถัดไป)
SELECT LEVEL AS LVL, ID, CODE, STATUSID, PARENTID, VERSION, BUDGETFORMTYPEID
FROM   OAGWBG_BUDGETREQUEST
START  WITH ID = 1769
CONNECT BY NOCYCLE PRIOR PARENTID = ID;

SELECT LEVEL AS LVL, ID, CODE, STATUSID, PARENTID, VERSION, BUDGETFORMTYPEID
FROM   OAGWBG_BUDGETREQUEST
START  WITH ID = 1769
CONNECT BY NOCYCLE PRIOR ID = PARENTID;

-- ===== หลังดูผล Q1–Q5 (2026-10-20) =====
-- 1769 (143/2570 v2, PARENTID 1013) ↔ 1792 (5/2570 v2, PARENTID 1061)
-- โครงการ 337–353 (TEMP null) REF ชี้แถวใน 1769 ตรง ๆ
-- โครงการ 354+ (TEMP = 132, 131, 144 …) REF ยังชี้แถวใน 1013 (ใบแผนงานเวอร์ชันเก่า)

-- Q6: map REF ทุกโครงการใน 1792 ไปแถวใน 1769 ด้วย RUNNING
--     (วิธีเดียวกับ BudgetService.ResolveLatestRefBudgetGovernmentId: ใบล่าสุด + RUNNING เดียวกัน + CATEGORYTYPEID '2')
SELECT PJ.ID                       AS PROJECT_ID,
       PJ.TEMP,
       SUBSTR(PJ.PROJECTNAME,1,50) AS PROJECTNAME,
       OLD.ID                      AS REF_BG_ID,
       OLD.BUDGETREQUESTID         AS REF_REQ_ID,
       OLD.RUNNING                 AS REF_RUNNING,
       NEW.ID                      AS BG_IN_1769,
       NEW.BUDGETPLANID,
       NEW.PRODUCTID,
       NEW.ACTIVITYCODEID,
       SUBSTR(NEW.BUDGETDETAIL,1,50) AS DETAIL_IN_1769
FROM   OAGWBG_PROJECT PJ
JOIN   OAGWBG_BUDGETGOVERNMENT PBG ON PBG.ID = PJ.BUDGETGOVERNMENTID
JOIN   OAGWBG_BUDGETGOVERNMENT OLD ON OLD.ID = PBG.REF_BUDGETGOVERNMENTID
LEFT JOIN OAGWBG_BUDGETGOVERNMENT NEW
       ON NEW.BUDGETREQUESTID = 1769
      AND NEW.RUNNING         = OLD.RUNNING
      AND NEW.CATEGORYTYPEID  = '2'
WHERE  PJ.BUDGETREQUESTID = 1792
ORDER  BY NEW.ID, PJ.ID;

-- Q7: แถวโครงการใน 1769 ที่ถูกโครงการใน 1792 ใช้ซ้ำมากกว่า 1 ตัว (ต้นฉบับ + สำเนา TEMP)
SELECT NEW.ID AS BG_IN_1769,
       SUBSTR(NEW.BUDGETDETAIL,1,50) AS DETAIL,
       COUNT(*) AS PROJECT_COUNT,
       LISTAGG(PJ.ID || CASE WHEN PJ.TEMP IS NOT NULL THEN '(T' || PJ.TEMP || ')' END, ', ')
         WITHIN GROUP (ORDER BY PJ.ID) AS PROJECT_IDS
FROM   OAGWBG_PROJECT PJ
JOIN   OAGWBG_BUDGETGOVERNMENT PBG ON PBG.ID = PJ.BUDGETGOVERNMENTID
JOIN   OAGWBG_BUDGETGOVERNMENT OLD ON OLD.ID = PBG.REF_BUDGETGOVERNMENTID
JOIN   OAGWBG_BUDGETGOVERNMENT NEW
       ON NEW.BUDGETREQUESTID = 1769
      AND NEW.RUNNING         = OLD.RUNNING
      AND NEW.CATEGORYTYPEID  = '2'
WHERE  PJ.BUDGETREQUESTID = 1792
GROUP  BY NEW.ID, SUBSTR(NEW.BUDGETDETAIL,1,50)
HAVING COUNT(*) > 1
ORDER  BY NEW.ID;

-- ===== หลังดูผล Q6–Q7 (2026-10-20) =====
-- ทุกแถวโครงการใน 1769 มีโครงการใน 1792 ชี้มา 4 ตัวเท่ากันหมด:
--   ต้นฉบับ (TEMP null, REF→1769) / ชุดจัดสรรของต้นฉบับ (TEMP→ต้นฉบับ, REF→1769)
--   สำเนาที่ติดมาจาก v1 (TEMP→โครงการนอกใบ, REF→1013) / สำเนาของสำเนา (TEMP→สำเนา v1, REF→1013)

-- Q8: ตารางเชื่อมแบบสะอาด — 1 แถวต่อโครงการ: ต้นฉบับ + ชุดจัดสรรที่ถูก + แถวแผนงานใน 1769
--     ชุดจัดสรรที่ถูก = TEMP ชี้ต้นฉบับ (TEMP null) ในใบเดียวกัน
SELECT ORIG.ID                       AS ORIGINAL_PROJECT_ID,
       ALLOC.ID                      AS ALLOCATE_PROJECT_ID,
       SUBSTR(ORIG.PROJECTNAME,1,60) AS PROJECTNAME,
       SRC.ID                        AS BG_IN_1769,
       SRC.RUNNING,
       SRC.BUDGETPLANID,
       SRC.PRODUCTID,
       SRC.ACTIVITYCODEID,
       SRC.CATEGORYID
FROM   OAGWBG_PROJECT ORIG
JOIN   OAGWBG_BUDGETGOVERNMENT PBG ON PBG.ID = ORIG.BUDGETGOVERNMENTID
JOIN   OAGWBG_BUDGETGOVERNMENT SRC ON SRC.ID = PBG.REF_BUDGETGOVERNMENTID
LEFT JOIN OAGWBG_PROJECT ALLOC
       ON ALLOC.TEMP            = ORIG.ID
      AND ALLOC.BUDGETREQUESTID = ORIG.BUDGETREQUESTID
WHERE  ORIG.BUDGETREQUESTID = 1792
AND    ORIG.TEMP IS NULL
ORDER  BY SRC.ID;
