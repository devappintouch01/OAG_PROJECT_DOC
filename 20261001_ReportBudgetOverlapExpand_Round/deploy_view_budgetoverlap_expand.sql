-- ฐาน = DDL สดจาก PREPROD (DBMS_METADATA.GET_DDL 2026-10-01) — แก้ "เฉพาะ WHERE" บรรทัดท้ายไฟล์
--
-- เหตุผล : ผู้ใช้ต้องการให้รายงานแสดงรอบที่ยังไม่ยืนยันด้วย
--   รายการ EXPAND_* ได้สถานะ 90102 ตั้งแต่ตอนบันทึก จึงขึ้นรายงานอยู่แล้ว
--   แต่ CANCEL_* ได้ 90109 ตอนบันทึก และเปลี่ยนเป็น 90110 ตอน "ส่งเรื่อง" เท่านั้น
--   → ช่อง "เหลือจ่าย/ส่งคืน" ของรอบที่ยังไม่ส่งเรื่องเป็นว่าง ขณะที่ช่องขยายเวลามียอดแล้ว
--
-- เพิ่ม 90109 เฉพาะ CANCEL_PR / CANCEL_PO / CANCEL_LUMP
--   ไม่เปิดกว้าง 90109 ทั้งหมด เพราะมีรายการเดิมประเภท 'R' ที่สถานะ 90109 อยู่ด้วย จะกลายเป็นแถวเกิน
--
-- rollback : rollback_view_budgetoverlap_expand.sql (โฟลเดอร์เดียวกัน)
