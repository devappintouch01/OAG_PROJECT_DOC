-- OAGWBG.OAGWBG_V_BUDGET_ADJUSTMENT_TRANSFER_INTERFACE
-- Purpose : แสดงรายการ Interface ที่ส่งจากหน้าโอนเปลี่ยนแปลงงบประมาณ (CR-115v3)
--           อ่านจาก OAGWBG_LOG_INTERFACE ที่ถูก INSERT โดย ConfirmBudgetTransferAdjust()
--           ACTUAL_FLAG = 'B' → ขา CR (รับโอน, Budget)
--           ACTUAL_FLAG = 'E' → ขา DR (โอนออก, Encumbrance)
-- Deploy  : run เป็น DBA / OAGWBG schema owner บน PREPROD แล้ว PROD
-- Created : 2026-06-18

CREATE OR REPLACE FORCE EDITIONABLE VIEW "OAGWBG"."OAGWBG_V_BUDGET_ADJUSTMENT_TRANSFER_INTERFACE"
(
  "ID",
  "WEB_BATCH_NO",
  "USER_JE_SOURCE_NAME",
  "REFERENCE4",
  "REFERENCE5",
  "LEDGER_ID",
  "USER_JE_CATEGORY_NAME",
  "DEFAULT_EFFECTIVE_DATE",
  "ACTUAL_FLAG",
  "BUDGET_ENCUMBRANCE_NAME",
  "ENCUMBRANCE_TYPE",
  "CURRENCY_CODE",
  "ATTRIBUTE3",
  "ATTRIBUTE4",
  "LINE_NUMBER",
  "SEGMENT1",
  "SEGMENT2",
  "SEGMENT3",
  "SEGMENT4",
  "SEGMENT5",
  "SEGMENT6",
  "SEGMENT7",
  "SEGMENT8",
  "SEGMENT9",
  "SEGMENT10",
  "SEGMENT11",
  "SEGMENT12",
  "SEGMENT13",
  "ENTERED_DR",
  "ACCOUNTED_DR",
  "ENTERED_CR",
  "ACCOUNTED_CR",
  "REFERENCE1",
  "REFERENCE10",
  "REFERENCE_PAGE",
  "PAGE_NAME",
  "STATUS",
  "MESSAGE",
  "CREATED_BY",
  "LAST_UPDATED_BY",
  "CREATION_DATE",
  "LAST_UPDATE_DATE",
  "TRANSFER_TYPE",
  "ACTION_NAME",
  -- columns จาก JOIN BUDGETTRANSFER
  "BUDGETTRANSFER_ID",
  "TRANSFERNO",
  "ROUNDNO",
  "BUDGETYEAR",
  "TRANSFERSTATUSID"
) AS
SELECT
  LI.ID,
  LI.WEB_BATCH_NO,
  LI.USER_JE_SOURCE_NAME,
  LI.REFERENCE4,
  LI.REFERENCE5,
  LI.LEDGER_ID,
  LI.USER_JE_CATEGORY_NAME,
  LI.DEFAULT_EFFECTIVE_DATE,
  LI.ACTUAL_FLAG,
  LI.BUDGET_ENCUMBRANCE_NAME,
  LI.ENCUMBRANCE_TYPE,
  LI.CURRENCY_CODE,
  LI.ATTRIBUTE3,
  LI.ATTRIBUTE4,
  LI.LINE_NUMBER,
  LI.SEGMENT1,
  LI.SEGMENT2,
  LI.SEGMENT3,
  LI.SEGMENT4,
  LI.SEGMENT5,
  LI.SEGMENT6,
  LI.SEGMENT7,
  LI.SEGMENT8,
  LI.SEGMENT9,
  LI.SEGMENT10,
  LI.SEGMENT11,
  LI.SEGMENT12,
  LI.SEGMENT13,
  LI.ENTERED_DR,
  LI.ACCOUNTED_DR,
  LI.ENTERED_CR,
  LI.ACCOUNTED_CR,
  LI.REFERENCE1,
  LI.REFERENCE10,
  LI.REFERENCE_PAGE,
  LI.PAGE_NAME,
  LI.STATUS,
  LI.MESSAGE,
  LI.CREATED_BY,
  LI.LAST_UPDATED_BY,
  LI.CREATION_DATE,
  LI.LAST_UPDATE_DATE,
  LI.TRANSFER_TYPE,
  LI.ACTION_NAME,
  -- JOIN BUDGETTRANSFER ผ่าน ATTRIBUTE3 = BT.ID (string)
  BT.ID          AS BUDGETTRANSFER_ID,
  BT.TRANSFERNO,
  BT.ROUNDNO,
  BT.BUDGETYEAR,
  BT.TRANSFERSTATUSID
FROM OAGWBG.OAGWBG_LOG_INTERFACE LI
LEFT JOIN OAGWBG.OAGWBG_BUDGETTRANSFER BT
  ON BT.ID = TO_NUMBER(LI.ATTRIBUTE3)
WHERE LI.TRANSFER_TYPE  = 'ADJUSTMENT'
  AND LI.ACTION_NAME    = 'SaveBudgetAdjust'
ORDER BY LI.ID;
