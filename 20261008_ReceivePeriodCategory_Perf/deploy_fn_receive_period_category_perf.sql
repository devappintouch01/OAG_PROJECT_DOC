-- DEPLOY: performance fix for OAGWBG_FN_GETBUDGET_RECEIVE_PERIOD_CATEGORY (2026-10-08)
-- Base: DDL from PREPROD (LAST_DDL_TIME 2026-09-29 13:37). Before deploying to PROD, pull the PROD DDL and diff against rollback_*.sql first.
-- Changes (results identical to the original on all 42 PREPROD IDs):
--   1. BDPI   : /*+ MATERIALIZE */ + WHERE BUDGETYEAR = v_budgetyear  -> heavy pivot view runs once, cannot be run per row
--   2. CAL    : /*+ MATERIALIZE */                                    -> computed once (used by both GG and CC)
--   3. BA_SUM : WHERE BR.BUDGETYEAR = v_budgetyear, drop the useless ORDER BY
--   4. RCV_BASE: AND BRP.BUDGETYEAR = v_budgetyear
--   5. SUM_RCV: WHERE BUDGETYEAR = v_budgetyear
  CREATE OR REPLACE EDITIONABLE FUNCTION "OAGWBG"."OAGWBG_FN_GETBUDGET_RECEIVE_PERIOD_CATEGORY" (
    PAR_BUDGETRECEIVEPERIODID IN NUMBER
) RETURN OAGWBG_FN_GETBUDGET_RECEIVE_PERIOD_CATEGORY_TABLE PIPELINED AS 
    v_budgetyear OAGWBG_BUDGETRECEIVEPERIOD.BUDGETYEAR %TYPE;
    v_budgetgovernmentid OAGWBG_BUDGETRECEIVEPERIOD.BUDGETGOVERNMENTID %TYPE;

BEGIN 
    BEGIN
        SELECT BUDGETYEAR, BUDGETGOVERNMENTID 
        INTO v_budgetyear, v_budgetgovernmentid
        FROM OAGWBG_BUDGETRECEIVEPERIOD
        WHERE ID = PAR_BUDGETRECEIVEPERIODID;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN 
            RETURN;
    END;

    FOR R IN (
        -- Calculate totals
        WITH 
        BA_SUM AS (
            SELECT 
		        BR.BUDGETYEAR,
		        BR.CATEGORYID,
		        BR.PRODUCTID,
		        BR.ACTIVITYID,
		        CASE 
		            WHEN BR.MONTH IN (10, 11, 12) THEN 1
		            WHEN BR.MONTH IN (1, 2, 3)   THEN 2
		            WHEN BR.MONTH IN (4, 5, 6)   THEN 3
		            WHEN BR.MONTH IN (7, 8, 9)   THEN 4
		        END AS PERIOD,
		        SUM(BR.ADDEDAMOUNT) AS TOTALALLOCATEAMOUNT
		    FROM OAGWBG_BUDGETDISBURSEMENTPLANRECEIVE BR
		    WHERE BR.BUDGETYEAR = v_budgetyear
		    GROUP BY
		        BR.BUDGETYEAR,
		        BR.CATEGORYID,
		        BR.PRODUCTID,
		        BR.ACTIVITYID,
		        CASE
		            WHEN BR.MONTH IN (10, 11, 12) THEN 1
		            WHEN BR.MONTH IN (1, 2, 3)   THEN 2
		            WHEN BR.MONTH IN (4, 5, 6)   THEN 3
		            WHEN BR.MONTH IN (7, 8, 9)   THEN 4
		        END
        ),
        BDPI AS (
            SELECT /*+ MATERIALIZE */
                BDPI.TOTALALLOCATEAMOUNT,
                BDPI.TOTALALLOCATESUMMARYAMOUNT,
                BDPI.BUDGETYEAR,
                BDPI.CATEGORYID,
                BDPI.PRODUCT_ID,
                BDPI.ACTIVITY_ID
            FROM OAGWBG_V_BUDGETDISBURSEMENTPLANITEMPIVOT BDPI
            WHERE BDPI.BUDGETYEAR = v_budgetyear
        ),
        CAT_BASE AS (
			SELECT 
				BG.CATEGORYID,
				BG.PRODUCTID,
				BG.ACTIVITYCODEID,
				BG.BUDGETYEAR 
			FROM OAGWBG_BUDGETGOVERNMENT BG
			WHERE BG.BUDGETSTATUS = 'C'
			AND ( BG.BUDGETGOVERNMENTTYPE IS NULL OR BG.BUDGETGOVERNMENTTYPE = 7 )
			AND NOT EXISTS (
				SELECT 1 
				FROM OAGWBG_BUDGETREQUEST BR
				WHERE ( BR.PARENTID IS NOT NULL
					AND BR.PARENTID = BG.BUDGETREQUESTID )
			)
			GROUP BY 
				BG.CATEGORYID, 
				BG.BUDGETYEAR, 
				BG.PRODUCTID,
				BG.ACTIVITYCODEID
		),
		RCV_BASE AS (
		    SELECT
		        CB.CATEGORYID,
				CB.PRODUCTID,
				CB.ACTIVITYCODEID,
		        BRP.BUDGETYEAR,
		        BRP.PERIOD,
		        BRP.ROUNDNO,
		        SUM(NVL(BRC.TOTALRECEIVEAMOUNT,0)) AS TOTAL_RECEIVE
		    FROM OAGWBG_BUDGETRECEIVEPERIOD BRP
		    LEFT JOIN CAT_BASE CB
		        ON CB.BUDGETYEAR = BRP.BUDGETYEAR
		    LEFT JOIN OAGWBG_BUDGETRECEIVEPERIODCATEGORY BRC
		    	ON BRC.BUDGETRECEIVEPERIODID = BRP.ID
		    	AND BRC.CATEGORYID = CB.CATEGORYID
		    	AND BRC.PRODUCTID = CB.PRODUCTID
		    	AND BRC.ACTIVITYID = CB.ACTIVITYCODEID
		    WHERE BRP.PERIOD_TYPE = '1'
		    AND BRP.BUDGETYEAR = v_budgetyear
		    GROUP BY
		        CB.CATEGORYID,
				CB.PRODUCTID,
				CB.ACTIVITYCODEID,
		        BRP.BUDGETYEAR,
		        BRP.PERIOD,
		        BRP.ROUNDNO
		),
		RCV_ACCUM AS (
		    SELECT
			    CATEGORYID,
				PRODUCTID,
				ACTIVITYCODEID,
			    BUDGETYEAR,
			    PERIOD,
			    ROUNDNO,
			    SUM(TOTAL_RECEIVE) OVER (
			        PARTITION BY
			            CATEGORYID,
			            BUDGETYEAR,
						PRODUCTID,
						ACTIVITYCODEID
			        ORDER BY
			            PERIOD,
			            ROUNDNO
			        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
			    ) AS TOTAL_RECEIVE_ACCUM
			FROM RCV_BASE
		),
        CAL AS (
            SELECT /*+ MATERIALIZE */
			    BG.BUDGETYEAR,
			    BG.BUDGETPLANID,
			    BG.PRODUCTID,
			    BG.ACTIVITYCODEID,
			    BG.EXPENSETYPEID AS BUDGETEXPENSETYPEID,
			    BG.CATEGORYID,
			    NVL(BDPI.TOTALALLOCATESUMMARYAMOUNT, 0) AS TOTALALLOCATEAMOUNT,
			    NVL(BDPI.TOTALALLOCATESUMMARYAMOUNT, 0) - NVL(SUM_RCV.TOTAL_RECEIVE, 0) AS TOTALBALANCEAMOUNT,
			    CASE 
			        WHEN BRP.ROUNDNO = 1 
			            THEN NVL(BC.TOTALRECEIVEAMOUNT, BA_SUM.TOTALALLOCATEAMOUNT)
			        ELSE NVL(BC.TOTALRECEIVEAMOUNT, 0)
			    END AS TOTALRECEIVEAMOUNT,
			    NVL(RA.TOTAL_RECEIVE_ACCUM, 0) AS TOTALRECEIVEACCUMAMOUNT
			FROM OAGWBG_BUDGETGOVERNMENT BG
			LEFT JOIN OAGWBG_BUDGETRECEIVEPERIODCATEGORY BC 
			    ON BC.CATEGORYID = BG.CATEGORYID
			    AND BC.PRODUCTID = BG.PRODUCTID
			    AND BC.ACTIVITYID = BG.ACTIVITYCODEID
			    AND BC.BUDGETYEAR = BG.BUDGETYEAR
			    AND BC.BUDGETRECEIVEPERIODID = PAR_BUDGETRECEIVEPERIODID
			LEFT JOIN OAGWBG_BUDGETRECEIVEPERIOD BRP 
			    ON BRP.ID = PAR_BUDGETRECEIVEPERIODID
			LEFT JOIN BA_SUM 
			    ON BA_SUM.PERIOD = BRP.PERIOD
			    AND BA_SUM.CATEGORYID = BG.CATEGORYID
			    AND BA_SUM.BUDGETYEAR = BG.BUDGETYEAR
			    AND BA_SUM.PRODUCTID = BG.PRODUCTID
			    AND BA_SUM.ACTIVITYID = BG.ACTIVITYCODEID
			LEFT JOIN BDPI 
			    ON BDPI.CATEGORYID = BG.CATEGORYID
			    AND BDPI.BUDGETYEAR = BG.BUDGETYEAR
			    AND BDPI.PRODUCT_ID = BG.PRODUCTID
			    AND BDPI.ACTIVITY_ID = BG.ACTIVITYCODEID
			LEFT JOIN (
			    SELECT 
			        CATEGORYID,
			        BUDGETYEAR,
			        PRODUCTID,
			        ACTIVITYID,
			        SUM(TOTALRECEIVEAMOUNT) AS TOTAL_RECEIVE
			    FROM OAGWBG_BUDGETRECEIVEPERIODCATEGORY
			    WHERE BUDGETYEAR = v_budgetyear
			    GROUP BY CATEGORYID, BUDGETYEAR, PRODUCTID, ACTIVITYID
			) SUM_RCV 
			    ON SUM_RCV.CATEGORYID = BG.CATEGORYID
			    AND SUM_RCV.BUDGETYEAR = BG.BUDGETYEAR
			    AND SUM_RCV.ACTIVITYID = BG.ACTIVITYCODEID
			    AND SUM_RCV.PRODUCTID = BG.PRODUCTID
			LEFT JOIN RCV_ACCUM RA
			    ON RA.CATEGORYID = BG.CATEGORYID
			    AND RA.PRODUCTID = BG.PRODUCTID
			    AND RA.ACTIVITYCODEID = BG.ACTIVITYCODEID
			    AND RA.BUDGETYEAR = BG.BUDGETYEAR
			    AND RA.PERIOD = BRP.PERIOD
			    AND RA.ROUNDNO = BRP.ROUNDNO
			WHERE BG.BUDGETSTATUS = 'C'
			    AND ( BG.BUDGETGOVERNMENTTYPE IS NULL OR BG.BUDGETGOVERNMENTTYPE = 7 )
			    AND BG.BUDGETFORMTYPEID = 1
			    AND BG.BUDGETYEAR = v_budgetyear
			GROUP BY 
			    BG.BUDGETYEAR,
			    BRP.ROUNDNO,
			    BG.BUDGETPLANID,
			    BG.PRODUCTID,
			    BG.ACTIVITYCODEID,
			    BG.EXPENSETYPEID,
			    BG.CATEGORYID,
			    BDPI.TOTALALLOCATESUMMARYAMOUNT,
			    SUM_RCV.TOTAL_RECEIVE,
			    BA_SUM.TOTALALLOCATEAMOUNT,
			    BC.TOTALRECEIVEAMOUNT,
			    RA.TOTAL_RECEIVE_ACCUM
        ),
        MS_GROUPED_BP AS (
            SELECT 
                MS.BUDGETPLANID,
                MS.BUDGETYEAR,
                CCC.DESCRIPTION AS CATEGORYNAME
            FROM OAGWBG_BUDGETGOVERNMENT MS
                LEFT JOIN APPS.OAGINV_CATEGORY_CODES_V CCC 
                    ON CCC.CATEGORY_ID = TO_CHAR(MS.BUDGETPLANID)
            WHERE MS.BUDGETSTATUS = 'C'
                AND ( MS.BUDGETGOVERNMENTTYPE IS NULL OR MS.BUDGETGOVERNMENTTYPE = 7 )
                AND MS.BUDGETFORMTYPEID = 1
                AND MS.BUDGETYEAR = v_budgetyear
            GROUP BY MS.BUDGETPLANID, MS.BUDGETYEAR, CCC.DESCRIPTION
        ),
        MS_GROUPED_BPD AS (
            SELECT 
                MS.BUDGETPLANID,
                MS.PRODUCTID,
                MS.BUDGETYEAR,
                BGPD.FV_DESCRIPTION AS CATEGORYNAME
            FROM OAGWBG_BUDGETGOVERNMENT MS
                LEFT JOIN APPS.OAGGL_BUDGET_PRODUCT_V BGPD 
                    ON BGPD.FLEX_VALUE = LPAD(MS.PRODUCTID, 5, '0')
            WHERE MS.BUDGETSTATUS = 'C'
                AND ( MS.BUDGETGOVERNMENTTYPE IS NULL OR MS.BUDGETGOVERNMENTTYPE = 7 )
                AND MS.BUDGETFORMTYPEID = 1
                AND MS.BUDGETYEAR = v_budgetyear
            GROUP BY MS.BUDGETPLANID, MS.PRODUCTID, MS.BUDGETYEAR, BGPD.FV_DESCRIPTION
        ),
        MS_GROUPED_BA AS (
            SELECT 
                MS.ACTIVITYCODEID,
                MS.BUDGETPLANID,
                MS.PRODUCTID,
                MS.BUDGETYEAR,
                BGA.FV_DESCRIPTION AS CATEGORYNAME
            FROM OAGWBG_BUDGETGOVERNMENT MS
                LEFT JOIN APPS.OAGGL_BUDGET_ACTIVITY_V BGA 
                    ON BGA.FLEX_VALUE = LPAD(MS.ACTIVITYCODEID, 5, '0')
            WHERE MS.BUDGETSTATUS = 'C'
                AND ( MS.BUDGETGOVERNMENTTYPE IS NULL OR MS.BUDGETGOVERNMENTTYPE = 7 )
                AND MS.BUDGETFORMTYPEID = 1
                AND MS.BUDGETYEAR = v_budgetyear
            GROUP BY MS.ACTIVITYCODEID, MS.BUDGETPLANID, MS.PRODUCTID, MS.BUDGETYEAR, BGA.FV_DESCRIPTION
        ),
        MS_GROUPED_BT AS (
            SELECT 
			    CCC.EXPENSE_TYPE_ID AS BUDGETEXPENSETYPEID,
			    MS.ACTIVITYCODEID,
			    MS.BUDGETPLANID,
			    MS.PRODUCTID,
			    MS.BUDGETYEAR,
			    CCC.EXPENSE_TYPE_NAME  AS DESCRIPTION
			FROM OAGWBG_BUDGETGOVERNMENT MS
			LEFT JOIN OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CCC 
			        ON MS.CATEGORYID = CCC.ID
			WHERE MS.BUDGETSTATUS = 'C'
			    AND ( MS.BUDGETGOVERNMENTTYPE IS NULL OR MS.BUDGETGOVERNMENTTYPE = 7 )
				AND MS.BUDGETEXPENSETYPEID IS NOT NULL
			    AND MS.BUDGETFORMTYPEID = 1
			    AND MS.BUDGETYEAR = v_budgetyear
			GROUP BY CCC.EXPENSE_TYPE_ID, MS.ACTIVITYCODEID, MS.BUDGETPLANID, MS.PRODUCTID, MS.BUDGETYEAR, CCC.EXPENSE_TYPE_NAME
			ORDER BY CCC.EXPENSE_TYPE_ID
        ),
        MS_GROUPED_CC AS (
			SELECT 
				CC.EXPENSE_TYPE_ID AS BUDGETEXPENSETYPEID,
			    MS.ACTIVITYCODEID,
			    MS.BUDGETPLANID,
			    MS.PRODUCTID,
			    MS.BUDGETYEAR,
				MS.CATEGORYID,
			    CC.BUDGET_TYPE_NAME  AS DESCRIPTION,
			    CC.CODE
			FROM OAGWBG_BUDGETGOVERNMENT MS
			LEFT JOIN OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CC 
				ON MS.CATEGORYID = CC.ID
			WHERE MS.BUDGETSTATUS = 'C'
			    AND ( MS.BUDGETGOVERNMENTTYPE IS NULL OR MS.BUDGETGOVERNMENTTYPE = 7 )
			    AND MS.BUDGETFORMTYPEID = 1
			    AND MS.BUDGETYEAR = v_budgetyear
			GROUP BY 
				CC.EXPENSE_TYPE_ID,
			    MS.ACTIVITYCODEID,
			    MS.BUDGETPLANID,
			    MS.PRODUCTID,
			    MS.BUDGETYEAR,
			    CC.BUDGET_TYPE_NAME ,
				MS.CATEGORYID,
				CC.CODE 
			ORDER BY CC.CODE
		),
		-- GG (Group Level - Level 5)
		GG AS (
		    SELECT
		        TO_CHAR(MS_GROUPED_CC.BUDGETEXPENSETYPEID || MS_GROUPED_CC.ACTIVITYCODEID || MS_GROUPED_CC.PRODUCTID || MS_GROUPED_CC.BUDGETPLANID) AS ID,
		        MS_GROUPED_CC.BUDGETPLANID || '.' || LPAD(MS_GROUPED_CC.PRODUCTID,5,'0') || '.' || LPAD(MS_GROUPED_CC.ACTIVITYCODEID,5,'0') || '.' || LPAD(MS_GROUPED_CC.BUDGETEXPENSETYPEID,4,'0') || '.0000' AS ORDERCODE,
		        NULL AS CODE,
		        NULL AS BUDGETGOVERNMENTID,
		        NULL AS BUDGETRECEIVEPERIODID,
		        NULL AS BUDGETYEAR,
		        NULL AS PRODUCTID,
		        NULL AS ACTIVITYID,
		        NULL AS BUDGETPLANID,
		        NULL AS BUDGETTYPEID,
		        NULL AS CATEGORYID,
		        MS_GROUPED_CC.DESCRIPTION AS CATEGORYNAME,
		        NULL AS DEPARTMENTID,
		        NULL AS COSTCENTERID,
		        TO_CHAR(
				    MS_GROUPED_CC.BUDGETPLANID || LPAD(MS_GROUPED_CC.PRODUCTID,5,'0') || LPAD(MS_GROUPED_CC.ACTIVITYCODEID,5,'0') || MS_GROUPED_CC.BUDGETEXPENSETYPEID
				) AS PARENTID,
		        TO_CHAR(
				    MS_GROUPED_CC.BUDGETPLANID || LPAD(MS_GROUPED_CC.PRODUCTID,5,'0') || LPAD(MS_GROUPED_CC.ACTIVITYCODEID,5,'0') || MS_GROUPED_CC.BUDGETEXPENSETYPEID || MS_GROUPED_CC.CATEGORYID
				) AS NODEID,
		        NULL AS ISCATEGORY,
		        SUM(CAL.TOTALALLOCATEAMOUNT) AS TOTALALLOCATEAMOUNT,
		        SUM(CAL.TOTALBALANCEAMOUNT) AS TOTALBALANCEAMOUNT,
		        SUM(CAL.TOTALRECEIVEAMOUNT) AS TOTALRECEIVEAMOUNT,
		        SUM(CAL.TOTALRECEIVEACCUMAMOUNT) AS TOTALRECEIVEACCUMAMOUNT,
		        '5' AS LEVEL_NAME
		    FROM MS_GROUPED_CC
	        LEFT JOIN CAL 
	            ON CAL.CATEGORYID = MS_GROUPED_CC.CATEGORYID
	            AND CAL.ACTIVITYCODEID = MS_GROUPED_CC.ACTIVITYCODEID
	            AND CAL.PRODUCTID = MS_GROUPED_CC.PRODUCTID
	            AND CAL.BUDGETEXPENSETYPEID = MS_GROUPED_CC.BUDGETEXPENSETYPEID
	            AND CAL.BUDGETPLANID = MS_GROUPED_CC.BUDGETPLANID
	            AND CAL.BUDGETYEAR = MS_GROUPED_CC.BUDGETYEAR
		    GROUP BY
		        MS_GROUPED_CC.BUDGETEXPENSETYPEID,
		        MS_GROUPED_CC.ACTIVITYCODEID,
		        MS_GROUPED_CC.BUDGETPLANID,
		        MS_GROUPED_CC.PRODUCTID,
		        MS_GROUPED_CC.BUDGETYEAR,
		        MS_GROUPED_CC.DESCRIPTION,
		        MS_GROUPED_CC.CATEGORYID
		),
		-- CC (Category Level - Level 6)
		CC AS (
		    SELECT 
			    TO_CHAR(BG.CATEGORYID) AS ID,
			    BG.BUDGETPLANID || '.' || LPAD(BG.PRODUCTID,5,'0') || '.' || LPAD(BG.ACTIVITYCODEID,5,'0') || '.' || LPAD(CCC.EXPENSE_TYPE_ID,4,'0') || '.' || BG.CATEGORYID AS ORDERCODE,
			    NVL(BCY.BUDGETCODEID,'00000000000000000000') AS CODE,
			    NULL AS BUDGETGOVERNMENTID,
			    '' AS BUDGETRECEIVEPERIODID,
			    '' AS BUDGETYEAR,
			    LPAD(BG.PRODUCTID,5,'0') AS PRODUCTID,
			    LPAD(BG.ACTIVITYCODEID,5,'0') AS ACTIVITYID,
			    BG.BUDGETPLANID AS BUDGETPLANID,
			    CCC.EXPENSE_TYPE_ID AS BUDGETTYPEID,
			    TO_CHAR(BG.CATEGORYID) AS CATEGORYID,
			    CCC.NAME AS CATEGORYNAME,
			    NULL AS DEPARTMENTID,
			    NULL AS COSTCENTERID,
			    TO_CHAR(
			        BG.BUDGETPLANID || LPAD(BG.PRODUCTID,5,'0') || LPAD(BG.ACTIVITYCODEID,5,'0') || CCC.EXPENSE_TYPE_ID || BG.CATEGORYID
			    ) AS PARENTID,
			    TO_CHAR(BG.CATEGORYID) AS NODEID,
			    TO_CHAR(BG.CATEGORYID) AS ISCATEGORY,
			    MAX(CAL.TOTALALLOCATEAMOUNT) AS TOTALALLOCATEAMOUNT,
			    MAX(CAL.TOTALBALANCEAMOUNT) AS TOTALBALANCEAMOUNT,
			    MAX(CAL.TOTALRECEIVEAMOUNT) AS TOTALRECEIVEAMOUNT,
			    NVL(MAX(CAL.TOTALRECEIVEACCUMAMOUNT),0) AS TOTALRECEIVEACCUMAMOUNT,
			    '6' AS LEVEL_NAME
			FROM OAGWBG_BUDGETGOVERNMENT BG
			    LEFT JOIN OAGWBG_BUDGETCODE_YEAR BCY 
			        ON BCY.CATEGORYID = BG.CATEGORYID
			        AND BCY.BUDGETYEAR = BG.BUDGETYEAR
			        AND BCY.PRODUCTID = BG.PRODUCTID
			        AND BCY.ACTIVITYCODEID = BG.ACTIVITYCODEID
			        AND BCY.STATUS = 1
			LEFT JOIN OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CCC 
				ON BG.CATEGORYID = CCC.ID
			    LEFT JOIN CAL 
			        ON CAL.CATEGORYID = BG.CATEGORYID
			        AND CAL.ACTIVITYCODEID = BG.ACTIVITYCODEID
			        AND CAL.PRODUCTID = BG.PRODUCTID
			        AND CAL.BUDGETEXPENSETYPEID = CCC.EXPENSE_TYPE_ID
			        AND CAL.BUDGETPLANID = BG.BUDGETPLANID
			        AND CAL.BUDGETYEAR = BG.BUDGETYEAR
			WHERE BG.BUDGETSTATUS = 'C'
			    AND BG.BUDGETFORMTYPEID = 1
			    AND BG.BUDGETYEAR = v_budgetyear
			    AND ( BG.BUDGETGOVERNMENTTYPE IS NULL OR BG.BUDGETGOVERNMENTTYPE = 7 )
			    AND NOT EXISTS (
					SELECT 1 
					FROM OAGWBG_BUDGETREQUEST BR
					WHERE ( BR.PARENTID IS NOT NULL
						AND BR.PARENTID = BG.BUDGETREQUESTID )
				)
			GROUP BY 
			    BG.CATEGORYID,
			    CCC.EXPENSE_TYPE_ID,
			    BG.BUDGETPLANID,
			    BG.PRODUCTID,
			    BG.ACTIVITYCODEID,
			    BG.BUDGETYEAR,
			    BCY.BUDGETCODEID,
			    CCC.NAME,
			    BG.CATEGORYID
		    HAVING MAX(CAL.TOTALALLOCATEAMOUNT) > 0
		),
        -- BT (BUDGET TYPE Level - Level 4)
        BT AS (
            SELECT 
                TO_CHAR(LPAD(MS_GROUPED_BT.BUDGETEXPENSETYPEID, 4, '0')) AS ID,
                MS_GROUPED_BT.BUDGETPLANID || '.' || LPAD(MS_GROUPED_BT.PRODUCTID, 5, '0') || '.' || LPAD(MS_GROUPED_BT.ACTIVITYCODEID, 5, '0') || '.' || LPAD(MS_GROUPED_BT.BUDGETEXPENSETYPEID, 4, '0') || '.0000' AS ORDERCODE,
                NULL AS CODE,
                NULL AS BUDGETGOVERNMENTID,
                NULL AS BUDGETRECEIVEPERIODID,
                NULL AS BUDGETYEAR,
                NULL AS PRODUCTID,
                NULL AS ACTIVITYID,
                NULL AS BUDGETPLANID,
                NULL AS BUDGETTYPEID,
                NULL AS CATEGORYID,
                MS_GROUPED_BT.DESCRIPTION AS CATEGORYNAME,
                NULL AS DEPARTMENTID,
                NULL AS COSTCENTERID,
                TO_CHAR(
                    MS_GROUPED_BT.BUDGETPLANID || LPAD(MS_GROUPED_BT.PRODUCTID, 5, '0') || LPAD(MS_GROUPED_BT.ACTIVITYCODEID, 5, '0')
                ) AS PARENTID,
                TO_CHAR(
                    MS_GROUPED_BT.BUDGETPLANID || LPAD(MS_GROUPED_BT.PRODUCTID, 5, '0') || LPAD(MS_GROUPED_BT.ACTIVITYCODEID, 5, '0') || MS_GROUPED_BT.BUDGETEXPENSETYPEID
                ) AS NODEID,
                NULL AS ISCATEGORY,
                SUM(CC.TOTALALLOCATEAMOUNT) AS TOTALALLOCATEAMOUNT,
                SUM(CC.TOTALBALANCEAMOUNT) AS TOTALBALANCEAMOUNT,
                SUM(CC.TOTALRECEIVEAMOUNT) AS TOTALRECEIVEAMOUNT,
		        SUM(CC.TOTALRECEIVEACCUMAMOUNT) AS TOTALRECEIVEACCUMAMOUNT,
                '4' AS LEVEL_NAME
            FROM MS_GROUPED_BT
                LEFT JOIN CC 
                    ON CC.BUDGETTYPEID = MS_GROUPED_BT.BUDGETEXPENSETYPEID
                    AND CC.BUDGETPLANID = MS_GROUPED_BT.BUDGETPLANID
                    AND CC.PRODUCTID = LPAD(MS_GROUPED_BT.PRODUCTID, 5, '0')
                    AND CC.ACTIVITYID = LPAD(MS_GROUPED_BT.ACTIVITYCODEID, 5, '0')
            GROUP BY 
                MS_GROUPED_BT.BUDGETEXPENSETYPEID,
                MS_GROUPED_BT.ACTIVITYCODEID,
                MS_GROUPED_BT.BUDGETPLANID,
                MS_GROUPED_BT.PRODUCTID,
                MS_GROUPED_BT.BUDGETYEAR,
                MS_GROUPED_BT.DESCRIPTION
        ),
        -- BA (Budget Activity Level - Level 3)
        BA AS (
            SELECT 
                LPAD(MS_GROUPED_BA.ACTIVITYCODEID, 5, '0') AS ID,
                MS_GROUPED_BA.BUDGETPLANID || '.' || LPAD(MS_GROUPED_BA.PRODUCTID, 5, '0') || '.' || LPAD(MS_GROUPED_BA.ACTIVITYCODEID, 5, '0') || '.0000.0000' AS ORDERCODE,
                NULL AS CODE,
                NULL AS BUDGETGOVERNMENTID,
                NULL AS BUDGETRECEIVEPERIODID,
                NULL AS BUDGETYEAR,
                NULL AS PRODUCTID,
                NULL AS ACTIVITYID,
                NULL AS BUDGETPLANID,
                NULL AS BUDGETTYPEID,
                NULL AS CATEGORYID,
                MS_GROUPED_BA.CATEGORYNAME,
                NULL AS DEPARTMENTID,
                NULL AS COSTCENTERID,
                TO_CHAR(
                    MS_GROUPED_BA.BUDGETPLANID || LPAD(MS_GROUPED_BA.PRODUCTID, 5, '0')
                ) AS PARENTID,
                TO_CHAR(
                    MS_GROUPED_BA.BUDGETPLANID || LPAD(MS_GROUPED_BA.PRODUCTID, 5, '0') || LPAD(MS_GROUPED_BA.ACTIVITYCODEID, 5, '0')
                ) AS NODEID,
                NULL AS ISCATEGORY,
                SUM(BT.TOTALALLOCATEAMOUNT) AS TOTALALLOCATEAMOUNT,
                SUM(BT.TOTALBALANCEAMOUNT) AS TOTALBALANCEAMOUNT,
                SUM(BT.TOTALRECEIVEAMOUNT) AS TOTALRECEIVEAMOUNT,
		        SUM(BT.TOTALRECEIVEACCUMAMOUNT) AS TOTALRECEIVEACCUMAMOUNT,
                '3' AS LEVEL_NAME
            FROM MS_GROUPED_BA
                LEFT JOIN BT 
                    ON BT.PARENTID = TO_CHAR(
                        MS_GROUPED_BA.BUDGETPLANID || LPAD(MS_GROUPED_BA.PRODUCTID, 5, '0') || LPAD(MS_GROUPED_BA.ACTIVITYCODEID, 5, '0')
                    )
            GROUP BY 
                MS_GROUPED_BA.ACTIVITYCODEID,
                MS_GROUPED_BA.PRODUCTID,
                MS_GROUPED_BA.BUDGETPLANID,
                MS_GROUPED_BA.BUDGETYEAR,
                MS_GROUPED_BA.CATEGORYNAME
        ),
        -- BPD (PRODUCT Level - Level 2)
        BPD AS (
            SELECT 
                LPAD(MS_GROUPED_BPD.PRODUCTID, 5, '0') AS ID,
                MS_GROUPED_BPD.BUDGETPLANID || '.' || LPAD(MS_GROUPED_BPD.PRODUCTID, 5, '0') || '.00000.0000.0000' AS ORDERCODE,
                NULL AS CODE,
                NULL AS BUDGETGOVERNMENTID,
                NULL AS BUDGETRECEIVEPERIODID,
                NULL AS BUDGETYEAR,
                NULL AS PRODUCTID,
                NULL AS ACTIVITYID,
                NULL AS BUDGETPLANID,
                NULL AS BUDGETTYPEID,
                NULL AS CATEGORYID,
                MS_GROUPED_BPD.CATEGORYNAME,
                NULL AS DEPARTMENTID,
                NULL AS COSTCENTERID,
                TO_CHAR(MS_GROUPED_BPD.BUDGETPLANID) AS PARENTID,
                TO_CHAR(
                    MS_GROUPED_BPD.BUDGETPLANID || LPAD(MS_GROUPED_BPD.PRODUCTID, 5, '0')
                ) AS NODEID,
                NULL AS ISCATEGORY,
                SUM(BA.TOTALALLOCATEAMOUNT) AS TOTALALLOCATEAMOUNT,
                SUM(BA.TOTALBALANCEAMOUNT) AS TOTALBALANCEAMOUNT,
                SUM(BA.TOTALRECEIVEAMOUNT) AS TOTALRECEIVEAMOUNT,
		        SUM(BA.TOTALRECEIVEACCUMAMOUNT) AS TOTALRECEIVEACCUMAMOUNT,
                '2' AS LEVEL_NAME
            FROM MS_GROUPED_BPD
                LEFT JOIN BA 
                    ON BA.PARENTID = TO_CHAR(
                        MS_GROUPED_BPD.BUDGETPLANID || LPAD(MS_GROUPED_BPD.PRODUCTID, 5, '0')
                    )
            GROUP BY 
                MS_GROUPED_BPD.BUDGETPLANID,
                MS_GROUPED_BPD.PRODUCTID,
                MS_GROUPED_BPD.BUDGETYEAR,
                MS_GROUPED_BPD.CATEGORYNAME
        ),
        -- BP (PLAN Level - Level 1)
        BP AS (
            SELECT 
                TO_CHAR(MS_GROUPED_BP.BUDGETPLANID) AS ID,
                MS_GROUPED_BP.BUDGETPLANID || '.00000.00000.0000.0000' AS ORDERCODE,
                NULL AS CODE,
                NULL AS BUDGETGOVERNMENTID,
                NULL AS BUDGETRECEIVEPERIODID,
                NULL AS BUDGETYEAR,
                NULL AS PRODUCTID,
                NULL AS ACTIVITYID,
                NULL AS BUDGETPLANID,
                NULL AS BUDGETTYPEID,
                NULL AS CATEGORYID,
                MS_GROUPED_BP.CATEGORYNAME,
                NULL AS DEPARTMENTID,
                NULL AS COSTCENTERID,
                NULL AS PARENTID,
                TO_CHAR(MS_GROUPED_BP.BUDGETPLANID) AS NODEID,
                NULL AS ISCATEGORY,
                SUM(BPD.TOTALALLOCATEAMOUNT) AS TOTALALLOCATEAMOUNT,
                SUM(BPD.TOTALBALANCEAMOUNT) AS TOTALBALANCEAMOUNT,
                SUM(BPD.TOTALRECEIVEAMOUNT) AS TOTALRECEIVEAMOUNT,
		        SUM(BPD.TOTALRECEIVEACCUMAMOUNT) AS TOTALRECEIVEACCUMAMOUNT,
                '1' AS LEVEL_NAME
            FROM MS_GROUPED_BP
                LEFT JOIN BPD 
                    ON BPD.PARENTID = TO_CHAR(MS_GROUPED_BP.BUDGETPLANID)
            GROUP BY 
                MS_GROUPED_BP.BUDGETPLANID,
                MS_GROUPED_BP.BUDGETYEAR,
                MS_GROUPED_BP.CATEGORYNAME
        )
        -- Union all levels and order by hierarchy
        SELECT DT.*
        FROM (
            SELECT * FROM BP
			UNION ALL
			SELECT * FROM BPD
			UNION ALL
			SELECT * FROM BA
			UNION ALL
			SELECT * FROM BT
			UNION ALL
			SELECT * FROM GG
			UNION ALL
			SELECT * FROM CC
        ) DT
        LEFT JOIN OAGWBG_BUDGETRECEIVEPERIOD BG6 
            ON BG6.ID = PAR_BUDGETRECEIVEPERIODID
        LEFT JOIN OAGWBG_V_EXT_OAGGL_BUDGET_CATEGORY_PLAN BGP 
            ON BGP.BUDGETPLAN_ID = BG6.BUDGETPLANID
        WHERE (BG6.BUDGETPLANID = 50000) 
            OR (DT.NODEID LIKE BGP.ID || '%' OR DT.PARENTID LIKE BGP.ID || '%')
        ORDER BY ORDERCODE, LEVEL_NAME
    ) LOOP 
        PIPE ROW (
            OAGWBG_FN_GETBUDGET_RECEIVE_PERIOD_CATEGORY_ROW (
                R.ID,
                R.ORDERCODE,
                R.CODE,
                R.BUDGETGOVERNMENTID,
                R.BUDGETRECEIVEPERIODID,
                R.BUDGETYEAR,
                R.PRODUCTID,
                R.ACTIVITYID,
                R.BUDGETPLANID,
                R.BUDGETTYPEID,
                R.CATEGORYID,
                R.CATEGORYNAME,
                R.DEPARTMENTID,
                R.COSTCENTERID,
                R.PARENTID,
                R.NODEID,
                R.ISCATEGORY,
                R.TOTALALLOCATEAMOUNT,
                R.TOTALBALANCEAMOUNT,
                R.TOTALRECEIVEAMOUNT,
                R.TOTALRECEIVEACCUMAMOUNT,
                R.LEVEL_NAME
            )
        );
    END LOOP;

    RETURN;
END;
