-- ตรวจว่า BG4P (fallback) ดึงยอดเกินมาจากแถวที่ไม่ควรนับหรือไม่
-- READ-ONLY ล้วน
--
-- ที่มา : ซับคิวรี BG4P มี WHERE แค่ PBG.RUNNING IS NOT NULL
--         ต่างจาก BG ในตัว view ที่กรอง BUDGETFORMTYPEID / BUDGETGOVERNMENTTYPE /
--         BUDGETSTATUS / BUDGETTYPEID / PROJECT.TEMP
--         => แถวแม่ที่ "ไม่มีสิทธิ์ขึ้นจอ" ก็ยังส่งค่าต่อให้ลูกได้
--
-- ผลบน PREPROD : ไม่มี leak (25 แถว OK หมด, ยอดต่าง 0 ทุกปี)
--                แต่ PROD ข้อมูลเยอะกว่าและหลากหลายกว่า ต้องตรวจเอง
--------------------------------------------------------------------------------


-- ════════════════════════════════════════════════════════════════════
-- [L1] แถวแม่ที่ป้อนค่าให้ลูก — ผ่านตัวกรองเดียวกับ view หรือไม่
--      ถ้ามีบรรทัดที่ไม่ใช่ 'OK)' = leak  ดู SUM_LEAK ว่าเป็นเงินเท่าไร
-- ════════════════════════════════════════════════════════════════════
WITH VISIBLE_BG AS (
  SELECT BG.ID, BG.RUNNING, BG.BUDGETREQUESTID, BR.PARENTID
  FROM OAGWBG_BUDGETREQUEST BR
  JOIN OAGWBG_BUDGETGOVERNMENT BG ON BG.BUDGETREQUESTID = BR.ID
       AND BG.BUDGETFORMTYPEID IN (1,2) AND BG.ID IS NOT NULL
       AND (BG.BUDGETGOVERNMENTTYPE IS NULL OR BG.BUDGETGOVERNMENTTYPE = '7')
       AND BG.BUDGETSTATUS NOT IN ('A','X')
  WHERE BR.BUDGETTYPEID = 1 AND BR.PARENTID IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM OAGWBG_BUDGETREQUEST B2
                  WHERE B2.PARENTID IS NOT NULL AND B2.PARENTID = BG.BUDGETREQUESTID)
)
SELECT
  CASE WHEN PBG.BUDGETSTATUS IN ('A','X')                THEN 'A) PBG BUDGETSTATUS = A/X'
       WHEN PBG.BUDGETFORMTYPEID NOT IN (1,2)            THEN 'B) PBG formtype ไม่ใช่ 1,2'
       WHEN NOT (PBG.BUDGETGOVERNMENTTYPE IS NULL
                 OR PBG.BUDGETGOVERNMENTTYPE = '7')      THEN 'C) PBG type ไม่ใช่ null/7'
       WHEN PBR.BUDGETTYPEID <> 1                        THEN 'D) คำขอแม่ BUDGETTYPEID <> 1'
       WHEN PBG.PROJECTID IS NOT NULL AND EXISTS (
            SELECT 1 FROM OAGWBG_PROJECT
            WHERE TEMP IS NOT NULL AND TEMP = PBG.PROJECTID) THEN 'E) PROJECT.TEMP ชี้อยู่'
       ELSE 'OK) PBG ผ่านตัวกรองเดียวกับ view' END AS PBG_STATE,
  NVL(PBG.BUDGETGOVERNMENTTYPE,'<null>') BGTYPE, PBG.BUDGETSTATUS, PBG.BUDGETFORMTYPEID,
  COUNT(*) N_ROWS, SUM(NVL(B4P.KEPTCENTRAL,0)) SUM_LEAK
FROM VISIBLE_BG V
JOIN OAGWBG_BUDGETGOVERNMENT PBG
     ON PBG.BUDGETREQUESTID = V.PARENTID AND PBG.RUNNING = V.RUNNING
JOIN OAGWBG_BUDGETGOVERNMENT B4P
     ON B4P.REF_BUDGETGOVERNMENTID = PBG.ID AND B4P.BUDGETGOVERNMENTTYPE = '4'
LEFT JOIN OAGWBG_BUDGETREQUEST PBR ON PBR.ID = PBG.BUDGETREQUESTID
GROUP BY
  CASE WHEN PBG.BUDGETSTATUS IN ('A','X')                THEN 'A) PBG BUDGETSTATUS = A/X'
       WHEN PBG.BUDGETFORMTYPEID NOT IN (1,2)            THEN 'B) PBG formtype ไม่ใช่ 1,2'
       WHEN NOT (PBG.BUDGETGOVERNMENTTYPE IS NULL
                 OR PBG.BUDGETGOVERNMENTTYPE = '7')      THEN 'C) PBG type ไม่ใช่ null/7'
       WHEN PBR.BUDGETTYPEID <> 1                        THEN 'D) คำขอแม่ BUDGETTYPEID <> 1'
       WHEN PBG.PROJECTID IS NOT NULL AND EXISTS (
            SELECT 1 FROM OAGWBG_PROJECT
            WHERE TEMP IS NOT NULL AND TEMP = PBG.PROJECTID) THEN 'E) PROJECT.TEMP ชี้อยู่'
       ELSE 'OK) PBG ผ่านตัวกรองเดียวกับ view' END,
  NVL(PBG.BUDGETGOVERNMENTTYPE,'<null>'), PBG.BUDGETSTATUS, PBG.BUDGETFORMTYPEID
ORDER BY 1,2,3;


-- ════════════════════════════════════════════════════════════════════
-- [L2] เทียบยอด : BG4P แบบเดิม vs แบบรัดกุม  →  "ยอดที่เกินมา" เป็นเงินเท่าไร
-- ════════════════════════════════════════════════════════════════════
WITH BASE AS (
  SELECT BR.ID REQ, BR.PARENTID, BR.BUDGETYEAR, BG.ID BG_ID, BG.RUNNING
  FROM OAGWBG_BUDGETREQUEST BR
  JOIN OAGWBG_BUDGETGOVERNMENT BG ON BG.BUDGETREQUESTID = BR.ID
       AND BG.BUDGETFORMTYPEID IN (1,2) AND BG.ID IS NOT NULL
       AND (BG.BUDGETGOVERNMENTTYPE IS NULL OR BG.BUDGETGOVERNMENTTYPE='7')
       AND BG.BUDGETSTATUS NOT IN ('A','X')
  WHERE BR.BUDGETTYPEID = 1
  AND NOT EXISTS (SELECT 1 FROM OAGWBG_BUDGETREQUEST B2
                  WHERE B2.PARENTID IS NOT NULL AND B2.PARENTID = BG.BUDGETREQUESTID)
  AND (BG.PROJECTID IS NULL OR NOT EXISTS (
       SELECT 1 FROM OAGWBG_PROJECT WHERE TEMP IS NOT NULL AND TEMP = BG.PROJECTID))
),
OWN4 AS (SELECT REF_BUDGETGOVERNMENTID REF, SUM(KEPTCENTRAL) K
         FROM OAGWBG_BUDGETGOVERNMENT WHERE BUDGETGOVERNMENTTYPE='4'
         GROUP BY REF_BUDGETGOVERNMENTID),
OLD4P AS (
  SELECT PBG.BUDGETREQUESTID PARENT_REQID, PBG.RUNNING, SUM(B4P.KEPTCENTRAL) K
  FROM OAGWBG_BUDGETGOVERNMENT PBG
  JOIN OAGWBG_BUDGETGOVERNMENT B4P
       ON B4P.REF_BUDGETGOVERNMENTID=PBG.ID AND B4P.BUDGETGOVERNMENTTYPE='4'
  WHERE PBG.RUNNING IS NOT NULL
  GROUP BY PBG.BUDGETREQUESTID, PBG.RUNNING HAVING COUNT(*)=1),
NEW4P AS (
  SELECT PBG.BUDGETREQUESTID PARENT_REQID, PBG.RUNNING, SUM(B4P.KEPTCENTRAL) K
  FROM OAGWBG_BUDGETGOVERNMENT PBG
  JOIN OAGWBG_BUDGETREQUEST PBR ON PBR.ID = PBG.BUDGETREQUESTID AND PBR.BUDGETTYPEID = 1
  JOIN OAGWBG_BUDGETGOVERNMENT B4P
       ON B4P.REF_BUDGETGOVERNMENTID=PBG.ID AND B4P.BUDGETGOVERNMENTTYPE='4'
  WHERE PBG.RUNNING IS NOT NULL
    AND PBG.BUDGETFORMTYPEID IN (1,2)
    AND (PBG.BUDGETGOVERNMENTTYPE IS NULL OR PBG.BUDGETGOVERNMENTTYPE='7')
    AND PBG.BUDGETSTATUS NOT IN ('A','X')
    AND (PBG.PROJECTID IS NULL OR NOT EXISTS (
         SELECT 1 FROM OAGWBG_PROJECT WHERE TEMP IS NOT NULL AND TEMP = PBG.PROJECTID))
  GROUP BY PBG.BUDGETREQUESTID, PBG.RUNNING HAVING COUNT(*)=1)
SELECT B.BUDGETYEAR,
       SUM(NVL(COALESCE(O.K, OP.K),0)) SUM_แบบเดิม,
       SUM(NVL(COALESCE(O.K, NP.K),0)) SUM_แบบรัดกุม,
       SUM(NVL(COALESCE(O.K, OP.K),0)) - SUM(NVL(COALESCE(O.K, NP.K),0)) AS ยอดที่เกินมา
FROM BASE B
LEFT JOIN OWN4  O  ON O.REF = B.BG_ID
LEFT JOIN OLD4P OP ON OP.PARENT_REQID = B.PARENTID AND OP.RUNNING = B.RUNNING
LEFT JOIN NEW4P NP ON NP.PARENT_REQID = B.PARENTID AND NP.RUNNING = B.RUNNING
GROUP BY B.BUDGETYEAR ORDER BY 1;


-- ════════════════════════════════════════════════════════════════════
-- [L3] type-4 ที่ BUDGETYEAR ไม่ตรงกับ BG ที่มันชี้ไป
--      (ทั้ง BG4 และ BG4P ไม่ได้เช็คปีงบ — ถ้ามีแถวแบบนี้ ยอดจะข้ามปีได้)
--      PREPROD : 0 แถว
-- ════════════════════════════════════════════════════════════════════
SELECT T.BUDGETYEAR T4_YEAR, BG.BUDGETYEAR BG_YEAR, COUNT(*) N, SUM(NVL(T.KEPTCENTRAL,0)) SUM_KEPT
FROM   OAGWBG_BUDGETGOVERNMENT T
JOIN   OAGWBG_BUDGETGOVERNMENT BG ON BG.ID = T.REF_BUDGETGOVERNMENTID
WHERE  T.BUDGETGOVERNMENTTYPE = '4'
AND    NVL(T.BUDGETYEAR,-1) <> NVL(BG.BUDGETYEAR,-1)
GROUP  BY T.BUDGETYEAR, BG.BUDGETYEAR
ORDER  BY 1,2;
