-- ════════════════════════════════════════════════════════════════════
-- [P1a] OAGWBG_V_BUDGETREQUESTSUMMARY : OLD vs NEW
-- ════════════════════════════════════════════════════════════════════
WITH NEWV AS (
  SELECT BR.BUDGETYEAR, COALESCE(BG4.KEPTCENTRAL, BG4P.KEPTCENTRAL) AS NEW_KEPT
  FROM OAGWBG_BUDGETREQUEST BR
  JOIN OAGWBG_BUDGETGOVERNMENT BG
        ON BG.BUDGETREQUESTID = BR.ID AND BG.BUDGETFORMTYPEID IN (1,2) AND BG.ID IS NOT NULL
       AND (BG.BUDGETGOVERNMENTTYPE IS NULL OR BG.BUDGETGOVERNMENTTYPE = '7')
       AND BG.BUDGETSTATUS NOT IN ('A','X')
  LEFT JOIN (SELECT REF_BUDGETGOVERNMENTID, SUM(KEPTCENTRAL) AS KEPTCENTRAL
             FROM OAGWBG_BUDGETGOVERNMENT WHERE BUDGETGOVERNMENTTYPE = '4'
             GROUP BY REF_BUDGETGOVERNMENTID) BG4 ON BG.ID = BG4.REF_BUDGETGOVERNMENTID
  LEFT JOIN (SELECT PBG.BUDGETREQUESTID AS PARENT_REQID, PBG.RUNNING, SUM(B4P.KEPTCENTRAL) AS KEPTCENTRAL
             FROM OAGWBG_BUDGETGOVERNMENT PBG
             JOIN OAGWBG_BUDGETGOVERNMENT B4P
                  ON B4P.REF_BUDGETGOVERNMENTID = PBG.ID AND B4P.BUDGETGOVERNMENTTYPE = '4'
             WHERE PBG.RUNNING IS NOT NULL
             GROUP BY PBG.BUDGETREQUESTID, PBG.RUNNING HAVING COUNT(*) = 1) BG4P
        ON BG4P.PARENT_REQID = BR.PARENTID AND BG4P.RUNNING = BG.RUNNING
  WHERE BR.BUDGETTYPEID = 1
  AND NOT EXISTS (SELECT 1 FROM OAGWBG_BUDGETREQUEST B2
                  WHERE B2.PARENTID IS NOT NULL AND B2.PARENTID = BG.BUDGETREQUESTID)
  AND (BG.PROJECTID IS NULL OR NOT EXISTS (
        SELECT 1 FROM OAGWBG_PROJECT WHERE TEMP IS NOT NULL AND TEMP = BG.PROJECTID))
)
SELECT 'OLD' SRC, BUDGETYEAR, COUNT(*) ROWS_, COUNT(TOTALKEPTCENTRAL) HAS_KEPT,
       SUM(NVL(TOTALKEPTCENTRAL,0)) SUM_KEPT
FROM   OAGWBG_V_BUDGETREQUESTSUMMARY GROUP BY BUDGETYEAR
UNION ALL
SELECT 'NEW', BUDGETYEAR, COUNT(*), COUNT(NEW_KEPT), SUM(NVL(NEW_KEPT,0))
FROM   NEWV GROUP BY BUDGETYEAR
ORDER  BY 2, 1;


-- ════════════════════════════════════════════════════════════════════
-- [P1b] OAGWBG_R_BUDGETREQUEST : OLD vs NEW   (คอลัมน์ REQUESTAMOUNT_ADD)
-- ════════════════════════════════════════════════════════════════════
SELECT 'OLD' SRC, BUDGETYEAR, COUNT(*) ROWS_, SUM(NVL(REQUESTAMOUNT_ADD,0)) SUM_ADD
FROM   OAGWBG_R_BUDGETREQUEST GROUP BY BUDGETYEAR
UNION ALL
SELECT 'NEW', BG.BUDGETYEAR, COUNT(*), SUM(NVL(COALESCE(BG4.KEPTCENTRAL, BG4P.KEPTCENTRAL),0))
FROM ( SELECT BG.ID, BG.BUDGETREQUESTID, BG.RUNNING, BG.BUDGETYEAR
       FROM   OAGWBG_V_BUDGETGOVERNMENT BG
       WHERE  BG.BUDGETFORMTYPEID = 1 AND BG.BUDGETREQUESTID != 0
       AND    BG.BUDGETSTATUS NOT IN ('X')
       AND    BG.BUDGETREQUESTID IN (SELECT ob2.ID FROM OAGWBG_BUDGETREQUEST ob2)
       AND    NOT EXISTS (SELECT 1 FROM OAGWBG_BUDGETREQUEST BR
                          WHERE BR.PARENTID IS NOT NULL AND BR.PARENTID = BG.BUDGETREQUESTID) ) BG
LEFT JOIN (SELECT REF_BUDGETGOVERNMENTID, BUDGETDETAIL, SUM(KEPTCENTRAL) KEPTCENTRAL
           FROM OAGWBG_BUDGETGOVERNMENT WHERE BUDGETGOVERNMENTTYPE='4'
           GROUP BY REF_BUDGETGOVERNMENTID, BUDGETDETAIL) BG4 ON BG.ID = BG4.REF_BUDGETGOVERNMENTID
LEFT JOIN OAGWBG_BUDGETREQUEST PBR ON PBR.ID = BG.BUDGETREQUESTID
LEFT JOIN (SELECT PBG.BUDGETREQUESTID PARENT_REQID, PBG.RUNNING, SUM(B4P.KEPTCENTRAL) KEPTCENTRAL
           FROM OAGWBG_BUDGETGOVERNMENT PBG
           JOIN OAGWBG_BUDGETGOVERNMENT B4P
                ON B4P.REF_BUDGETGOVERNMENTID = PBG.ID AND B4P.BUDGETGOVERNMENTTYPE='4'
           WHERE PBG.RUNNING IS NOT NULL
           GROUP BY PBG.BUDGETREQUESTID, PBG.RUNNING HAVING COUNT(*)=1) BG4P
     ON BG4P.PARENT_REQID = PBR.PARENTID AND BG4P.RUNNING = BG.RUNNING
GROUP BY BG.BUDGETYEAR
ORDER BY 2, 1;


-- ════════════════════════════════════════════════════════════════════
-- [P1c] OAGWBG_V_BUDGETREQUESTSUMMARYLIST : OLD vs NEW
--       จำนวน "กลุ่ม" ต้องเท่ากัน (view นี้ GROUP BY อยู่แล้ว)
-- ════════════════════════════════════════════════════════════════════
SELECT 'OLD' SRC, BUDGETYEAR, BUDGETFORMTYPEID, TOTALRECEIVEAMOUNT
FROM   OAGWBG_V_BUDGETREQUESTSUMMARYLIST
UNION ALL
SELECT 'NEW', BR.BUDGETYEAR, BR.BUDGETFORMTYPEID,
       SUM(NVL(COALESCE(BG4.KEPTCENTRAL, BG4P.KEPTCENTRAL),0))
FROM OAGWBG_BUDGETREQUEST BR
LEFT JOIN OAGWBG_BUDGETGOVERNMENT BG
     ON BG.BUDGETREQUESTID = BR.ID AND BG.ID IS NOT NULL
    AND (BG.BUDGETGOVERNMENTTYPE IS NULL OR BG.BUDGETGOVERNMENTTYPE = 7)
LEFT JOIN (SELECT REF_BUDGETGOVERNMENTID, SUM(KEPTCENTRAL) AS KEPTCENTRAL
           FROM OAGWBG_BUDGETGOVERNMENT WHERE BUDGETGOVERNMENTTYPE = 4
           GROUP BY REF_BUDGETGOVERNMENTID) BG4 ON BG.ID = BG4.REF_BUDGETGOVERNMENTID
LEFT JOIN (SELECT PBG.BUDGETREQUESTID PARENT_REQID, PBG.RUNNING, SUM(B4P.KEPTCENTRAL) KEPTCENTRAL
           FROM OAGWBG_BUDGETGOVERNMENT PBG
           JOIN OAGWBG_BUDGETGOVERNMENT B4P
                ON B4P.REF_BUDGETGOVERNMENTID = PBG.ID AND B4P.BUDGETGOVERNMENTTYPE = '4'
           WHERE PBG.RUNNING IS NOT NULL
           GROUP BY PBG.BUDGETREQUESTID, PBG.RUNNING HAVING COUNT(*)=1) BG4P
     ON BG4P.PARENT_REQID = BR.PARENTID AND BG4P.RUNNING = BG.RUNNING
LEFT JOIN OAGWBG_PROJECTTARGETS OPT ON OPT.PROJECTID = BG.PROJECTID
WHERE NOT EXISTS (SELECT 1 FROM OAGWBG_BUDGETREQUEST B2
                  WHERE B2.PARENTID IS NOT NULL AND B2.PARENTID = BG.BUDGETREQUESTID)
AND (BG.PROJECTID IS NULL OR NOT EXISTS (
     SELECT 1 FROM OAGWBG_PROJECT WHERE TEMP IS NOT NULL AND TEMP = BG.PROJECTID))
AND BG.BUDGETSTATUS NOT IN ('A','X')
AND BR.BUDGETFORMTYPEID IN (1, 2)
GROUP BY BR.BUDGETYEAR, BR.BUDGETFORMTYPEID
ORDER BY 2, 3, 1;


-- ════════════════════════════════════════════════════════════════════
-- [P2] แถวที่จะ "กลับมา" — ของตัวเองว่าง แต่ของแม่มีค่า
--      คาดว่า 318 แถว รวม 114,693,702 บาท (ปี 2570)
-- ════════════════════════════════════════════════════════════════════
SELECT BR.BUDGETYEAR, BR.ID CHILD_REQ, BR.PARENTID PARENT_REQ, BR.COSTCENTERID,
       BG.ID CHILD_BG, BG.RUNNING, BG.CATEGORYID, BG.TOTALREQUESTAMOUNT,
       BG4P.KEPTCENTRAL AS จะกลับมาเป็น
FROM OAGWBG_BUDGETREQUEST BR
JOIN OAGWBG_BUDGETGOVERNMENT BG
      ON BG.BUDGETREQUESTID = BR.ID AND BG.BUDGETFORMTYPEID IN (1,2)
     AND (BG.BUDGETGOVERNMENTTYPE IS NULL OR BG.BUDGETGOVERNMENTTYPE='7')
     AND BG.BUDGETSTATUS NOT IN ('A','X')
LEFT JOIN (SELECT REF_BUDGETGOVERNMENTID, SUM(KEPTCENTRAL) AS KEPTCENTRAL
           FROM OAGWBG_BUDGETGOVERNMENT WHERE BUDGETGOVERNMENTTYPE='4'
           GROUP BY REF_BUDGETGOVERNMENTID) BG4 ON BG.ID = BG4.REF_BUDGETGOVERNMENTID
JOIN (SELECT PBG.BUDGETREQUESTID AS PARENT_REQID, PBG.RUNNING, SUM(B4P.KEPTCENTRAL) AS KEPTCENTRAL
      FROM OAGWBG_BUDGETGOVERNMENT PBG
      JOIN OAGWBG_BUDGETGOVERNMENT B4P
           ON B4P.REF_BUDGETGOVERNMENTID = PBG.ID AND B4P.BUDGETGOVERNMENTTYPE='4'
      WHERE PBG.RUNNING IS NOT NULL
      GROUP BY PBG.BUDGETREQUESTID, PBG.RUNNING HAVING COUNT(*)=1) BG4P
     ON BG4P.PARENT_REQID = BR.PARENTID AND BG4P.RUNNING = BG.RUNNING
WHERE BR.BUDGETTYPEID = 1
AND   BG4.KEPTCENTRAL  IS NULL
AND   BG4P.KEPTCENTRAL IS NOT NULL
ORDER BY BR.BUDGETYEAR, BR.ID, BG.RUNNING;


-- ════════════════════════════════════════════════════════════════════
-- [P3] orphan ที่ fallback เก็บไม่ได้ (BG แม่ถูกลบ / RUNNING ซ้ำ)
-- ════════════════════════════════════════════════════════════════════
SELECT B4.BUDGETYEAR,
       CASE WHEN PBG.ID IS NULL THEN 'BG แม่ถูกลบ — กู้ไม่ได้'
            WHEN CNT.N > 1      THEN 'RUNNING ซ้ำ — ถูก guard กรองทิ้ง'
            ELSE 'อื่น ๆ' END REASON,
       COUNT(*) CNT, SUM(NVL(B4.KEPTCENTRAL,0)) SUM_KEPT
FROM OAGWBG_BUDGETGOVERNMENT B4
LEFT JOIN OAGWBG_BUDGETGOVERNMENT PBG ON PBG.ID = B4.REF_BUDGETGOVERNMENTID
LEFT JOIN (SELECT BUDGETREQUESTID, RUNNING, COUNT(*) N
           FROM OAGWBG_BUDGETGOVERNMENT WHERE RUNNING IS NOT NULL
           GROUP BY BUDGETREQUESTID, RUNNING) CNT
       ON CNT.BUDGETREQUESTID = PBG.BUDGETREQUESTID AND CNT.RUNNING = PBG.RUNNING
WHERE B4.BUDGETGOVERNMENTTYPE = '4'
AND   (PBG.ID IS NULL OR NVL(CNT.N,1) > 1)
GROUP BY B4.BUDGETYEAR,
       CASE WHEN PBG.ID IS NULL THEN 'BG แม่ถูกลบ — กู้ไม่ได้'
            WHEN CNT.N > 1      THEN 'RUNNING ซ้ำ — ถูก guard กรองทิ้ง'
            ELSE 'อื่น ๆ' END
ORDER BY 1, 3 DESC;


-- ════════════════════════════════════════════════════════════════════
-- [P4] ★ GATE : ค่าของแม่ 1 ก้อน ถูกเคลมโดยลูกมากกว่า 1 แถวหรือไม่
--      ต้องคืน 0 แถว  ถ้ามีแถว = จะนับซ้ำ → หยุด deploy
-- ════════════════════════════════════════════════════════════════════
SELECT BG4P.PARENT_REQID, BG4P.RUNNING, BG4P.KEPTCENTRAL,
       COUNT(*) CLAIMED_BY_N_ROWS,
       LISTAGG(BG.ID, ' ') WITHIN GROUP (ORDER BY BG.ID) CHILD_BG_IDS
FROM OAGWBG_BUDGETREQUEST BR
JOIN OAGWBG_BUDGETGOVERNMENT BG
      ON BG.BUDGETREQUESTID = BR.ID AND BG.BUDGETFORMTYPEID IN (1,2)
     AND (BG.BUDGETGOVERNMENTTYPE IS NULL OR BG.BUDGETGOVERNMENTTYPE='7')
     AND BG.BUDGETSTATUS NOT IN ('A','X')
JOIN (SELECT PBG.BUDGETREQUESTID AS PARENT_REQID, PBG.RUNNING, SUM(B4P.KEPTCENTRAL) AS KEPTCENTRAL
      FROM OAGWBG_BUDGETGOVERNMENT PBG
      JOIN OAGWBG_BUDGETGOVERNMENT B4P
           ON B4P.REF_BUDGETGOVERNMENTID = PBG.ID AND B4P.BUDGETGOVERNMENTTYPE='4'
      WHERE PBG.RUNNING IS NOT NULL
      GROUP BY PBG.BUDGETREQUESTID, PBG.RUNNING HAVING COUNT(*)=1) BG4P
     ON BG4P.PARENT_REQID = BR.PARENTID AND BG4P.RUNNING = BG.RUNNING
WHERE BR.BUDGETTYPEID = 1
GROUP BY BG4P.PARENT_REQID, BG4P.RUNNING, BG4P.KEPTCENTRAL
HAVING COUNT(*) > 1
ORDER BY 4 DESC;


-- ════════════════════════════════════════════════════════════════════
-- [P5] ★ GATE : มีคำขอต้นฉบับที่ถูก clone ซ้ำจนมีลูก 2 ใบหรือไม่
--      ต้องคืน 0 แถว  ถ้ามีแถว = ยอด TOTALREQUESTAMOUNT นับซ้ำอยู่แล้ว
--      (บั๊กเดิม ไม่ได้เกิดจาก view ใหม่ แต่ต้องรู้ก่อน deploy)
-- ════════════════════════════════════════════════════════════════════
SELECT PARENTID, COUNT(*) N_CHILDREN,
       LISTAGG(ID||'(st'||STATUSID||')', ' ') WITHIN GROUP (ORDER BY ID) CHILDREN
FROM   OAGWBG_BUDGETREQUEST
WHERE  PARENTID IS NOT NULL
GROUP  BY PARENTID
HAVING COUNT(*) > 1
ORDER  BY 2 DESC;
