-- ⚠️ ตัวนี้คือตัวที่ทำให้ยอดเบิ้ล — ใช้เฉพาะเมื่อ deploy แล้วมีปัญหาอื่นเท่านั้น
CREATE OR REPLACE FORCE EDITIONABLE VIEW "OAGWBG"."OAGWBG_R_BUDGETALLOCATE" ("BUDGETYEAR", "BUDGETPLANID", "BUDGETPLANIDDISPLAY", "BUDGETPLANNAME", "ACTIVITYID", "ACTIVITYNAME", "PRODUCTID", "PRODUCTNAME", "CODE", "CATEGORYID", "CATEGORYNAME", "BUDGETEXPENSETYPENAME", "EXPENSETYPEID", "EXPENSETYPENAME", "PROPOSEAMOUNT", "AMENDAMOUNT", "REQUESTAMOUNT", "BUDGETEXPENSETYPEID", "CREATEON") AS
  WITH BASE AS (
  SELECT DISTINCT
    a.BUDGETYEAR,
    a.BUDGET_PLAN_ID AS BUDGETPLANID,
    a.BUDGET_PLAN_NAME AS BUDGETPLANNAME,
    a.PRODUCTID,
    a.ACTIVITYCODEID,
    CC.CODE,
    a.CATEGORY_ID AS CATEGORYID,
    a.CATEGORY_NAME,
    NVL(a.TOTALALLOCATEAMOUNT, 0) AS TOTALALLOCATEAMOUNT,
    NVL(a.TOTALADJUSTEDAMOUNT, 0) AS TOTALADJUSTEDAMOUNT,
    NVL(a.TOTALREQUESTSUMADJUSTAMOUNT, 0) AS TOTALREQUESTAMOUNT,
    a.PRODUCTNAME,
    a.ACTIVITYNAME
  FROM OAGWBG_V_BUDGETALLOCATEITEM a
  LEFT JOIN OAGWBG_BUDGETGOVERNMENT BG
  	ON a.BUDGET_GOVERNMENT_ID = BG.ID
  LEFT JOIN OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CC
  	ON CC.ID = BG.CATEGORYID
  WHERE BG.BUDGETSTATUS != 'A'
),

REQ AS (
  SELECT
    b.BUDGETYEAR,
    b.BUDGETPLANID,
    b.PRODUCTID,
    b.ACTIVITYCODEID,
    MIN(b.CODE) AS CODE,
    b.CATEGORYID,
    b.CATEGORY_NAME,
    SUM(b.TOTALREQUESTAMOUNT) AS REQUESTAMOUNT
  FROM BASE b
  GROUP BY
    b.BUDGETYEAR,
    b.BUDGETPLANID,
    b.PRODUCTID,
    b.ACTIVITYCODEID,
    b.CATEGORYID,
    b.CATEGORY_NAME
),

PA AS (
  SELECT
    b.BUDGETYEAR,
    b.BUDGETPLANID,
    b.PRODUCTID,
    b.ACTIVITYCODEID,
    b.CATEGORYID,
    b.CATEGORY_NAME,
    SUM(b.TOTALALLOCATEAMOUNT) AS PROPOSEAMOUNT,
    SUM(b.TOTALADJUSTEDAMOUNT) AS AMENDAMOUNT
  FROM BASE b
  GROUP BY
    b.BUDGETYEAR,
    b.BUDGETPLANID,
    b.PRODUCTID,
    b.ACTIVITYCODEID,
    b.CATEGORYID,
    b.CATEGORY_NAME
),

ACT_DIM AS (
  SELECT ACTIVITYCODEID, MAX(ACTIVITYNAME) AS ACTIVITYNAME
  FROM BASE
  GROUP BY ACTIVITYCODEID
),

PROD_DIM AS (
  SELECT PRODUCTID, MAX(PRODUCTNAME) AS PRODUCTNAME
  FROM BASE
  GROUP BY PRODUCTID
),

PLAN_DIM AS (
  SELECT BUDGETPLANID, MAX(BUDGETPLANNAME) AS BUDGETPLANNAME
  FROM BASE
  GROUP BY BUDGETPLANID
),

GOV_NAME AS (
  SELECT
    v.BUDGETYEAR,
    v.BUDGETPLANID,
    v.PRODUCTID,
    v.ACTIVITYCODEID,
    v.CATEGORYID,
    v.EXPENSETYPEID,
    MAX(v.EXPENSETYPENAME) AS EXPENSETYPENAME,
    MAX(v.BUDGETEXPENSETYPENAME) AS BUDGETEXPENSETYPENAME,
    v.BUDGET_EXPENSE_TYPE_ID,
    MIN(v.CREATEON) AS CREATEON
  FROM OAGWBG.OAGWBG_V_BUDGETGOVERNMENT v
  GROUP BY
    v.BUDGETYEAR,
    v.BUDGETPLANID,
    v.PRODUCTID,
    v.ACTIVITYCODEID,
    v.CATEGORYID,
    v.EXPENSETYPEID,
    v.BUDGET_EXPENSE_TYPE_ID
)

SELECT
  R.BUDGETYEAR AS BUDGETYEAR,
  R.BUDGETPLANID AS BUDGETPLANID,
  CASE
    WHEN R.BUDGETPLANID = 3533 THEN '30000'
    WHEN R.BUDGETPLANID = 3571 THEN '00000'
    WHEN R.BUDGETPLANID = 2144 THEN '10000'
    WHEN R.BUDGETPLANID = 2181 THEN '20000'
    ELSE TO_CHAR(R.BUDGETPLANID)
  END AS BUDGETPLANIDDISPLAY,
  PL.BUDGETPLANNAME AS BUDGETPLANNAME,
  R.ACTIVITYCODEID AS ACTIVITYID,
  ACT.ACTIVITYNAME AS ACTIVITYNAME,
  R.PRODUCTID AS PRODUCTID,
  PRD.PRODUCTNAME AS PRODUCTNAME,
  R.CODE AS CODE,
  R.CATEGORYID AS CATEGORYID,
  R.CATEGORY_NAME AS CATEGORYNAME,
  G.BUDGETEXPENSETYPENAME AS BUDGETEXPENSETYPENAME,
  G.EXPENSETYPEID AS EXPENSETYPEID,
  G.EXPENSETYPENAME AS EXPENSETYPENAME,
  NVL(PA.PROPOSEAMOUNT, 0) AS PROPOSEAMOUNT,
  NVL(PA.AMENDAMOUNT, 0) AS AMENDAMOUNT,
  NVL(R.REQUESTAMOUNT, 0) AS REQUESTAMOUNT,
  G.BUDGET_EXPENSE_TYPE_ID AS BUDGETEXPENSETYPEID,
  G.CREATEON AS CREATEON
FROM REQ R
LEFT JOIN PA
  ON PA.BUDGETYEAR    = R.BUDGETYEAR
 AND PA.BUDGETPLANID  = R.BUDGETPLANID
 AND TO_CHAR(PA.PRODUCTID)      = TO_CHAR(R.PRODUCTID)
 AND TO_CHAR(PA.ACTIVITYCODEID) = TO_CHAR(R.ACTIVITYCODEID)
 AND PA.CATEGORYID    = R.CATEGORYID

LEFT JOIN ACT_DIM ACT
  ON TO_CHAR(ACT.ACTIVITYCODEID) = TO_CHAR(R.ACTIVITYCODEID)

LEFT JOIN PROD_DIM PRD
  ON TO_CHAR(PRD.PRODUCTID) = TO_CHAR(R.PRODUCTID)

LEFT JOIN PLAN_DIM PL
  ON PL.BUDGETPLANID = R.BUDGETPLANID

LEFT JOIN GOV_NAME G
  ON G.BUDGETYEAR    = R.BUDGETYEAR
 AND G.BUDGETPLANID  = R.BUDGETPLANID
 AND TO_CHAR(G.PRODUCTID)      = TO_CHAR(R.PRODUCTID)
 AND TO_CHAR(G.ACTIVITYCODEID) = TO_CHAR(R.ACTIVITYCODEID)
 AND G.CATEGORYID    = R.CATEGORYID

ORDER BY
  R.BUDGETYEAR,
  PL.BUDGETPLANNAME,
  PRD.PRODUCTNAME,
  ACT.ACTIVITYNAME,
  G.BUDGETEXPENSETYPENAME,
  R.CATEGORY_NAME,
  G.CATEGORYID
/
