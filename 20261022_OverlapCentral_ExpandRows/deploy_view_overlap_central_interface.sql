-- เพิ่มรายการขยายเวลา (รอบ มี.ค. + ก.ย.) ของกันเงินส่วนกลาง ต่อท้ายด้วย UNION ALL — ส่วนเดิมไม่แตะ
-- ฐาน = DDL สดจาก PREPROD วันที่ 2026-10-22 | เปิดไฟล์เป็น UTF-8 (มีข้อความไทย)

CREATE OR REPLACE FORCE EDITIONABLE VIEW "OAGWBG"."OAGWBG_V_BUDGET_OVERLAPYEAR_CENTRAL_DETAIL_INTERFACE" ("WEB_BATCH_NO", "USER_JE_SOURCE_NAME", "REFERENCE4", "REFERENCE5", "LEDGER_ID", "USER_JE_CATEGORY_NAME", "TRANSFER_DATE", "DEFAULT_EFFECTIVE_DATE", "ACTUAL_FLAG", "BUDGET_ENCUMBRANCE_NAME", "CURRENCY_CODE", "ATTRIBUTE3", "ATTRIBUTE4", "LINE_NUMBER", "SEGMENT1", "SEGMENT2", "SEGMENT3", "SEGMENT4", "SEGMENT5", "SEGMENT6", "SEGMENT7", "SEGMENT8", "SEGMENT9", "SEGMENT10", "SEGMENT11", "SEGMENT12", "SEGMENT13", "ENTERED_DR", "ACCOUNTED_DR", "ENTERED_CR", "ACCOUNTED_CR", "REFERENCE1", "CREATED_BY", "LAST_UPDATED_BY", "CREATION_DATE", "LAST_UPDATE_DATE", "REFERENCE10", "ENCUMBRANCE_TYPE", "TRANSFERNO", "RECEIPIENT_ACCOUNT", "SENDER_ACCOUNT", "TYPE", "TRANSFERTYPE") AS 
  WITH BASE AS (
  SELECT 
    BRSC.*,
    BRS.BUDGETYEAR AS BRS_BUDGETYEAR,
    BRS.DEPARTMENTID,
    BRS.COSTCENTERID,
    BRS.BUDGETSOURCEID,
    BRS.TRANSFERNO,
    EAR.BUDGETTYPEID,
    EAR.ACCOUNTNO,
    EAR.SUBACCOUNTNO, 
    CC.NAME AS CATEGORY_NAME,
    SC.CONFIG_VALUE AS LEDGER_ID,
    BCC_GIVER.CASH_ACC AS GIVER,
    BCC_RECEIVER.CASH_ACC AS RECEIVER,
    BRS.TRANSFERDATE
  FROM OAGWBG_BUDGETRESERVED_CATEGORY BRSC
  LEFT JOIN OAGWBG_BUDGETRESERVED BRS
    ON BRSC.BUDGETRESERVEDID = BRS.ID
  LEFT JOIN (
	    SELECT *
	    FROM (
	        SELECT
	            EAR.*,
	            ROW_NUMBER() OVER (
	                PARTITION BY CATEGORYID
	                ORDER BY
	                    CASE
	                        WHEN BUDGETYEAR IS NOT NULL
	                         AND PRODUCTID IS NOT NULL
	                         AND ACTIVITYCODEID IS NOT NULL
	                        THEN 1
	                        ELSE 2
	                    END
	            ) RN
	        FROM OAGWBG_V_EXT_OAGPO_EXPENSE_ACCOUNT_RULE_V EAR
	    )
	    WHERE RN = 1
	) EAR
	  ON BRSC.CATEGORYID = EAR.CATEGORYID
  LEFT JOIN OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CC
    ON CC.ID = BRSC.CATEGORYID
  LEFT JOIN OAGWBG_BUDGETRESERVED_BANKACCOUNT BRB
          ON BRB.RESERVEDID = BRS.ID 
  LEFT JOIN OAGWBG_V_EXT_OAGCE_BANK_ACCOUNT_V BCC_GIVER
          ON BCC_GIVER.BANK_ACCOUNT_ID = BRB.BANKACCOUNTGIVER 
  LEFT JOIN OAGWBG_V_EXT_OAGCE_BANK_ACCOUNT_V BCC_RECEIVER
          ON BCC_RECEIVER.BANK_ACCOUNT_ID = BRB.BANKACCOUNTRECEIVER  
  LEFT JOIN OAGWBG_SYSTEMCONFIG SC
          ON SC.CONFIG_KEY = 'Ledger'
  WHERE BRS.ROUNDINTERFACE IS NOT NULL AND BRS.BUDGETRESERVEDREGION = 'C' 
),
TYPE_MAP AS (
  SELECT 'ENC' AS DOC_TYPE, 'E' AS ACTUAL_FLAG, 'C' AS DRCR_FLAG FROM DUAL
  UNION ALL
  SELECT 'BG', 'B', 'D' FROM DUAL
)
,
-- รายการขยายเวลาของกันเงินส่วนกลาง (2026-10-22, เคส 681203)
-- ทั้งรอบ มี.ค. (OVERLAPROUND คี่) และรอบ ก.ย. (OVERLAPROUND คู่) แสดงหลังยืนยันรอบนั้นแล้ว (ROUNDINTERFACE > OVERLAPROUND)
-- ยอด = USAGEAMOUNT (ยอดอนุมัติขยาย), ชุดบัญชีตาม ACCOUNTCODE ของรายการ, SEGMENT4 = 400 ทั้งขา E/B
EXP_BASE AS (
  SELECT
    I.ID, I.BUDGETREVERSEDID, I.OVERLAPROUND, I.OVERLAPYEAR, I.USAGEAMOUNT, I.DESCRIPTION,
    I.CREATEBY, I.UPDATEBY, I.CREATEON, I.UPDATEON,
    BRS.DEPARTMENTID, BRS.TRANSFERNO,
    SC.CONFIG_VALUE AS LEDGER_ID,
    BCC_GIVER.CASH_ACC AS GIVER,
    BCC_RECEIVER.CASH_ACC AS RECEIVER,
    RBN0.BATCHNAME AS FIRST_BATCHNAME,
    REGEXP_SUBSTR(I.ACCOUNTCODE, '[^.]+', 1, 1)  AS S1,
    REGEXP_SUBSTR(I.ACCOUNTCODE, '[^.]+', 1, 2)  AS S2,
    REGEXP_SUBSTR(I.ACCOUNTCODE, '[^.]+', 1, 3)  AS S3,
    REGEXP_SUBSTR(I.ACCOUNTCODE, '[^.]+', 1, 5)  AS S5,
    REGEXP_SUBSTR(I.ACCOUNTCODE, '[^.]+', 1, 6)  AS S6,
    REGEXP_SUBSTR(I.ACCOUNTCODE, '[^.]+', 1, 7)  AS S7,
    REGEXP_SUBSTR(I.ACCOUNTCODE, '[^.]+', 1, 8)  AS S8,
    REGEXP_SUBSTR(I.ACCOUNTCODE, '[^.]+', 1, 9)  AS S9,
    REGEXP_SUBSTR(I.ACCOUNTCODE, '[^.]+', 1, 10) AS S10,
    REGEXP_SUBSTR(I.ACCOUNTCODE, '[^.]+', 1, 11) AS S11,
    REGEXP_SUBSTR(I.ACCOUNTCODE, '[^.]+', 1, 12) AS S12,
    REGEXP_SUBSTR(I.ACCOUNTCODE, '[^.]+', 1, 13) AS S13
  FROM OAGWBG_BUDGETRESERVEDITEM I
  JOIN OAGWBG_BUDGETRESERVED BRS
    ON BRS.ID = I.BUDGETREVERSEDID
  LEFT JOIN OAGWBG_BUDGETRESERVED_BANKACCOUNT BRB
    ON BRB.RESERVEDID = BRS.ID
  LEFT JOIN OAGWBG_V_EXT_OAGCE_BANK_ACCOUNT_V BCC_GIVER
    ON BCC_GIVER.BANK_ACCOUNT_ID = BRB.BANKACCOUNTGIVER
  LEFT JOIN OAGWBG_V_EXT_OAGCE_BANK_ACCOUNT_V BCC_RECEIVER
    ON BCC_RECEIVER.BANK_ACCOUNT_ID = BRB.BANKACCOUNTRECEIVER
  LEFT JOIN OAGWBG_SYSTEMCONFIG SC
    ON SC.CONFIG_KEY = 'Ledger'
  LEFT JOIN (
    SELECT ROUNDNO, BATCHNAME
    FROM (
      SELECT R.ROUNDNO, R.BATCHNAME,
             ROW_NUMBER() OVER (PARTITION BY R.ROUNDNO, R.INTERFACETYPE ORDER BY R.RUNNING DESC, R.ID DESC) RN
      FROM OAGWBG_RECEIVE_BATCH_NO R
      WHERE R.INTERFACETYPE = 'C'
    )
    WHERE RN = 1
  ) RBN0
    ON RBN0.ROUNDNO = BRS.TRANSFERNO
  WHERE BRS.BUDGETRESERVEDREGION = 'C'
    AND BRS.ROUNDINTERFACE > I.OVERLAPROUND
    AND I.BUDGETRESERVEDTYPE IN ('EXPAND_PO', 'EXPAND_PR')
    AND I.STATUSID = 90102
    AND NVL(I.USAGEAMOUNT, 0) > 0
),
EXP_ROWS AS (
  SELECT
    E.*,
    T.DOC_TYPE,
    T.ACTUAL_FLAG,
    -- มี.ค. = 31 มี.ค. ทั้งสองขา / ก.ย. = ขา E 30 ก.ย., ขา B 1 ต.ค.
    CASE
      WHEN MOD(E.OVERLAPROUND, 2) = 1 THEN TO_DATE((E.OVERLAPYEAR - 543) || '0331', 'YYYYMMDD')
      WHEN T.DOC_TYPE = 'ENC'         THEN TO_DATE((E.OVERLAPYEAR - 543) || '0930', 'YYYYMMDD')
      ELSE                                 TO_DATE((E.OVERLAPYEAR - 543) || '1001', 'YYYYMMDD')
    END AS EFF_DATE
  FROM EXP_BASE E
  CROSS JOIN TYPE_MAP T
),
EXP_FINAL AS (
  SELECT
    X.*,
    -- ชื่อ batch = CARRY_FORWARD_{ปีที่ขยาย}_{เลขท้าย batch รอบกันเงิน}_{วันที่ของแถว}
    'CARRY_FORWARD_' || X.OVERLAPYEAR ||
      NVL(SUBSTR(X.FIRST_BATCHNAME, INSTR(X.FIRST_BATCHNAME, '_', -1)), '_' || X.TRANSFERNO) ||
      '_' || TO_CHAR(X.EFF_DATE, 'YYYYMMDD') AS BATCH_NAME
  FROM EXP_ROWS X
)

SELECT
  NVL(RBN.BATCHNAME,
  CASE 
    WHEN T.DOC_TYPE = 'ENC' THEN
      'ENC_CARRY_FORWARD_' || B.BUDGETYEAR || '_' ||
      TO_CHAR(NVL(B.TRANSFERDATE, SYSDATE),'YYMMDDHH24MISS')
    ELSE
      'BG_CARRY_FORWARD_' || B.BUDGETYEAR || '_' ||
      TO_CHAR(NVL(B.TRANSFERDATE, SYSDATE),'YYMMDDHH24MISS')
  END ) AS WEB_BATCH_NO,

  'Web Budget' AS USER_JE_SOURCE_NAME,
  'เงินกันเหลื่อมปี ' || B.BUDGETYEAR || '-' || B.DEPARTMENTID || ' เลขที่เงินกัน ' || B.TRANSFERNO AS REFERENCE4,
  'เงินกันเหลื่อมปี ' || B.BUDGETYEAR || '-' || B.DEPARTMENTID || ' เลขที่เงินกัน ' || B.TRANSFERNO AS REFERENCE5,
  B.LEDGER_ID,

  'Budget - ' || TO_CHAR(UNISTR('\0E40\0E07\0E34\0E19\0E01\0E31\0E19')) AS USER_JE_CATEGORY_NAME,
  
  TO_CHAR(B.TRANSFERDATE,'YYYY-MM-DD') AS TRANSFER_DATE,

  CASE 
    WHEN T.DOC_TYPE = 'ENC' THEN (B.BUDGETYEAR - 543) || '-SEP-30'
    ELSE (B.BUDGETYEAR - 543) || '-OCT-01'
  END AS DEFAULT_EFFECTIVE_DATE,

  T.ACTUAL_FLAG,

  CASE 
    WHEN T.DOC_TYPE = 'BG' THEN 'OAG_BG_FINAL'
    ELSE ''
  END AS BUDGET_ENCUMBRANCE_NAME,

  'THB' AS CURRENCY_CODE,
  '' AS ATTRIBUTE3,
  B.TRANSFERNO AS ATTRIBUTE4,
  ROW_NUMBER() OVER (
  PARTITION BY B.BUDGETRESERVEDID, T.DOC_TYPE
  ORDER BY 
    B.CATEGORYID,
    B.BUDGETPLANID
  ) AS LINE_NUMBER,

  B.DEPARTMENTID AS SEGMENT1,
  B.COSTCENTERID AS SEGMENT2,
  NVL(SUBSTR(B.TRANSFERNO, 1, 2), MOD(B.BUDGETYEAR, 100)) AS SEGMENT3,

  CASE 
    WHEN T.DOC_TYPE = 'BG' THEN '400'
    ELSE B.BUDGETSOURCEID
  END AS SEGMENT4,

--  LPAD(
--  NVL(
--    TO_CHAR(
--      CASE 
--        WHEN B.BUDGETPLANID = '90000' THEN '0'
--        ELSE TO_CHAR(B.BUDGETPLANID)
--      END
--    ),
--    '0')
--     ,5,'0') AS SEGMENT5,
  B.BUDGETPLANID AS SEGMENT5,
  LPAD(NVL(TO_CHAR(B.PRODUCTID),'0'),5,'0') AS SEGMENT6,
  B.ACTIVITYID AS SEGMENT7,
  B.BUDGETTYPEID AS SEGMENT8,
  NVL(B.BUDGETCODEID,'00000000000000000000') AS SEGMENT9,
  B.ACCOUNTNO AS SEGMENT10,
  B.SUBACCOUNTNO AS SEGMENT11,
  '00' AS SEGMENT12,
  '000' AS SEGMENT13,

	CASE 
	    WHEN T.DOC_TYPE = 'BG' THEN B.TOTALRESERVEDAMOUNT
	    ELSE NULL
	END AS ENTERED_DR,
	
	CASE 
	    WHEN T.DOC_TYPE = 'BG' THEN B.TOTALRESERVEDAMOUNT
	    ELSE NULL
	END AS ACCOUNTED_DR,
	
	CASE 
	    WHEN T.DOC_TYPE = 'ENC' THEN B.TOTALRESERVEDAMOUNT
	    ELSE NULL
	END AS ENTERED_CR,
	
	CASE 
	    WHEN T.DOC_TYPE = 'ENC' THEN B.TOTALRESERVEDAMOUNT
	    ELSE NULL
	END AS ACCOUNTED_CR,

  NVL(RBN.BATCHNAME,
  CASE 
    WHEN T.DOC_TYPE = 'ENC' THEN
      'ENC_CARRY_FORWARD_' || B.BUDGETYEAR || '_' ||
      TO_CHAR(NVL(B.TRANSFERDATE, SYSDATE),'YYMMDDHH24MISS')
    ELSE
      'BG_CARRY_FORWARD_' || B.BUDGETYEAR || '_' ||
      TO_CHAR(NVL(B.TRANSFERDATE, SYSDATE),'YYMMDDHH24MISS')
  END ) AS REFERENCE1,

  B.CREATEBY AS CREATED_BY,
  B.UPDATEBY AS LAST_UPDATED_BY,
  B.CREATEON AS CREATION_DATE,
  B.UPDATEON AS LAST_UPDATE_DATE,
  B.CATEGORY_NAME AS REFERENCE10,

  CASE WHEN T.DOC_TYPE = 'ENC' THEN 'Web Encumbrance' ELSE '' END AS ENCUMBRANCE_TYPE,
  B.TRANSFERNO, 
  CASE WHEN T.DOC_TYPE = 'ENC' THEN NULL ELSE B.RECEIVER END AS RECEIPIENT_ACCOUNT,
  CASE WHEN T.DOC_TYPE = 'ENC' THEN B.GIVER ELSE NULL END AS SENDER_ACCOUNT,

  CASE WHEN T.DOC_TYPE = 'ENC' THEN 'O' ELSE 'I' END AS TYPE,
  'CARRYFWD' AS TRANSFERTYPE

FROM BASE B
CROSS JOIN TYPE_MAP T
LEFT JOIN (
    SELECT *
    FROM (
        SELECT RBN.*,
               ROW_NUMBER() OVER (
                   PARTITION BY ROUNDNO, INTERFACETYPE
                   ORDER BY RUNNING DESC,
                            ID DESC
               ) RN
        FROM OAGWBG_RECEIVE_BATCH_NO RBN
    )
    WHERE RN = 1
) RBN
    ON RBN.ROUNDNO = B.TRANSFERNO
   AND RBN.INTERFACETYPE = 'C'
UNION ALL

SELECT
  F.BATCH_NAME AS WEB_BATCH_NO,
  'Web Budget' AS USER_JE_SOURCE_NAME,
  'เงินกันเหลื่อมปี ' || F.OVERLAPYEAR || '-' || F.DEPARTMENTID || ' เลขที่เงินกัน ' || F.TRANSFERNO AS REFERENCE4,
  'เงินกันเหลื่อมปี ' || F.OVERLAPYEAR || '-' || F.DEPARTMENTID || ' เลขที่เงินกัน ' || F.TRANSFERNO AS REFERENCE5,
  F.LEDGER_ID,
  'Budget - ' || TO_CHAR(UNISTR('\0E40\0E07\0E34\0E19\0E01\0E31\0E19')) AS USER_JE_CATEGORY_NAME,
  TO_CHAR(F.EFF_DATE, 'YYYY-MM-DD') AS TRANSFER_DATE,
  TO_CHAR(F.EFF_DATE, 'YYYY-MON-DD', 'NLS_DATE_LANGUAGE=ENGLISH') AS DEFAULT_EFFECTIVE_DATE,
  F.ACTUAL_FLAG,
  CASE WHEN F.DOC_TYPE = 'BG' THEN 'OAG_BG_FINAL' ELSE '' END AS BUDGET_ENCUMBRANCE_NAME,
  'THB' AS CURRENCY_CODE,
  '' AS ATTRIBUTE3,
  F.TRANSFERNO AS ATTRIBUTE4,
  ROW_NUMBER() OVER (
    PARTITION BY F.BUDGETREVERSEDID, F.OVERLAPROUND, F.DOC_TYPE
    ORDER BY F.ID
  ) AS LINE_NUMBER,
  F.S1 AS SEGMENT1,
  F.S2 AS SEGMENT2,
  F.S3 AS SEGMENT3,
  '400' AS SEGMENT4,
  F.S5 AS SEGMENT5,
  F.S6 AS SEGMENT6,
  F.S7 AS SEGMENT7,
  F.S8 AS SEGMENT8,
  NVL(F.S9, '00000000000000000000') AS SEGMENT9,
  F.S10 AS SEGMENT10,
  F.S11 AS SEGMENT11,
  NVL(F.S12, '00') AS SEGMENT12,
  NVL(F.S13, '000') AS SEGMENT13,
  CASE WHEN F.DOC_TYPE = 'BG'  THEN F.USAGEAMOUNT END AS ENTERED_DR,
  CASE WHEN F.DOC_TYPE = 'BG'  THEN F.USAGEAMOUNT END AS ACCOUNTED_DR,
  CASE WHEN F.DOC_TYPE = 'ENC' THEN F.USAGEAMOUNT END AS ENTERED_CR,
  CASE WHEN F.DOC_TYPE = 'ENC' THEN F.USAGEAMOUNT END AS ACCOUNTED_CR,
  F.BATCH_NAME AS REFERENCE1,
  F.CREATEBY AS CREATED_BY,
  F.UPDATEBY AS LAST_UPDATED_BY,
  F.CREATEON AS CREATION_DATE,
  F.UPDATEON AS LAST_UPDATE_DATE,
  F.DESCRIPTION AS REFERENCE10,
  CASE WHEN F.DOC_TYPE = 'ENC' THEN 'Web Encumbrance' ELSE '' END AS ENCUMBRANCE_TYPE,
  F.TRANSFERNO,
  CASE WHEN F.DOC_TYPE = 'ENC' THEN NULL ELSE F.RECEIVER END AS RECEIPIENT_ACCOUNT,
  CASE WHEN F.DOC_TYPE = 'ENC' THEN F.GIVER ELSE NULL END AS SENDER_ACCOUNT,
  CASE WHEN F.DOC_TYPE = 'ENC' THEN 'O' ELSE 'I' END AS TYPE,
  'CARRYFWD' AS TRANSFERTYPE
FROM EXP_FINAL F

;
