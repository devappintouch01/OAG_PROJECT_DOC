-- QA: แถวในรายงาน
SELECT R.BUDGETPLANIDDISPLAY AS PLANID, R.PRODUCTID, R.ACTIVITYID, SUBSTR(R.ACTIVITYNAME, 1, 30) AS ACTIVITYNAME,
       R.CATEGORYID, R.CODE, R.REQUESTAMOUNT, R.PROPOSEAMOUNT, R.AMENDAMOUNT
FROM   OAGWBG.OAGWBG_R_BUDGETALLOCATE R
WHERE  R.BUDGETYEAR = 2570
AND    R.CODE IN ('EXP.200.211001.0000000008', 'EXP.200.211001.0000000009', 'EXP.200.211001.0000000010')
ORDER  BY R.CODE, R.PRODUCTID, R.ACTIVITYID;

-- QB: แถวใน view ที่หน้าจอใช้ (ครบทุกคอลัมน์ยอด)
SELECT V.CODE, V.BUDGET_PLAN_ID, V.PRODUCTID, V.ACTIVITYCODEID, V.BUDGET_TYPE_ID,
       V.BUDGETGOVERNMENTTYPE AS GT, V.BUDGETREQUESTID, V.BUDGET_GOVERNMENT_ID, V.BUDGETSTATUS,
       V.TOTALREQUESTAMOUNT, V.KEPTCENTRAL, V.TOTALREQUESTSIMMARYAMOUNT, V.TOTALREQUESTADJUSTAMOUNT,
       V.TOTALREQUESTSUMADJUSTAMOUNT, V.ALLOCATEID, V.TOTALALLOCATEAMOUNT, V.ADJUSTEDID, V.TOTALADJUSTEDAMOUNT
FROM   OAGWBG.OAGWBG_V_BUDGETALLOCATEITEM V
WHERE  V.BUDGETYEAR = 2570 AND V.BUDGETFORMTYPEID = 1
AND    V.CODE IN ('EXP.200.211001.0000000008', 'EXP.200.211001.0000000009', 'EXP.200.211001.0000000010')
ORDER  BY V.CODE, V.PRODUCTID, V.ACTIVITYCODEID, V.BUDGET_GOVERNMENT_ID;

-- QC: record จริงใน BUDGETGOVERNMENT (คำขอ / type 4 กันส่วนกลาง / type 5-6-8)
SELECT CC.CODE, BG.ID, BG.BUDGETGOVERNMENTTYPE AS T, BG.BUDGETREQUESTID, BG.PRODUCTID, BG.ACTIVITYCODEID,
       BG.BUDGETPLANID, BG.BUDGETEXPENSETYPEID, BG.BUDGETSTATUS,
       BG.TOTALREQUESTAMOUNT, BG.KEPTCENTRAL, BG.REF_BUDGETGOVERNMENTID,
       BG.TOTALALLOCATEAMOUNT, BG.TOTALADJUSTEDAMOUNT, BG.TOTALREQUESTADJUSTAMOUNT,
       SUBSTR(BG.BUDGETDETAIL, 1, 40) AS DETAIL
FROM   OAGWBG.OAGWBG_BUDGETGOVERNMENT BG
JOIN   OAGWBG.OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CC ON CC.ID = BG.CATEGORYID
WHERE  BG.BUDGETYEAR = 2570 AND BG.BUDGETFORMTYPEID = 1
AND    CC.CODE IN ('EXP.200.211001.0000000008', 'EXP.200.211001.0000000009', 'EXP.200.211001.0000000010')
ORDER  BY CC.CODE, BG.ACTIVITYCODEID, BG.BUDGETGOVERNMENTTYPE NULLS FIRST, BG.ID;
