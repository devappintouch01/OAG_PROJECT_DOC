--   BUDGETDETAIL = 'รายการจัดสรร พรบ', ยอดทุกช่องเป็น 0/ว่าง, แผนรายเดือนไม่มียอด


-- ---------- STEP 1: ดูแถวเป้าหมาย — จดจำนวนไว้ (= N) ----------
SELECT BG.ID, BG.BUDGETYEAR, BG.CATEGORYID, CC.NAME AS CATEGORYNAME, BG.BUDGETPLANID, BG.PRODUCTID, BG.ACTIVITYCODEID,
       BG.BUDGETSTATUS, BG.BUDGETDETAIL, BG.CREATEON, BG.CREATEBY
FROM   OAGWBG.OAGWBG_BUDGETGOVERNMENT BG
JOIN   OAGWBG.OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CC ON CC.ID = BG.CATEGORYID
WHERE  CC.DUMMY_FLAG = 'YES'
AND    BG.BUDGETREQUESTID = 0
AND    BG.BUDGETGOVERNMENTTYPE IS NULL
AND    BG.BUDGETFORMTYPEID = 1
AND    BG.BUDGETDETAIL = 'รายการจัดสรร พรบ'
AND    NVL(BG.TOTALREQUESTAMOUNT, 0) = 0
AND    NVL(BG.TOTALALLOCATEAMOUNT, 0) = 0
AND    NVL(BG.TOTALADJUSTEDAMOUNT, 0) = 0
AND    NVL(BG.TOTALREQUESTADJUSTAMOUNT, 0) = 0
AND    NVL(BG.KEPTCENTRAL, 0) = 0
AND    NOT EXISTS (SELECT 1 FROM OAGWBG.OAGWBG_BUDGETDISBURSEMENTPLANITEM D
                   WHERE D.BUDGETGOVERNMENTID = BG.ID
                   AND  (NVL(D.PLANAMOUNT, 0) <> 0 OR NVL(D.ALLOCATEAMOUNT, 0) <> 0))
ORDER  BY BG.BUDGETYEAR, BG.ID;
-- => ถ้าได้ 0 แถว: ไม่มีอะไรต้องลบ จบที่นี่
-- => PREPROD 2026-10-01 ได้ 1 แถว (73725 | 2572 | 2191 ค่าตอบแทน (อื่นๆ โปรดระบุ...))


-- ---------- STEP 1.1: ดูแถวที่ "เกือบเข้าเงื่อนไข" แต่ถูกกันไว้ (มียอด) — ไม่ลบ แค่ดูไว้ ----------
SELECT BG.ID, BG.BUDGETYEAR, BG.CATEGORYID, BG.BUDGETSTATUS,
       BG.TOTALREQUESTAMOUNT, BG.TOTALALLOCATEAMOUNT, BG.TOTALADJUSTEDAMOUNT, BG.TOTALREQUESTADJUSTAMOUNT, BG.KEPTCENTRAL,
       (SELECT SUM(NVL(D.PLANAMOUNT, 0)) FROM OAGWBG.OAGWBG_BUDGETDISBURSEMENTPLANITEM D WHERE D.BUDGETGOVERNMENTID = BG.ID) AS PLANAMT
FROM   OAGWBG.OAGWBG_BUDGETGOVERNMENT BG
JOIN   OAGWBG.OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CC ON CC.ID = BG.CATEGORYID
WHERE  CC.DUMMY_FLAG = 'YES'
AND    BG.BUDGETREQUESTID = 0
AND    BG.BUDGETGOVERNMENTTYPE IS NULL
AND    BG.BUDGETFORMTYPEID = 1
ORDER  BY BG.BUDGETYEAR, BG.ID;
-- => แถวที่อยู่ที่นี่แต่ไม่อยู่ใน STEP 1 = มียอด → ไม่ใช่ขยะ ห้ามลบ (แจ้งทีมก่อน)


-- ---------- STEP 2: ตรวจความปลอดภัย — ทุกตัวต้องได้ 0 (ถ้าไม่ใช่ 0 หยุด อย่าลบ) ----------
-- 2.1 FK ที่ชี้มาที่ 2 ตาราง
SELECT COUNT(*) AS FK_COUNT
FROM   ALL_CONSTRAINTS C
JOIN   ALL_CONSTRAINTS P ON P.OWNER = C.R_OWNER AND P.CONSTRAINT_NAME = C.R_CONSTRAINT_NAME
WHERE  C.OWNER = 'OAGWBG' AND C.CONSTRAINT_TYPE = 'R'
AND    P.TABLE_NAME IN ('OAGWBG_BUDGETGOVERNMENT', 'OAGWBG_BUDGETDISBURSEMENTPLANITEM');

-- 2.2 ตารางอื่นที่อ้าง ID ของแถวเป้าหมาย (นอกจากแผนรายเดือน) — ใส่ ID จาก STEP 1 แทน <IDS> เช่น 73725, 73726
SELECT 'BUDGETGOVERNMENT.REF'             AS SRC, COUNT(*) AS CNT FROM OAGWBG.OAGWBG_BUDGETGOVERNMENT              WHERE REF_BUDGETGOVERNMENTID IN (<IDS>)
UNION ALL SELECT 'BUDGETCODEMORE_YEAR',          COUNT(*) FROM OAGWBG.OAGWBG_BUDGETCODEMORE_YEAR           WHERE BUDGETGOVERNMENTID IN (<IDS>)
UNION ALL SELECT 'BUDGETDISBURSEMENTESTIMATED',  COUNT(*) FROM OAGWBG.OAGWBG_BUDGETDISBURSEMENTESTIMATED   WHERE BUDGETGOVERNMENTID IN (<IDS>)
UNION ALL SELECT 'BUDGETGOVERNMENTASSETITEM',    COUNT(*) FROM OAGWBG.OAGWBG_BUDGETGOVERNMENTASSETITEM     WHERE BUDGETGOVERNMENTID IN (<IDS>)
UNION ALL SELECT 'BUDGETGOVERNMENTITEM',         COUNT(*) FROM OAGWBG.OAGWBG_BUDGETGOVERNMENTITEM          WHERE BUDGETGOVERNMENTID IN (<IDS>)
UNION ALL SELECT 'BUDGETRECEIVEPERIOD',          COUNT(*) FROM OAGWBG.OAGWBG_BUDGETRECEIVEPERIOD           WHERE BUDGETGOVERNMENTID IN (<IDS>)
UNION ALL SELECT 'BUDGETRECEIVEPERIODALLOCATION',COUNT(*) FROM OAGWBG.OAGWBG_BUDGETRECEIVEPERIODALLOCATION WHERE BUDGETGOVERNMENTID IN (<IDS>)
UNION ALL SELECT 'BUDGETRECEIVEPERIODCATEGORY',  COUNT(*) FROM OAGWBG.OAGWBG_BUDGETRECEIVEPERIODCATEGORY   WHERE BUDGETGOVERNMENTID IN (<IDS>)
UNION ALL SELECT 'BUDGETRECEIVEPERIODREQUEST',   COUNT(*) FROM OAGWBG.OAGWBG_BUDGETRECEIVEPERIODREQUEST    WHERE BUDGETGOVERNMENTID IN (<IDS>)
UNION ALL SELECT 'PROJECT',                      COUNT(*) FROM OAGWBG.OAGWBG_PROJECT                       WHERE BUDGETGOVERNMENTID IN (<IDS>)
UNION ALL SELECT 'PROJECTASSETITEM',             COUNT(*) FROM OAGWBG.OAGWBG_PROJECTASSETITEM              WHERE BUDGETGOVERNMENTID IN (<IDS>);
-- => ทุกแถว CNT = 0


-- ---------- STEP 3: backup ลงตาราง BK (DDL — auto commit) ----------
-- ถ้าตาราง BK มีอยู่แล้วจากการรันครั้งก่อน: ตรวจว่าไม่ต้องใช้ rollback แล้ว ค่อย DROP ก่อนสร้างใหม่
CREATE TABLE OAGWBG.OAGWBG_BK1001_DUMMY_BG AS
SELECT BG.*
FROM   OAGWBG.OAGWBG_BUDGETGOVERNMENT BG
JOIN   OAGWBG.OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CC ON CC.ID = BG.CATEGORYID
WHERE  CC.DUMMY_FLAG = 'YES'
AND    BG.BUDGETREQUESTID = 0
AND    BG.BUDGETGOVERNMENTTYPE IS NULL
AND    BG.BUDGETFORMTYPEID = 1
AND    BG.BUDGETDETAIL = 'รายการจัดสรร พรบ'
AND    NVL(BG.TOTALREQUESTAMOUNT, 0) = 0
AND    NVL(BG.TOTALALLOCATEAMOUNT, 0) = 0
AND    NVL(BG.TOTALADJUSTEDAMOUNT, 0) = 0
AND    NVL(BG.TOTALREQUESTADJUSTAMOUNT, 0) = 0
AND    NVL(BG.KEPTCENTRAL, 0) = 0
AND    NOT EXISTS (SELECT 1 FROM OAGWBG.OAGWBG_BUDGETDISBURSEMENTPLANITEM D
                   WHERE D.BUDGETGOVERNMENTID = BG.ID
                   AND  (NVL(D.PLANAMOUNT, 0) <> 0 OR NVL(D.ALLOCATEAMOUNT, 0) <> 0));

CREATE TABLE OAGWBG.OAGWBG_BK1001_DUMMY_DPI AS
SELECT D.*
FROM   OAGWBG.OAGWBG_BUDGETDISBURSEMENTPLANITEM D
WHERE  D.BUDGETGOVERNMENTID IN (SELECT ID FROM OAGWBG.OAGWBG_BK1001_DUMMY_BG);

-- 3.1 ตรวจ backup: BG_CNT ต้อง = N จาก STEP 1 / DPI_CNT ปกติ = N x 12 / DPI_AMT ต้อง = 0
SELECT (SELECT COUNT(*) FROM OAGWBG.OAGWBG_BK1001_DUMMY_BG)  AS BG_CNT,
       (SELECT COUNT(*) FROM OAGWBG.OAGWBG_BK1001_DUMMY_DPI) AS DPI_CNT,
       (SELECT SUM(NVL(PLANAMOUNT, 0)) + SUM(NVL(ALLOCATEAMOUNT, 0)) FROM OAGWBG.OAGWBG_BK1001_DUMMY_DPI) AS DPI_AMT
FROM   DUAL;


-- ---------- STEP 4: ลบ — ลบเฉพาะแถวที่อยู่ในตาราง BK ----------
DELETE FROM OAGWBG.OAGWBG_BUDGETDISBURSEMENTPLANITEM
WHERE  ID IN (SELECT ID FROM OAGWBG.OAGWBG_BK1001_DUMMY_DPI);
-- => ต้องเท่ากับ DPI_CNT

DELETE FROM OAGWBG.OAGWBG_BUDGETGOVERNMENT
WHERE  ID IN (SELECT ID FROM OAGWBG.OAGWBG_BK1001_DUMMY_BG)
AND    BUDGETREQUESTID = 0
AND    BUDGETGOVERNMENTTYPE IS NULL;
-- => ต้องเท่ากับ BG_CNT


-- ---------- STEP 5: ตรวจหลังลบ ก่อน COMMIT ----------
-- 5.1 ต้องได้ 0 ทั้งสองตัว
SELECT COUNT(*) AS REMAIN_BG  FROM OAGWBG.OAGWBG_BUDGETGOVERNMENT           WHERE ID IN (SELECT ID FROM OAGWBG.OAGWBG_BK1001_DUMMY_BG);
SELECT COUNT(*) AS REMAIN_DPI FROM OAGWBG.OAGWBG_BUDGETDISBURSEMENTPLANITEM WHERE ID IN (SELECT ID FROM OAGWBG.OAGWBG_BK1001_DUMMY_DPI);

-- 5.2 รัน STEP 1 ซ้ำ ต้องได้ 0 แถว

-- 5.3 หน้าจอ: ค่ากลางที่ถูกลบต้องไม่โผล่ใน view แล้ว (ต้องได้ 0)
SELECT COUNT(*) AS STILL_IN_VIEW
FROM   OAGWBG.OAGWBG_V_BUDGETALLOCATEITEM V
WHERE  V.BUDGET_GOVERNMENT_ID IN (SELECT ID FROM OAGWBG.OAGWBG_BK1001_DUMMY_BG);

