-- Q1: คำขอค่ากลางปี 2570 ที่มียอดรายคำขอ (REQ_*) — ยอดเหล่านี้คือส่วนที่หน้าจอเดิมไม่นับขึ้นชั้นบน
--     ต้องเห็น "โครงการจัดทำคู่มือการปฏิบัติงานของพนักงานอัยการ ..." เสนอจัดสรร 469,200
SELECT BG.ID, BG.CATEGORYID, CC.NAME AS CATEGORYNAME, BG.PRODUCTID, BG.ACTIVITYCODEID, BG.BUDGETSTATUS,
       BG.REQ_TOTALREQUESTADJUSTAMOUNT AS REQ_ADJUST, BG.REQ_TOTALALLOCATEAMOUNT AS REQ_ALLOC, BG.REQ_TOTALADJUSTEDAMOUNT AS REQ_ADJUSTED,
       SUBSTR(BG.BUDGETDETAIL, 1, 80) AS DETAIL
FROM   OAGWBG.OAGWBG_BUDGETGOVERNMENT BG
JOIN   OAGWBG.OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CC ON CC.ID = BG.CATEGORYID
WHERE  BG.BUDGETYEAR = 2570 AND BG.BUDGETFORMTYPEID = 1
AND    CC.DUMMY_FLAG = 'YES' AND NVL(BG.BUDGETREQUESTID, 0) <> 0
AND   (NVL(BG.REQ_TOTALALLOCATEAMOUNT, 0) <> 0 OR NVL(BG.REQ_TOTALADJUSTEDAMOUNT, 0) <> 0 OR NVL(BG.REQ_TOTALREQUESTADJUSTAMOUNT, 0) <> 0)
ORDER  BY BG.CATEGORYID, BG.PRODUCTID, BG.ACTIVITYCODEID, BG.ID;

-- Q2: รวมต่อ (Category ค่ากลาง, ผลผลิต, กิจกรรม) = ยอดที่ช่องเสนอจัดสรรชั้นงบรายจ่ายควรเพิ่มขึ้นหลังแก้
SELECT BG.CATEGORYID, CC.NAME AS CATEGORYNAME, BG.PRODUCTID, BG.ACTIVITYCODEID,
       COUNT(*) AS N_REQ,
       SUM(NVL(BG.REQ_TOTALALLOCATEAMOUNT, 0)) AS SUM_ALLOC,
       SUM(NVL(BG.REQ_TOTALADJUSTEDAMOUNT, 0)) AS SUM_ADJUSTED
FROM   OAGWBG.OAGWBG_BUDGETGOVERNMENT BG
JOIN   OAGWBG.OAGWBG_V_EXT_OAGINV_CATEGORY_CODES_V CC ON CC.ID = BG.CATEGORYID
WHERE  BG.BUDGETYEAR = 2570 AND BG.BUDGETFORMTYPEID = 1
AND    CC.DUMMY_FLAG = 'YES' AND NVL(BG.BUDGETREQUESTID, 0) <> 0
AND    BG.BUDGETSTATUS IN ('B', 'C')
GROUP  BY BG.CATEGORYID, CC.NAME, BG.PRODUCTID, BG.ACTIVITYCODEID
HAVING SUM(NVL(BG.REQ_TOTALALLOCATEAMOUNT, 0)) <> 0 OR SUM(NVL(BG.REQ_TOTALADJUSTEDAMOUNT, 0)) <> 0
ORDER  BY BG.CATEGORYID, BG.PRODUCTID, BG.ACTIVITYCODEID;
