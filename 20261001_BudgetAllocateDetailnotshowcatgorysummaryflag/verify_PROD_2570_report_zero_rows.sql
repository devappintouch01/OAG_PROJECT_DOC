-- แถวในรายงานมาจาก OAGWBG_V_BUDGETALLOCATEITEM ทุกแถว (ไม่กรองยอด 0 เหมือนหน้าจอ)

-- Q1: แถว 0 ทุกช่องในรายงานปี 2570 ทั้งหมด
SELECT R.BUDGETPLANIDDISPLAY AS PLANID, R.PRODUCTID, R.ACTIVITYID, SUBSTR(R.ACTIVITYNAME, 1, 40) AS ACTIVITYNAME,
       R.CATEGORYID, R.CODE, SUBSTR(R.CATEGORYNAME, 1, 60) AS CATEGORYNAME,
       R.REQUESTAMOUNT, R.PROPOSEAMOUNT, R.AMENDAMOUNT
FROM   OAGWBG.OAGWBG_R_BUDGETALLOCATE R
WHERE  R.BUDGETYEAR = 2570
AND    NVL(R.REQUESTAMOUNT, 0) = 0 AND NVL(R.PROPOSEAMOUNT, 0) = 0 AND NVL(R.AMENDAMOUNT, 0) = 0
ORDER  BY R.BUDGETPLANIDDISPLAY, R.PRODUCTID, R.ACTIVITYID, R.CODE;

-- Q2: แถวต้นทางใน V_BUDGETALLOCATEITEM ที่ทำให้เกิดแถว 0 — ดูว่าเป็นคำขอยอด 0 / กันส่วนกลางหมด / ค่ากลาง / รายการจัดสรร พรบ
SELECT V.BUDGET_PLAN_ID, V.PRODUCTID, V.ACTIVITYCODEID, V.CATEGORY_ID, V.CODE, SUBSTR(V.CATEGORY_NAME, 1, 50) AS CATEGORYNAME,
       V.BUDGETGOVERNMENTTYPE AS GT, V.BUDGETREQUESTID, V.BUDGET_GOVERNMENT_ID, V.BUDGETSTATUS,
       V.TOTALREQUESTAMOUNT, V.KEPTCENTRAL, V.TOTALREQUESTSIMMARYAMOUNT, V.TOTALREQUESTSUMADJUSTAMOUNT, V.TOTALALLOCATEAMOUNT
FROM   OAGWBG.OAGWBG_V_BUDGETALLOCATEITEM V
WHERE  V.BUDGETYEAR = 2570 AND V.BUDGETFORMTYPEID = 1
AND    NVL(V.TOTALREQUESTSUMADJUSTAMOUNT, 0) = 0 AND NVL(V.TOTALALLOCATEAMOUNT, 0) = 0 AND NVL(V.TOTALADJUSTEDAMOUNT, 0) = 0
ORDER  BY V.BUDGET_PLAN_ID, V.PRODUCTID, V.ACTIVITYCODEID, V.CODE;

-- Q3: record จริงใน BUDGETGOVERNMENT ของแถวจาก Q2 — ใส่ BUDGET_GOVERNMENT_ID จาก Q2 แทน <IDS>
SELECT BG.ID, BG.CATEGORYID, BG.BUDGETGOVERNMENTTYPE AS T, BG.BUDGETREQUESTID, BG.BUDGETSTATUS,
       BG.TOTALREQUESTAMOUNT, BG.KEPTCENTRAL, BG.DUMMY_CATEGORY, BG.CREATEON, BG.CREATEBY, BG.UPDATEON,
       SUBSTR(BG.BUDGETDETAIL, 1, 60) AS DETAIL
FROM   OAGWBG.OAGWBG_BUDGETGOVERNMENT BG
WHERE  BG.ID IN (<IDS>);
